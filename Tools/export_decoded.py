"""Write the decoder's output for a kernel as a Lean file (`Kernels/<K>/Data/Decoded.lean`).

The program is decoded by the Core decoder itself (`PTX.Decode.kernelIn`, evaluated by Lean)
and printed with its derived `Repr`, in definitions of `CHUNK` instructions. The kernel's
`decode_eq` then checks by kernel reduction that the source decodes to exactly this value, so
the file is a cache of the decoder's result, never a second source of truth.

    python Tools/export_decoded.py --ptx-module Kernels.Fp16Gemm8192.Ptx \\
        --function PTX.Generated.Fp16Gemm8192.gemm_kernel \\
        --globals PTX.Generated.Fp16Gemm8192.module.globals \\
        --namespace PTX.Kernels.Fp16Gemm8192.Decoded \\
        -o Kernels/Fp16Gemm8192/Data/Decoded.lean [--check]
"""

import argparse
import json
import subprocess
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from lean_wrap import WIDTH, wrap_lines  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
CHUNK = 32
# Register names per definition: a list literal of a few thousand elements exceeds Lean's
# default recursion depth, so a longer list is split into definitions of this many.
NAMES = 2048

PROGRAM = """import Core.Source.Decode
import {module}
open PTX

def main : IO Unit := do
  match Decode.kernelIn {globals} {function} with
  | .error e => throw (IO.userError e)
  | .ok k =>
    let chunks := (List.range ((k.code.length + {chunk} - 1) / {chunk})).map fun i =>
      Json.str (Std.Format.pretty (repr ((k.code.drop (i * {chunk})).take {chunk})) 100)
    let names := (List.range ((k.regNames.length + {names} - 1) / {names})).map fun i =>
      Json.str (Std.Format.pretty (repr ((k.regNames.drop (i * {names})).take {names})) 100)
    IO.println (Json.compress (Json.mkObj [
      ("metadata", Json.str (Std.Format.pretty (repr {{ k with code := [] }}) 100)),
      ("metadataNoNames",
        Json.str (Std.Format.pretty (repr {{ k with code := [], regNames := [] }}) 100)),
      ("length", Json.num k.code.length),
      ("chunks", Json.arr chunks.toArray),
      ("names", Json.arr names.toArray)]))
"""


def decode(module: str, function: str, globals_: str) -> dict:
    """The decoded kernel's printed parts, from Lean."""
    with tempfile.TemporaryDirectory() as tmp:
        src = Path(tmp) / "ExportDecoded.lean"
        src.write_text(
            "import Lean.Data.Json\n"
            + PROGRAM.format(
                module=module, function=function, globals=globals_, chunk=CHUNK, names=NAMES
            ).replace("open PTX", "open PTX Lean")
        )
        out = subprocess.run(
            ["lake", "env", "lean", "--run", str(src)],
            cwd=ROOT,
            capture_output=True,
            text=True,
        )
    if out.returncode != 0:
        raise SystemExit(out.stdout + out.stderr)
    return json.loads(out.stdout)


def kernel_def(n: int) -> list[str]:
    """`kernel`: the chunks joined as `code0 ++ (code1 ++ (...))`, broken to the line width."""
    words = [f"code{i} ++ (" for i in range(n - 1)] + [f"code{n - 1}" + ")" * (n - 1) + " }"]
    lines, cur = ["def kernel : Kernel :=", "  { metadata with code :="], "   "
    for w in words:
        if len(cur) + len(w) + 1 > WIDTH:
            lines.append(cur)
            cur = "   "
        cur += w if cur.endswith("(") else " " + w
    return lines + [cur]


def render(parts: dict, namespace: str) -> str:
    n = len(parts["chunks"])
    lines = [
        "-- SPDX-License-Identifier: Apache-2.0",
        "-- Generated by Tools/export_decoded.py; do not edit.",
        "module",
        "",
        "public import Core.Source.Instr",
        "",
        "@[expose] public section",
        "",
        f"namespace {namespace}",
        "",
        "open PTX",
        "",
    ]
    for i, chunk in enumerate(parts["chunks"]):
        lines += [f"def code{i} : List Instr :=", chunk, ""]
    names = parts["names"]
    if len(names) <= 1:
        lines += ["def metadata : Kernel :=", parts["metadata"], ""]
    else:
        for i, chunk in enumerate(names):
            lines += [f"def regNames{i} : List String :=", chunk, ""]
        joined = " ++ ".join(f"regNames{i}" for i in range(len(names)))
        metadata = parts["metadataNoNames"]
        assert metadata.count("regNames := []") == 1
        lines += [
            "def metadata : Kernel :=",
            metadata.replace("regNames := []", f"regNames := {joined}"),
            "",
        ]
    lines += [
        *kernel_def(n),
        "",
        f"theorem code_length : kernel.code.length = {parts['length']} := by decide +kernel",
        "",
        f"end {namespace}",
        "",
    ]
    return "\n".join(wrap_lines("\n".join(lines).split("\n")))


def main():
    p = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    p.add_argument("--ptx-module", required=True)
    p.add_argument("--function", required=True)
    p.add_argument("--globals", required=True)
    p.add_argument("--namespace", required=True)
    p.add_argument("-o", "--out", type=Path, required=True)
    p.add_argument("--check", action="store_true")
    a = p.parse_args()
    text = render(decode(a.ptx_module, a.function, a.globals), a.namespace)
    if a.check:
        return 0 if a.out.exists() and a.out.read_text() == text else 1
    a.out.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
