"""One step lemma per local instruction, generated from the decoded program.

For every program counter of the declared ranges whose instruction is an integer, floating, move
or conversion instruction (reading no special register), a branch or a `ld.param`, guarded or
not, writes

    theorem step_<pc> {L : Launch} {g : Nat} : PcLocal <kernel> <assumptions> L g <pc> <instr>

(`Lemmas/Flow/PcStep.lean`): a state at `pc` without a fault steps by `stepIns` of the literal
instruction (its guard, then its local rule: an assumption's rule for it, else Core's). Each is
proved once, from the kernel's code lemma `code_<pc>` (`Tools/code_table.py`), locality by `rfl`,
and no segment at `pc` by the declared tactic (`segfree`, default `seg_free_pc`); the pcs of
`exclude` (an assumption's segment starts there) are left out. `seg_fp` uses the lemmas (by name,
`<code namespace>.step_<pc>`) to chain a piece's steps instead of evaluating the code, the guards
and the assumptions' segments at every step. The instruction terms are the decoder's
(`Kernels/<K>/Data/Decoded.lean`, equal to the PTX by the kernel's `decode_eq`); the lemmas are
checked by Lean against `code_<pc>`, so a wrong selection fails to build rather than proving
something else.

Declaration (JSON):

    {"decoded": "Kernels/K/Data/Decoded.lean", "output": "Kernels/K/Flow/Step.lean",
     "namespace": "PTX.Kernels.K.Flow", "kernel": "PTX.Kernels.K.kernel",
     "assumptions": "PTX.Kernels.K.Assumptions.all",
     "imports": ["Kernels.K.Flow.Code"], "ranges": [[2356, 2410]], "exclude": [],
     "segfree": "seg_free_pc"}

    python Tools/step_gen.py decl.json            # write the output (parts next to it)
    python Tools/step_gen.py decl.json --check    # fail if the output is stale
"""

import argparse
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from code_table import fit, items  # noqa: E402

PART = 64
LOCAL = re.compile(
    r"^\{ guard := (none|some \(\d+, (true|false)\)), op := PTX\.Op\.(int|float|move|cvt|bra) "
    r"|^\{ guard := (none|some \(\d+, (true|false)\)), op := PTX\.Op\.mem "
    r"\{ kind := PTX\.MemKind\.load, space := some \(PTX\.StateSpace\.param\)"
)
VARYING = re.compile(r"PTX\.Opnd\.sreg")


def selected(instr: str) -> bool:
    """A local instruction the lemma form covers. A special-register operand is left out (a
    changing one makes the instruction an event)."""
    return bool(LOCAL.match(instr)) and not VARYING.search(instr)


def generate(decl: dict, root: Path) -> dict[Path, str]:
    instrs = items((root / decl["decoded"]).read_text())
    out = root / decl["output"]
    module = ".".join(out.resolve().relative_to(root.resolve()).with_suffix("").parts)
    ns, kernel, asms = decl["namespace"], decl["kernel"], decl["assumptions"]
    segfree = decl.get("segfree", "seg_free_pc")
    pcs = sorted(
        {
            pc
            for lo, hi in decl["ranges"]
            for pc in range(lo, min(hi, len(instrs)))
            if selected(instrs[pc]) and pc not in decl.get("exclude", [])
        }
    )
    head = [
        "-- SPDX-License-Identifier: Apache-2.0",
        "-- Generated by Tools/step_gen.py; do not edit.",
        "module",
        "",
    ]
    files, names = {}, []
    for k in range(0, len(pcs), PART):
        name = f"Part{k // PART:03d}"
        names.append(name)
        lines = head + [
            *[f"public import {m}" for m in decl["imports"]],
            "public import Lemmas.Flow.PcStep",
            "public import Lemmas.Flow.Hooks",
            "",
            "@[expose] public section",
            "",
            f"namespace {ns}",
            "open PTX PTX.Flow",
            "",
        ]
        for pc in pcs[k : k + PART]:
            lines += [
                f"theorem step_{pc} {{L : Launch}} {{g : Nat}} :",
                f"    PcLocal {kernel} {asms} L g {pc} {instrs[pc]} :=",
                f"  PcLocal.of_code code_{pc} rfl (by {segfree})",
                "",
            ]
        lines += [f"end {ns}", ""]
        files[out.with_suffix("") / f"{name}.lean"] = fit(lines)
    files[out] = fit(
        head
        + [f"public import {module}.{n}" for n in names]
        + [
            "",
            "/-! The step lemma of each local instruction (`step_<pc>`, in the parts). -/",
            "",
        ]
    )
    return files


def main():
    p = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    p.add_argument("decl", type=Path)
    p.add_argument("--root", type=Path, default=Path(__file__).resolve().parent.parent)
    p.add_argument("--check", action="store_true")
    a = p.parse_args()
    decl = json.loads(a.decl.read_text())
    files = generate(decl, a.root)
    out = a.root / decl["output"]
    parts = out.with_suffix("")
    stale = set(parts.glob("*.lean")) - set(files) if parts.exists() else set()
    if a.check:
        fresh = all(p.exists() and p.read_text() == t for p, t in files.items())
        return 0 if fresh and not stale else 1
    parts.mkdir(parents=True, exist_ok=True)
    for p in stale:
        p.unlink()
    for p, t in files.items():
        p.write_text(t)
    return 0


if __name__ == "__main__":
    sys.exit(main())
