"""Remove the Guarantee field from the contract blocks of Core through a reviewed worksheet.

usage: contract_fields.py --worksheet <path>
       contract_fields.py --apply <path>

`--worksheet` writes one section for every contract block `/-! ## ID — title` of `Core/**/*.lean`
that has a `Guarantee:` field. A section shows the block ID, its file, and the current Statement,
Premises and Guarantee fields exactly as they appear in the source (field line and continuation
lines). The author fills in a `Decision:` line, `drop` or `merge`, and an optional `Reason:`
line, and the reviewer adds an optional `Review:` line. A `merge` section also has a
`New Statement:` text, and any section may have a `Prose after the fields:` text. When the
worksheet file already exists, the decisions, reasons, reviews and texts of every section whose
source fields are unchanged are kept.

`--apply` rewrites the source comments from the worksheet. It deletes the Guarantee field with
its continuation lines, replaces the Statement field by the New Statement of a `merge` section
(wrapped to 100 columns, continuation lines indented by two spaces), and inserts the prose text
as the first paragraph after the fields. It refuses to run, and writes nothing, when a section
has no valid decision, when a block with a Guarantee field has no section, or when the
Statement, Premises or Guarantee text of a block differs from its worksheet section.
"""

import argparse
import re
import sys
import textwrap
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OPENER = "/-! ## "
WIDTH = 100
FENCE = "```"
SHOWN = ("Statement", "Premises", "Guarantee")
DECISIONS = ("drop", "merge")
# Worksheet labels of the texts the reviewer writes.
NEW_STATEMENT = "New Statement"
PROSE = "Prose after the fields"
TEXTS = (NEW_STATEMENT, PROSE)


class Block:
    """A contract block: its ID and title, file, and the line spans of its fields."""

    def __init__(self, file, ident, title, start, lines):
        self.file = file
        self.ident = ident
        self.title = title
        self.start = start  # index of the opener line in the file
        self.spans = {}  # field -> (first, end) line indices in the file, end exclusive
        self.field_end = start + 1  # index after the last field line
        i = start + 1
        while i < len(lines):
            line = lines[i]
            if line.endswith("-/") or line.startswith("### "):
                break
            m = re.match(r"([A-Z][A-Za-z]*): ", line)
            if m:
                j = i + 1
                while j < len(lines) and lines[j].startswith("  ") and not lines[j].endswith("-/"):
                    j += 1
                self.spans.setdefault(m.group(1), (i, j))
                self.field_end = j
                i = j
                continue
            if not line.strip():
                break
            i += 1
        self.end = i  # index of the closing line, `### ` heading or first blank line

    def raw(self, lines, key):
        """The source text of a field, or None."""
        if key not in self.spans:
            return None
        a, b = self.spans[key]
        return "\n".join(lines[a:b])


def blocks(file, lines):
    for i, line in enumerate(lines):
        if line.startswith(OPENER):
            ident, _, title = line[len(OPENER) :].partition(" — ")
            yield Block(file, ident.strip(), title.strip(), i, lines)


def core_files():
    return sorted(
        str(p.relative_to(ROOT))
        for folder in ("Core", "Assumption")
        for p in (ROOT / folder).rglob("*.lean")
    )


def guarantee_blocks():
    """(block, lines) for every block of Core with a Guarantee field, in file order."""
    out = []
    for f in core_files():
        lines = (ROOT / f).read_text().split("\n")
        out += [(b, lines) for b in blocks(f, lines) if "Guarantee" in b.spans]
    return out


def fenced(text):
    return [FENCE + "text", text, FENCE]


def render_section(block, lines, kept):
    out = [f"## {block.ident} — {block.title}", "", f"File: `{block.file}`", ""]
    for key in SHOWN:
        raw = block.raw(lines, key)
        out += [f"{key}:", ""] + fenced(raw if raw is not None else "") + [""]
    out += [f"Decision: {kept.get('Decision', '')}".rstrip(), ""]
    if kept.get("Reason"):
        out += [f"Reason: {kept['Reason']}", ""]
    for label in TEXTS:
        if kept.get(label):
            out += [f"{label}:", ""] + fenced(kept[label]) + [""]
    if kept.get("Review"):
        out += [f"Review: {kept['Review']}", ""]
    return out


HEADER = [
    "# Guarantee worksheet",
    "",
    "Generated by `Tools/contract_fields.py --worksheet`; applied by"
    " `Tools/contract_fields.py --apply`.",
    "Each section shows the Statement, Premises and Guarantee of one contract block exactly as in"
    " the source.",
    "`Decision: drop` deletes the Guarantee field. `Decision: merge` also replaces the Statement by"
    " the `New Statement` text.",
    "A `Prose after the fields` text, allowed with either decision, becomes the first paragraph"
    " after the fields of the block.",
    "`Reason` says why the Guarantee adds nothing to the Statement, or what it adds and where that"
    " text goes.",
    "",
]


def parse_worksheet(text):
    """Map block ID -> dict of the section: File, the shown fields, Decision, Reason, Review and
    texts."""
    sections = {}
    cur = None
    label = None
    lines = text.split("\n")
    i = 0
    while i < len(lines):
        line = lines[i]
        if line.startswith("## "):
            ident = line[3:].partition(" — ")[0].strip()
            if ident in sections:
                raise SystemExit(f"worksheet: duplicate section {ident}")
            cur = sections[ident] = {}
            label = None
        elif cur is None:
            pass
        elif line.startswith(FENCE):
            j = i + 1
            while j < len(lines) and lines[j] != FENCE:
                j += 1
            if j == len(lines):
                raise SystemExit(f"worksheet: unclosed fence in section {ident}")
            if label is None:
                raise SystemExit(f"worksheet: fenced text without a label in section {ident}")
            cur[label] = "\n".join(lines[i + 1 : j])
            label = None
            i = j
        elif line.startswith("File: "):
            cur["File"] = line[6:].strip().strip("`")
        elif line.startswith(("Decision:", "Reason:", "Review:")):
            key, _, value = line.partition(":")
            cur[key] = value.strip()
        elif line.endswith(":") and line[:-1] in SHOWN + TEXTS:
            label = line[:-1]
        elif line.strip():
            raise SystemExit(f"worksheet: unexpected line in section {ident}: {line}")
        i += 1
    return sections


def write_worksheet(path):
    old = parse_worksheet(path.read_text()) if path.exists() else {}
    out = list(HEADER)
    kept_count = 0
    found = guarantee_blocks()
    for block, lines in found:
        prev = old.get(block.ident, {})
        same = all(prev.get(k) == (block.raw(lines, k) or "") for k in SHOWN)
        kept = prev if same else {}
        kept_count += bool(kept.get("Decision"))
        out += render_section(block, lines, kept)
    path.write_text("\n".join(out).rstrip() + "\n")
    print(f"{path}: {len(found)} blocks with a Guarantee field, {kept_count} decisions kept")


def wrap(text, first, rest):
    """Fill `text` to WIDTH columns. A line break never falls inside a `code` span."""
    keep = "\x00"
    words = " ".join(text.split())
    words = re.sub(r"`[^`]*`", lambda m: m.group(0).replace(" ", keep), words)
    lines = textwrap.wrap(
        words,
        width=WIDTH,
        initial_indent=first,
        subsequent_indent=rest,
        break_long_words=False,
        break_on_hyphens=False,
    )
    return [line.replace(keep, " ") for line in lines]


def apply_worksheet(path):
    sections = parse_worksheet(path.read_text())
    errors = []
    edits = {}  # file -> list of (block, section)
    seen = set()
    for block, lines in guarantee_blocks():
        seen.add(block.ident)
        sec = sections.get(block.ident)
        where = f"{block.file}: {block.ident}"
        if sec is None:
            errors.append(f"{where}: no worksheet section")
            continue
        if sec.get("File") != block.file:
            errors.append(f"{where}: worksheet names file {sec.get('File')}")
        for key in SHOWN:
            if sec.get(key) != (block.raw(lines, key) or ""):
                errors.append(f"{where}: {key} differs from the worksheet")
        decision = sec.get("Decision")
        if decision not in DECISIONS:
            errors.append(f"{where}: decision must be drop or merge, found {decision!r}")
        elif decision == "merge" and not sec.get(NEW_STATEMENT, "").strip():
            errors.append(f"{where}: merge needs a New Statement text")
        elif decision == "drop" and sec.get(NEW_STATEMENT):
            errors.append(f"{where}: drop must not have a New Statement text")
        edits.setdefault(block.file, []).append((block, sec))
    for ident in sorted(set(sections) - seen):
        errors.append(f"{ident}: worksheet section names no block with a Guarantee field")
    if errors:
        raise SystemExit("contract_fields: nothing applied\n" + "\n".join(errors))
    for f, items in edits.items():
        lines = (ROOT / f).read_text().split("\n")
        for block, sec in sorted(items, key=lambda x: -x[0].start):
            # Replace from the bottom of the block up so that earlier spans stay valid.
            changes = [(block.spans["Guarantee"], [])]
            if sec["Decision"] == "merge":
                changes.append(
                    (block.spans["Statement"], wrap(sec[NEW_STATEMENT], "Statement: ", "  "))
                )
            prose = sec.get(PROSE, "").strip()
            if prose:
                insert = [""] + wrap(prose, "", "")
                after = lines[block.field_end].strip()
                if after and after != "-/":
                    insert.append("")
                changes.append(((block.field_end, block.field_end), insert))
            for (a, b), new in sorted(changes, key=lambda c: -c[0][0]):
                lines[a:b] = new
        (ROOT / f).write_text("\n".join(lines))
    print(f"applied {sum(len(v) for v in edits.values())} sections to {len(edits)} files")


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--worksheet", type=Path, help="write or refresh the worksheet")
    group.add_argument("--apply", type=Path, help="apply a reviewed worksheet to Core")
    args = parser.parse_args()
    if args.worksheet:
        write_worksheet(args.worksheet)
    else:
        apply_worksheet(args.apply)


if __name__ == "__main__":
    sys.exit(main())
