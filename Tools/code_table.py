"""Instruction lookups for the sites of a decoded kernel.

Reads the decoder's output (`Kernels/<K>/Data/Decoded.lean`, or a `Spec.lean` that writes the
program out as `code := [...]`; either agrees with the PTX by the kernel's `decode_eq`) and the
site list of `Tools/flow_gen.py`, and writes one
lemma per instruction, `kernel.code[pc]? = some ins`, checked by kernel reduction, in parts
that Lean checks in parallel. Site machines
rewrite with these lemmas instead of restating instructions.

    python Tools/code_table.py Kernels/K/Data/Decoded.lean Kernels/K/Flow/flow.json \\
        --namespace PTX.Kernels.K.Flow --kernel PTX.Kernels.K.kernel --spec Kernels.K.Spec \\
        -o Kernels/K/Flow/Code.lean [--check]
"""

import argparse
import json
import re
import sys
from pathlib import Path

from lean_wrap import WIDTH, wrap_lines


def items(text: str) -> list[str]:
    """The instruction terms of the decoder's `def codeN : List Instr := [ ... ]` lists, or of a
    kernel written out as `code := [ ... ]`, in order."""
    out = []
    text = re.sub(r"--[^\n]*", "", text)
    text = re.sub(r"\\\n\s*", "", text)  # string gaps: a long string printed over lines
    starts = r"^def code\d+ : List Instr :=\n\[|^\s*code := \["
    for m in re.finditer(starts, text, re.M):
        i, depth, start = m.end(), 0, m.end()
        while True:
            c = text[i]
            if c in "([{⟨":
                depth += 1
            elif c in ")]}⟩":
                if depth == 0:
                    out.append(text[start:i].strip())
                    break
                depth -= 1
            elif c == "," and depth == 0:
                out.append(text[start:i].strip())
                start = i + 1
            i += 1
    return [re.sub(r"\s+", " ", x) for x in out if x]


PART = 64
# Above this many conversion runs, `cvtRuns_code` is proved by one `List.Forall` term.
LONG_RUNS = 32


def module_of(path: Path) -> str:
    """The Lean module of a file under `Kernels/`."""
    parts = path.resolve().with_suffix("").parts
    return ".".join(parts[len(parts) - 1 - parts[::-1].index("Kernels") :])


def fit(lines: list[str]) -> str:
    """The lines as text, broken to the line width."""
    return "\n".join(wrap_lines("\n".join(lines).split("\n")))


def generate(
    decoded: Path, flow: Path, namespace: str, kernel: str, spec: str, out: Path, *, slices=False
):
    """The files of the table: parts of `PART` instructions, which Lean checks in parallel,
    and `out`, which imports them and names the sites."""
    decoded_text = decoded.read_text()
    instrs = items(decoded_text)
    if slices:
        from export_decoded import CHUNK

        counts = [
            len(items(chunk))
            for chunk in re.split(r"(?=^def code\d+ : List Instr :=)", decoded_text, flags=re.M)[1:]
        ]
        if PART % CHUNK or counts != [
            min(CHUNK, len(instrs) - i) for i in range(0, len(instrs), CHUNK)
        ]:
            raise ValueError("slice-based lookups require a standard decoder cache")
    sites = json.loads(flow.read_text())["sites"]
    module = module_of(out)
    files = {}
    names = []
    for k in range(0, len(instrs), PART):
        name = f"Part{k // PART:03d}"
        names.append(name)
        lines = [
            "-- SPDX-License-Identifier: Apache-2.0",
            "-- Generated by Tools/code_table.py; do not edit.",
            "module",
            "",
            f"public import {spec}",
            *(["public import Lemmas.Kernel.CodeSlice"] if slices else []),
            "public import Tactics.KernelRfl",
            "",
            "@[expose] public section",
            "",
            f"namespace {namespace}",
            "open PTX",
            "",
        ]
        stop = min(k + PART, len(instrs))
        if slices:
            decoded_namespace = kernel.removesuffix(".kernel")
            part = " ++ ".join(
                f"{decoded_namespace}.code{i // CHUNK}" for i in range(k, stop, CHUNK)
            )
            lines += [
                f"private theorem code_slice : ({kernel}.code.drop {k}).take {stop - k} =",
                f"    {part} := by",
                "  kernel_rfl",
                "",
            ]
        for pc in range(k, stop):
            lines += [
                f"theorem code_{pc} : {kernel}.code[{pc}]? = some {instrs[pc]} := by",
                (
                    f"  exact codeLookupOfSlice (offset := {pc - k}) code_slice (by decide) rfl"
                    if slices
                    else "  kernel_rfl"
                ),
                "",
            ]
        lines += [f"end {namespace}", ""]
        files[out.with_suffix("") / f"{name}.lean"] = fit(lines)
    lines = [
        "-- SPDX-License-Identifier: Apache-2.0",
        "-- Generated by Tools/code_table.py; do not edit.",
        "module",
        "",
        *[f"public import {module}.{n}" for n in names],
        "",
        "@[expose] public section",
        "",
        "/-! The instruction at each program counter (`code_<pc>`, in the parts, by kernel",
        "reduction of the decoded program) and at each site. -/",
        "",
        f"namespace {namespace}",
        "open PTX",
        "",
    ]
    for s in sites:
        lines += [
            f"theorem code_{s['name']} : {kernel}.code[{s['pc']}]? = some {instrs[s['pc']]} :=",
            f"  code_{s['pc']}",
            "",
        ]
    lines += [f"end {namespace}", ""]
    files[out] = fit(lines)
    runs = cvt_runs(instrs)
    if runs:
        files[out.with_name("CvtRuns.lean")] = cvt_runs_file(runs, namespace, kernel, module)
    return files


CVT = re.compile(
    r"^\{ guard := none, op := PTX\.Op\.cvt \{ "
    r"dst := PTX\.DType\.packed \(PTX\.DType\.float \(PTX\.FType\.f16\)\) 2, "
    r"src := PTX\.DType\.float \(PTX\.FType\.f32\), rnd := some \(PTX\.CvtRnd\.rn\), "
    r"ftz := false, sat := false, relu := false, satfinite := false, pzo := false, "
    r"scaled := false, pack := false, d := (\d+), "
    r"srcs := \[PTX\.Opnd\.reg (\d+), PTX\.Opnd\.reg (\d+)\] \} \}$"
)


def cvt_runs(instrs: list[str]) -> list[tuple[int, list[tuple[str, str, str]]]]:
    """Maximal runs of unguarded register-to-register `cvt.rn.f16x2.f32` conversions."""
    runs, pc = [], 0
    while pc < len(instrs):
        run = []
        while pc + len(run) < len(instrs) and (m := CVT.match(instrs[pc + len(run)])):
            run.append(m.groups())
        if run:
            runs.append((pc, run))
            pc += len(run)
        else:
            pc += 1
    return runs


def cvt_runs_file(runs, namespace: str, kernel: str, module: str) -> str:
    """`cvtRuns`: each run of conversions by its first program counter, with the code facts
    `Flow.cvt_chain` needs (`cvtRuns_code`)."""

    def triple(c):
        return f"({c[0]}, {c[1]}, {c[2]})"

    entries = ", ".join(f"({pc}, [{', '.join(triple(c) for c in run)}])" for pc, run in runs)
    proofs = "\n".join(
        f"  · exact ⟨{', '.join(f'code_{pc + i}' for i in range(len(run)))}, trivial⟩"
        for pc, run in runs
    )
    alts = " | ".join("rfl" for _ in runs)
    if len(runs) <= LONG_RUNS:
        proof = [
            "  intro r hr",
            "  simp only [cvtRuns, List.mem_cons, List.not_mem_nil, or_false] at hr",
            f"  rcases hr with {alts}",
            proofs,
        ]
    else:
        # A case split over a long list is quadratic; a long list gets one term instead.
        facts = ",\n    ".join(
            f"⟨{', '.join(f'code_{pc + i}' for i in range(len(run)))}, trivial⟩" for pc, run in runs
        )
        proof = [f"  List.forall_iff_forall_mem.1\n    ⟨{facts}⟩"]
    by = " by" if len(runs) <= LONG_RUNS else ""
    head = f"theorem cvtRuns_code : ∀ r ∈ cvtRuns, PTX.Flow.CvtCode {kernel} r.1 r.2 :={by}"
    if len(head) > WIDTH:
        head = head.replace(" : ∀", " :\n    ∀", 1)
    return fit(
        [
            "-- SPDX-License-Identifier: Apache-2.0",
            "-- Generated by Tools/code_table.py; do not edit.",
            "module",
            "",
            f"public import {module}",
            "public import Lemmas.Flow.Cvt",
            "",
            "@[expose] public section",
            "",
            "/-! The runs of half-precision conversions (`cvt.rn.f16x2.f32`): each run by its first",
            "program counter, as `(d, a, b)` triples, and its code facts (`cvtRuns_code`). -/",
            "",
            f"namespace {namespace}",
            "open PTX",
            "",
            "def cvtRuns : List (Nat × List (Nat × Nat × Nat)) :=",
            f"  [{entries}]",
            "",
            head,
            *proof,
            "",
            f"end {namespace}",
            "",
        ]
    )


def main():
    p = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    p.add_argument("decoded", type=Path)
    p.add_argument("flow", type=Path)
    p.add_argument("--namespace", required=True)
    p.add_argument("--kernel", required=True)
    p.add_argument("--spec", required=True)
    p.add_argument("-o", "--out", type=Path, required=True)
    p.add_argument("--check", action="store_true")
    p.add_argument(
        "--slices", action="store_true", help="prove lookups through decoder-cache slices"
    )
    a = p.parse_args()
    files = generate(a.decoded, a.flow, a.namespace, a.kernel, a.spec, a.out, slices=a.slices)
    parts = a.out.with_suffix("")
    stale = set(parts.glob("*.lean")) - set(files) if parts.exists() else set()
    if a.check:
        fresh = all(p.exists() and p.read_text() == t for p, t in files.items())
        return 0 if fresh and not stale else 1
    parts.mkdir(exist_ok=True)
    for p in stale:
        p.unlink()
    for p, t in files.items():
        p.write_text(t)
    return 0


if __name__ == "__main__":
    sys.exit(main())
