"""Generates `Proof/Wg0/Gen/NumEs.lean`: the scaled output words of the epilogue's four chunks
(`es0`..`es3`, 32 packed bf16 words each) against the numbers the accumulator words read as.

Word `j` of chunk `c` (register `R_c + 3 j` of `Gen.es<c>_facts4`) packs the products of the
accumulator words `2 j`, `2 j + 1` with the factor pair (`mul.f32x2` on the pack, then
`cvt.rn.bf16x2`). The pair register of the product (`3576 + ..`) is read from `Gen/Epi<c>.lean`.
`--check` compares the file on disk with the generated text. Run from the repository root."""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
K = ROOT / "Kernels/FlashMlaSparseDecodeH64/Proof/Wg0"
OUT = K / "Gen/NumEs.lean"
OREG = [1745, 1916, 2086, 2255]

HEAD = """-- SPDX-License-Identifier: Apache-2.0
-- Generated by Kernels/FlashMlaSparseDecodeH64/Gen/w0num_epi_gen.py; do not edit.
-- domain: valid-rows
module

public import Kernels.FlashMlaSparseDecodeH64.Proof.Wg0.Data.NumEpi
public import Kernels.FlashMlaSparseDecodeH64.Proof.Wg0.Data.NumP
public import Kernels.FlashMlaSparseDecodeH64.Proof.Wg0.Gen.Epi0
public import Kernels.FlashMlaSparseDecodeH64.Proof.Wg0.Gen.Epi1
public import Kernels.FlashMlaSparseDecodeH64.Proof.Wg0.Gen.Epi2
public import Kernels.FlashMlaSparseDecodeH64.Proof.Wg0.Gen.Epi3
public import Lemmas.Flow.Mul2NReads

@[expose] public section

/-! # The scaled output words against the numbers

Word `j` of output chunk `c` (`Gen.es<c>_facts4`, register `R_c + 3 j`) is the bf16 pack of the
products of the accumulator words `2 j` and `2 j + 1` (numbers `O`) with the factor `f`
(`w0e_word`). Generated by `Gen/w0num_epi_gen.py`. -/

namespace PTX.Kernels.FlashMlaSparseDecodeH64.Proof.Wg0.Data
open PTX PTX.Flow PTX.Proof PTX.Assumption PTX.Kernels.FlashMlaSparseDecodeH64.Proof.Wg0.Gen

noncomputable section

theorem w0e_word {p q : Nat} (hpq : p ≠ q) {a b c : Value} {x0 x1 f : ℝ} (ha : Rd a x0)
    (hb : Rd b x1) (hc : pairRead c = some (.ok ((f : EReal), (f : EReal)))) :
    okVal (.bits 32 0) (bfE [(splitValue 64 (okVal (.bits 32 0)
        (fF mul2NL [.reg p, .reg q] [joinValue a b, c]))).2,
      (splitValue 64 (okVal (.bits 32 0) (fF mul2NL [.reg p, .reg q] [joinValue a b, c]))).1]) =
      Assumptions.bf16Pair (x0 * f) (x1 * f) := by
  have hq : lk [p, q] [joinValue a b, c] q = c := by
    have e : (q == p) = false := beq_false_of_ne (Ne.symm hpq)
    simp [lk, List.lookup, e]
  have hp : lk [p, q] [joinValue a b, c] p = joinValue a b := by simp [lk]
  have e : fF mul2NL [.reg p, .reg q] [joinValue a b, c] = floatE mul2NI [joinValue a b, c] := by
    simp only [fF, regsOf, regOf, List.flatMap_cons, List.flatMap_nil, List.cons_append,
      List.nil_append, List.append_nil, List.map_cons, List.map_nil, fOpnd, hp, hq, mul2NL]
  rw [e, floatE_mul2N_reads (pairRead_join ha hb) hc (mulEReal_coe x0 f) (mulEReal_coe x1 f)]
  simp only [okVal, erealValue_coe, splitValue]
  exact w0p_bf

"""


def chunk(c):
    s = (K / f"Gen/Epi{c}.lean").read_text()
    fm = re.search(r"def es%d_facts4 .*?:= \[(.*?)\n\]" % c, s, re.S).group(1)
    regs = [(int(r), int(v)) for r, v in re.findall(r"\((\d+), es%d_v(\d+) V\)" % c, fm)]
    assert len(regs) == 32 and all(regs[j][0] == regs[0][0] + 3 * j for j in range(32))
    # the product register of word j: the `mul2NL` item before the word's `bfE`
    muls = {}
    for m in re.finditer(
        r"def es%d_v(\d+) \(V : Nat → Value\) : Value :=\n  okVal \(\.bits 32 0\)\n"
        r"\s+\(\(\(PTX\.Flow\.fF PTX\.Flow\.mul2NL \[\(\.reg (\d+)\), \(\.reg 3577\)\]\)\)"
        r" \[es%d_v(\d+) V, V 3577\]\)" % (c, c),
        s,
    ):
        muls[int(m.group(1))] = int(m.group(2))
    ps = []
    for j, (_, v) in enumerate(regs):
        # `bfE [..._1 V, ..._0 V]` of word v reads the split of the product v-2
        ps.append(muls[v - 2])
    return regs, ps


def gen():
    out = [HEAD]
    for c in range(4):
        regs, ps = chunk(c)
        r0 = regs[0][0]
        out.append(f"""theorem w0e_es{c} (V : Nat → Value) (O : Nat → ℝ) {{f : ℝ}}
    (hO : ∀ i < 64, Rd (V ({OREG[c]} + i)) (O i))
    (hc : pairRead (V 3577) = some (.ok ((f : EReal), (f : EReal)))) :
    ∀ j < 32, lookupD (es{c}_facts4 V) ({r0} + 3 * j) =
      Assumptions.bf16Pair (O (2 * j) * f) (O (2 * j + 1) * f) := by
  intro j hj
  have hO' : ∀ i < 64, ∀ v, v = {OREG[c]} + i → Rd (V v) (O i) := fun i hi v hv => hv ▸ hO i hi
  interval_cases j
  all_goals refine w0e_word ?_ ?_ ?_ hc
  all_goals first | exact hO' _ (by norm_num) _ (by norm_num) | norm_num""")
        out.append("")
    out.append("end\nend PTX.Kernels.FlashMlaSparseDecodeH64.Proof.Wg0.Data\n")
    return "\n".join(out)


if __name__ == "__main__":
    text = gen()
    if "--check" in sys.argv:
        sys.exit(0 if OUT.exists() and OUT.read_text() == text else 1)
    OUT.write_text(text)
