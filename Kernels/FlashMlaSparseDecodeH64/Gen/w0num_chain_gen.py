def wrap(line):
    if len(line) <= 100:
        return line
    ind = len(line) - len(line.lstrip())
    if line.startswith("theorem") and ", lookupD (" in line:
        a, b = line.split(", lookupD (", 1)
        return wrap(
            a + ",\n    lookupD (" + b.replace(" r = lookupD (", " r =\n      lookupD (", 1)
        )
    if " r = lookupD (" in line:
        a, b = line.split(" r = lookupD (", 1)
        return a + " r =\n" + " " * (ind + 2) + "lookupD (" + b
    if line.lstrip().startswith("rw [w0c_fr_pst7") or ", w0c_fr_pst" in line:
        parts = line.strip().split(", ")
        outl, cur = [], " " * ind
        for q in parts:
            piece = q + ", "
            if len(cur) + len(piece) > 96:
                outl.append(cur.rstrip())
                cur = " " * ind
            cur += piece
        outl.append(cur.rstrip().rstrip(","))
        return "\n".join(outl)
    return line


