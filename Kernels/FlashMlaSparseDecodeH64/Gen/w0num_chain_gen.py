def wreg(c):
    return 1009 + c + c // 8


def args(n, extra=""):
    ps = " ".join(f"p{i}" for i in range(n))
    return "x m l mx sk lo hi mw" + (" " + ps if n else "") + extra


def lst(xs):
    return "\n".join(
        textwrap.wrap(
            "[" + ", ".join(map(str, xs)) + "]", 90, initial_indent="  ", subsequent_indent="   "
        )
    )


