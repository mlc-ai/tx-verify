"""Generates `Proof/Wg0/Data/NumSum.lean`: the eight peer-sum stages `sum0`..`sum7` of warpgroup 0's
block loop (pcs 478-515) against the extended reals.

Stage `k` adds the peer pairs `2k`, `2k+1` to the masked pairs of columns `4k..4k+3`: the first masked
pair is the pack made by the previous stage (`3145 + 4k`), the second is packed in the stage. The
result registers are read from `Gen/Row.lean`'s `sum<k>_facts1`. Run from the repository root."""

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
K = ROOT / "Kernels/FlashMlaSparseDecodeH64/Proof/Wg0"
row = (K / "Gen/Row.lean").read_text()


def wreg(c):
    return 1009 + c + c // 8


HEAD = """-- SPDX-License-Identifier: Apache-2.0
-- domain: valid-rows
module

public import Kernels.FlashMlaSparseDecodeH64.Proof.Wg0.Data.NumRd
public import Kernels.FlashMlaSparseDecodeH64.Proof.Wg0.Gen.Row

@[expose] public section

/-! # The peer sums against the extended reals

Stage `k` of the peer exchange (`Gen.sum<k>`, pcs 478-515) adds the two peer pairs `2k`, `2k+1`
(`Y`, finite reals) to the masked score pairs of columns `4k`..`4k+3` (`A`, the masked words read
as an extended real). Its two result registers hold the pairs of sums
(`w0SumV (A c + Y c) (A (c+1) + Y (c+1))`). Generated by `Gen/w0num_sum_gen.py`. -/

namespace PTX.Kernels.FlashMlaSparseDecodeH64.Proof.Wg0.Data
open PTX PTX.Flow PTX.Proof PTX.Assumption PTX.Kernels.FlashMlaSparseDecodeH64.Proof.Wg0.Gen

noncomputable section

set_option linter.unusedSimpArgs false

/-- The pair of two extended reals as `f32` words. -/
def w0SumV (a b : EReal) : Value := .pair (erealValue .f32 a) (erealValue .f32 b)

/-- A peer pair that reads as the finite reals `y0`, `y1`. -/
def W0PairIs (v : Value) (y0 y1 : ℝ) : Prop := pairRead v = some (.ok ((y0 : EReal), (y1 : EReal)))

theorem w0s_add2 {r1 r2 : Nat} (hne : r1 ≠ r2) {va vb : Value} {x0 x1 : EReal} {y0 y1 : ℝ}
    (ha : pairRead va = some (.ok (x0, x1))) (l0 : SK.ni.Lane x0) (l1 : SK.ni.Lane x1)
    (hb : W0PairIs vb y0 y1) :
    okVal (.bits 32 0) (fF add2NL [.reg r1, .reg r2] [va, vb]) =
      w0SumV (x0 + (y0 : EReal)) (x1 + (y1 : EReal)) := by
  have e : fF add2NL [.reg r1, .reg r2] [va, vb] = add2NE va vb := by
    have h21 : (r2 == r1) = false := beq_false_of_ne (Ne.symm hne)
    simp [fF, fOpnd, lk, regsOf, regOf, add2NL, List.lookup, h21]
  rw [e, add2NE_reads ha hb (lane_add_coe l0 y0).2 (lane_add_coe l1 y1).2]
  rfl

theorem w0s_lane {a : EReal} {y : ℝ} (h : SK.ni.Lane a) : SK.ni.Lane (a + (y : EReal)) :=
  (lane_add_coe h y).1

open Lean in
set_option hygiene false in
/-- `w0s_sum<k>` for the stage whose masked words are at `V w2`, `V w3`, result registers `r0`,
`r1` and first sum item `v0` (the pack is `v0 + 1`, the second sum `v0 + 2`). -/
local macro "w0s_sum " k:num w2:num w3:num r0:num r1:num v0:num : command => do
  let k := k.getNat
  let c := 4 * k
  let id (s : String) := mkIdent (.mkSimple s)
  let num (i : Nat) := Syntax.mkNumLit (toString i)
  let facts := id s!"sum{k}_facts1"
  let v (i : Nat) := id s!"sum{k}_v{v0.getNat + i}"
  let first := 3145 + c
  `(theorem $(id s!"w0s_sum{k}") (V : Nat → Value) (A : Nat → EReal) (Y : Nat → ℝ)
      (hj : pairRead (V $(num first)) = some (.ok (A $(num c), A $(num (c + 1)))))
      (l0 : SK.ni.Lane (A $(num c))) (l1 : SK.ni.Lane (A $(num (c + 1))))
      (h2 : Rd (V $w2) (A $(num (c + 2)))) (h3 : Rd (V $w3) (A $(num (c + 3))))
      (hp0 : W0PairIs (V $(num (first + 1))) (Y $(num c)) (Y $(num (c + 1))))
      (hp1 : W0PairIs (V $(num (first + 3))) (Y $(num (c + 2))) (Y $(num (c + 3)))) :
      lookupD ($facts V) $r0 =
          w0SumV (A $(num c) + (Y $(num c) : EReal))
            (A $(num (c + 1)) + (Y $(num (c + 1)) : EReal)) ∧
        lookupD ($facts V) $r1 =
          w0SumV (A $(num (c + 2)) + (Y $(num (c + 2)) : EReal))
            (A $(num (c + 3)) + (Y $(num (c + 3)) : EReal)) := by
    constructor
    · change $(v 0) V = _
      rw [$(v 0):ident]
      exact w0s_add2 (by decide) hj l0 l1 hp0
    · change $(v 2) V = _
      rw [$(v 2):ident]
      exact w0s_add2 (by decide) (by rw [$(v 1):ident]; exact pairRead_join h2 h3) (rd_lane h2)
        (rd_lane h3) hp1)

"""

out = [HEAD]
for k in range(8):
    # result registers of stage k
    fm = re.search(r"def sum%d_facts1 .*?:= \[(.*?)\n\]" % k, row, re.S).group(1)
    regs = re.findall(r"\((\d+), sum%d_v(\d+) V\)" % k, fm)
    res = [(int(r), int(v)) for r, v in regs if int(r) >= 3242]
    assert len(res) == 2, (k, res)
    (r0, v0), (r1, v1) = res
    c = 4 * k
    first = 3145 + 4 * k
    p0, p1 = 3146 + 4 * k, 3148 + 4 * k
    # the masked pair of the second sum is the stage's own pack (the value after the first item)
    vpack = int(re.search(r"def sum%d_v(\d+) .*?:=\n  joinValue" % k, row).group(1))
    out.append(f"w0s_sum {k} {wreg(c + 2)} {wreg(c + 3)} {r0} {r1} {v0}")
out.append("\nend\nend PTX.Kernels.FlashMlaSparseDecodeH64.Proof.Wg0.Data\n")
(K / "Data/NumSum.lean").write_text("\n".join(out))
