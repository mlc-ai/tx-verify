def wrap_long(line):
    """Break a long line at spaces; continuation lines are indented 4 more than the line."""
    if len(line) <= 100:
        return line
    ind = len(line) - len(line.lstrip())
    res, cur = [], line[:ind]
    for tok in line.strip().split(" "):
        add = tok if cur.strip() == "" else " " + tok
        if len(cur) + len(add) > 98 and cur.strip():
            res.append(cur)
            cur = " " * (ind + 4) + tok
        else:
            cur += add
    res.append(cur)
    return "\n".join(res)


