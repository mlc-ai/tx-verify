"""Generates `Proof/Wg0/Gen/CondMask.lean`: `mask_cond_of_reads`, the condition of the valid-mask
chain (`Gen.mask_cond`, pcs 290-393), from `Data/StrictMask.lean` and the column calls of
`Data/NumMask.lean`. Run from the repository root."""

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
K = ROOT / "Kernels/FlashMlaSparseDecodeH64/Proof/Wg0"
msrc = (K / "Gen/Mask.lean").read_text()
nm = (K / "Data/NumMask.lean").read_text()

m = re.search(r"def mask_items0 : List XItem := \[\n(.*?)\n\]\n", msrc, re.S)
items = []
for k in range(4):
    m = re.search(r"def mask_items%d : List XItem := \[\n(.*?)\n\]\n" % k, msrc, re.S)
    items += [re.sub(r"\s+", " ", x.strip()) for x in re.split(r",\n  (?=\.)", m.group(1))]
assert len(items) == 104
sizes = [32, 32, 32, 8]


def regs(it):
    m = re.search(r"\) (\d+) \[([\d, ]*)\]", it) or re.search(r"mask_op\d+ (\d+) \[([\d, ]*)\]", it)
    return int(m.group(1)), [int(x) for x in m.group(2).split(",")]


CALLS = {}
for i in range(32):
    mm = re.search(r"theorem w0m_col%d .*?:=\n  (w0m_col[ABCD]) (.*?) hv\n" % i, nm, re.S)
    CALLS[i] = (mm.group(1)[-1], mm.group(2))

pre = [
    "cond_of_okVal (w0m_v290 V n h) (by simp)",
    "cond_of_okVal (w0m_v291 V n h) (by simp)",
    "c_shr (kn := 8) rfl hn (by norm_num) h",
    "c_bfe (p := 8) hn (by norm_num) h",
    "cond_of_okVal (w0m_v294 V n hn h) (by simp)",
    "cond_of_okVal (w0m_v295 V n hn h) (by simp)",
    "c_shr (kn := 16) rfl hn (by norm_num) h",
    "c_bfe (p := 16) hn (by norm_num) h",
    "cond_of_okVal (w0m_v298 V n hn h) (by simp)",
    "cond_of_okVal (w0m_v299 V n hn h) (by simp)",
    "c_shr (kn := 24) rfl hn (by norm_num) h",
    "cond_of_okVal (w0m_v301 V n hn h) (by simp)",
]
terms = list(pre)  # (term, have-index or None)
need = [None] * 12
pos = 12
haves = {}
for i in range(32):
    kind, args = CALLS[i]
    if kind in "AB":
        i1, i2, i3 = items[pos : pos + 3]
        (d1, (a1,)), (d2, (a2,)), (d3, (a, p)) = regs(i1), regs(i2), regs(i3)
        named = (
            f"(d1 := {d1}) (a1 := {a1}) (d2 := {d2}) (a2 := {a2}) (d3 := {d3})\n      "
            f"(a := {a}) (p := {p})"
        )
        cnt = 3
    else:
        i2, i3 = items[pos : pos + 2]
        (d2, (a2,)), (d3, (a, p)) = regs(i2), regs(i3)
        named = f"(d2 := {d2}) (a2 := {a2}) (d3 := {d3}) (a := {a}) (p := {p})"
        cnt = 2
    args = (
        args.replace("(by simpa using h)", "(src := V 1002) (k := 0) (by simpa using h)")
        if i == 0
        else args
    )
    if kind == "B":
        args = args.replace("(by norm_num) (by norm_num)", "rfl (by norm_num)")
        b = int(re.search(r"\(b := (\d+)\)", args).group(1))
        named += f" (km := ((2 ^ {b} : Nat) : Int))"
    haves[i] = f"c_col{kind} {named}\n      {args} (hv {i} (by norm_num))"
    paths = (
        ["c{i}.left", "c{i}.right.left", "c{i}.right.right"]
        if cnt == 3
        else ["c{i}.left", "c{i}.right"]
    )
    for pth in paths:
        terms.append(pth.format(i=i))
        need.append(i)
    pos += cnt
assert pos == 104 and len(terms) == 104

