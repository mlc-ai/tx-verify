"""Generates `Proof/Wg0/Data/NumFrame.lean`: the frame lemmas of the chain of data facts
(`Gen/DataFacts.lean`). Each transition (`f_pst j`, `f_pld k`, `f_mst`, `f_vote`, `f_vh`, `f_join`,
`f_ost`) keeps the registers of its keep-set: they are live in the next facts and no key of the run's
facts. Run from the repository root."""

from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
K = ROOT / "Kernels/FlashMlaSparseDecodeH64/Proof/Wg0"
SC = [467, 3243, 2950, 2955, 2885]
SUMREG = [
    3242,
    3247,
    3252,
    3256,
    3260,
    3264,
    3268,
    3272,
    3276,
    3280,
    3284,
    3288,
    3292,
    3296,
    3300,
    3304,
]
PK = [394, 404, 414, 424, 434, 444, 454, 464]


def wreg(c):
    return 1009 + c + c // 8


def lst(xs):
    return "[" + ", ".join(map(str, xs)) + "]"


def args(n, extra=""):
    ps = " ".join(f"p{i}" for i in range(n))
    return "x m l mx sk lo hi mw" + (" " + ps if n else "") + extra


HEAD = """-- SPDX-License-Identifier: Apache-2.0
-- domain: consistent
module

public import Kernels.FlashMlaSparseDecodeH64.Proof.Wg0.Data.NumLk

@[expose] public section

/-! # The frames of the chain of data facts

Between two links of the chain (`Gen/DataFacts.lean`), a register of the keep-set `w0Keep*` is
live and no key of the run's facts, so it keeps its value. Generated by `Gen/w0num_frame_gen.py`. -/

namespace PTX.Kernels.FlashMlaSparseDecodeH64.Proof.Wg0.Data
open PTX PTX.Flow PTX.Proof PTX.Kernels.FlashMlaSparseDecodeH64.Proof.Wg0.Gen

noncomputable section

variable {x : BitVec 64} {m l mx sk : Value} {lo hi : List Value} {mw : Value}
  {p0 p1 p2 p3 p4 p5 p6 p7 : Value × Value} {pm : Value} {vt : Bool}

"""
out = [HEAD]
keeps = {}


def keep(name, xs):
    keeps[name] = xs
    import textwrap

    body = "\n".join(textwrap.wrap(lst(xs), 90, initial_indent="  ", subsequent_indent="   "))
    out.append(f"/-- The registers kept by `{name}`. -/\ndef w0Keep{name} : List Nat :=\n{body}\n")


def fr(name, nxt, prv, kp, anames, a_args, p_args):
    """frame lemma `nxt` over `prv` with keep-set `kp`; `anames` simp unfolds for the keys."""
    unf = ", ".join(anames + ["List.map_cons", "List.map_nil"])
    out.append(f"""theorem w0c_fr_{name} : ∀ r ∈ w0Keep{kp},
    lookupD ({nxt} {a_args}) r =\n      lookupD ({prv} {p_args}) r := by
  intro r hr
  unfold {nxt}
  exact lk_frame (K := w0Keep{kp}) (by decide)
    (by simp only [{unf}]; decide) hr
""")


masks_all = [wreg(c) for c in range(32)]
keep("P", masks_all + SC)
keep("Pld0", [wreg(c) for c in range(2, 32)] + SC)
for k in range(1, 9):
    keep(f"Pld{k}", [wreg(c) for c in range(4 * k + 2, 32)] + SC + SUMREG[: 2 * (k - 1)])
keep("Mst", SUMREG + SC)
keep("Vote", SUMREG + SC[:4])
keep("Vh", SUMREG + [479, 2885, 467, 3243, 2950, 2955])
keep("Join", SUMREG + [467, 3243, 2955, 2885])
keep("Ost", [2950, 2951, 2885, 467, 3243])

# the pst chain
for j in range(8):
    prev = "m_vm" if j == 0 else f"f_pst{j - 1}"
    fr(f"pst{j}", f"f_pst{j}", prev, "P", [f"pk{PK[j]}_facts1"], args(0), args(0))
fr("pld0", "f_pld0", "f_pst7", "Pld0", ["pk476_facts1"], args(0), args(0))
for k in range(1, 9):
    fr(f"pld{k}", f"f_pld{k}", f"s_pld{k - 1}", f"Pld{k}", [f"sum{k - 1}_facts1"], args(k), args(k))
fr("mst", "f_mst", "f_pld8", "Mst", ["rmax_facts2"], args(8), args(8))
fr("vote", "f_vote", "s_mld", "Vote", ["mld_facts1"], args(8, " pm"), args(8, " pm"))
# the cons form of f_vh and the explicit list of f_join
out.append(f"""theorem w0c_fr_vh : ∀ r ∈ w0KeepVh,
    lookupD (f_vh {args(8, " pm")}) r =\n      lookupD (f_vote {args(8, " pm")}) r := by
  intro r hr
  show lookupD ([_] ++ factsFrom _ _) r = _
  exact lk_frame (K := w0KeepVh) (by decide)
    (by simp only [List.map_cons, List.map_nil]; decide) hr
""")
out.append(f"""theorem w0c_fr_join : ∀ r ∈ w0KeepJoin,
    lookupD (f_join {args(8, " pm vt")}) r =\n      lookupD (f_vh {args(8, " pm")}) r := by
  intro r hr
  unfold f_join
  exact lk_frame (K := w0KeepJoin) (by decide)
    (by simp only [List.map_cons, List.map_nil]; decide) hr
""")
fr("ost", "f_ost", "f_join", "Ost", ["pw_facts4"], args(8, " pm vt"), args(8, " pm vt"))
# the snoc steps: the two new words of peer load k
for k in range(8):
    aname = "pk476_facts1" if k == 0 else f"sum{k - 1}_facts1"
    ka, kb = 3146 + 4 * k, 3148 + 4 * k
    out.append(f"""theorem w0c_sn_pld{k} (r : Nat) (ha : r ≠ {ka}) (hb : r ≠ {kb}) :
    lookupD (s_pld{k} {args(k + 1)}) r =\n      lookupD (f_pld{k} {args(k)}) r := by
  unfold s_pld{k}
  exact lk_snoc (by simp [ha, hb])

theorem w0c_hd_pld{k} : lookupD (s_pld{k} {args(k + 1)}) {ka} = p{k}.1 ∧
    lookupD (s_pld{k} {args(k + 1)}) {kb} = p{k}.2 := by
  unfold s_pld{k}
  refine ⟨lk_snoc_head ?_ (by simp [List.lookup]), lk_snoc_head ?_ (by simp [List.lookup])⟩
  all_goals
    unfold f_pld{k}
    simp only [{aname}, factsFrom, List.map_append, List.map_cons, List.map_nil]
    decide
""")
(K / "Data/NumFrame.lean").write_text(
    "\n".join(out) + "\nend\nend PTX.Kernels.FlashMlaSparseDecodeH64.Proof.Wg0.Data\n"
)
