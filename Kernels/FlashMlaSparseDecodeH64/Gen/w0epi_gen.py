"""Generate warpgroup 0's epilogue chain: its facts (`Gen/EpiFacts.lean`) and the data steps and
reaches of its sites (`Gen/EpiSites.lean`). The runs themselves are `Gen/Epi*.lean`
(`Tools/out_gen.py`, declarations `Gen/Out/wg0_epi*.json`); the loop's chain is
`Gen/w0site_gen.py`. `--check` compares the files with the generator's output."""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
GEN = ROOT / "Kernels/FlashMlaSparseDecodeH64/Proof/Wg0/Gen"
PFX = "Kernels.FlashMlaSparseDecodeH64.Proof.Wg0"
NS = "PTX.Kernels.FlashMlaSparseDecodeH64.Proof.Wg0.Data"

HEAD = """-- SPDX-License-Identifier: Apache-2.0
-- Generated by Kernels/FlashMlaSparseDecodeH64/Gen/w0epi_gen.py; do not edit.
-- domain: consistent
module

{imports}
@[expose] public section

namespace {ns}
open PTX PTX.Proof PTX.Flow PTX.Flow.Code PTX.Kernels.FlashMlaSparseDecodeH64

noncomputable section
"""
TAIL = "\nend\nend " + NS + "\n"


def imports(*mods):
    return "".join(f"public import {PFX}.{m}\n" for m in mods)


def facts_file():
    body = """
/-- The facts at the epilogue's first barrier (pc 1154) from the block's end values: the
zero-maximum predicate `%p138`, the masked maximum `%r23`, the masked sum `%r1269` (the run `e1`)
and the sink word. -/
def f_exit (V : Nat → Value) : List (Nat × Value) :=
  Gen.e1_facts1 V ++ [(2880, V 2880)]

/-- The values at the row-sum read's end (pc 1158): the facts of the barriers and the peer's
word (`%r1270`, id 1728). -/
def f_ex1 (V : Nat → Value) (pe : Value) : Nat → Value :=
  lookupD (f_exit V ++ [(1728, pe)])

/-- The facts after the row sum `%r24 = %r1269 + %r1270` (pc 1158): the sum (id 482), the
masked maximum (`%r23`, id 481) and the sink word. -/
def f_ew (V : Nat → Value) (pe : Value) : List (Nat × Value) :=
  Gen.e3_facts1 (f_ex1 V pe) ++ [(481, f_ex1 V pe 481), (2880, f_ex1 V pe 2880)]

/-- The facts at the LSE store (pc 1178): the LSE word `%r1275` (id 1733, the run `e4`: `lg2` of
the sum times `ln 2`, plus the maximum times `ln 2`, `+inf` where that is `-inf`) with the
intermediate words, and the facts of the final sum. -/
def f_lse (V : Nat → Value) (pe : Value) : List (Nat × Value) :=
  Gen.e4_facts1 (lookupD (f_ew V pe)) ++ f_ew V pe

/-- The factor word `%r2498` (id 2956) at the join of the zero-sum test (pc 1197): zero when the
sum is zero (the branch at pc 1191), else `1 / (sum + 2^(sink - maximum))` (the run `e6`). -/
def f_zj (V : Nat → Value) (pe : Value) : Value :=
  if predOf (Gen.e5_v1189 (lookupD (f_ew V pe))) then Gen.e5_v1190 (lookupD (f_ew V pe))
  else Gen.e6_v1196 (lookupD (f_ew V pe))

/-- The facts at the first output load (pc 1201): the factor, as the pair `%rd588`. -/
def f_fac (V : Nat → Value) (pe : Value) : List (Nat × Value) :=
  Gen.e7_facts1 (lookupD [(2956, f_zj V pe)])

/-- The registers of the words of output chunk `c` (the load's 64 destinations). -/
def eRegs : Nat → List Nat
  | 0 => List.range' 1745 64
  | 1 => List.range' 1916 64
  | 2 => List.range' 2086 64
  | _ => List.range' 2255 64

/-- The facts after output chunk `c`'s load (its wait): the factor pair and the loaded words `o`. -/
def f_ow (c : Nat) (V : Nat → Value) (pe : Value) (o : List Value) : List (Nat × Value) :=
  f_fac V pe ++ factsFrom (eRegs c) (lookupD ((eRegs c).zip o))

/-- The scaled words of output chunk `c` (its run's end facts: 32 packed bf16 pairs). -/
def es_out (c : Nat) (W : Nat → Value) : List (Nat × Value) :=
  match c with
  | 0 => Gen.es0_facts4 W
  | 1 => Gen.es1_facts4 W
  | 2 => Gen.es2_facts4 W
  | _ => Gen.es3_facts4 W

/-- The facts at the staging stores of output chunk `c`: the packed words and the factor pair. -/
def f_os (c : Nat) (V : Nat → Value) (pe : Value) (o : List Value) : List (Nat × Value) :=
  es_out c (lookupD (f_ow c V pe o)) ++ f_fac V pe

/-- **The facts of the epilogue's sites** from the facts of the loop's end `V` and the block's
reads. -/
def wFe (V : Nat → Value) (s : Site) (b : Blk) : List (Nat × Value) :=
  match s with
  | .ebar0 => f_exit V
  | .lse => f_lse V b.pe
  | .wsv => f_ew V b.pe
  | .old _ => f_fac V b.pe
  | .oldw c => f_ow c.val V b.pe b.o
  | .ost2 c _ => f_os c.val V b.pe b.o
  | _ => []
"""
    head = HEAD.format(
        imports=imports(
            "Gen.Epi", "Gen.Epi0", "Gen.Epi1", "Gen.Epi2", "Gen.Epi3", "Data.Blk", "Sites"
        ),
        ns=NS,
    )
    head = head.replace("PTX.Flow.Code ", "")
    return head + body + TAIL


INTRO = "  rintro ⟨⟨_, el, a0, l0, l1, cnt, bi, vs, pv, sl, ps, vt⟩, b, hist, ok⟩ ⟨⟩\n"
SUCC = "(fun c' h => congrArg wcls (by simpa [succOk] using h))"
NOST = "(by intro h; cases h)"
CA = "(scX L) b.m b.l b.mx b.sk"
R = "Reach kernel Assumptions.all L g"


def ds_lemma(pc, site, body):
    return (
        f"theorem ds_{pc} : ∀ d : D, d.c.site = {site} →\n"
        f"    DataStep (code P L g w) (dF L) d := by\n{INTRO}  exact {body}\n"
    )


def sites_file():
    mods = ["Gen.DataSteps1", "GenRules", "Data.Fac"] + [f"Gen.EpiOut{c}" for c in range(4)]
    out = [
        HEAD.format(
            imports=imports(*mods)
            + "public import Kernels.FlashMlaSparseDecodeH64.Proof.Lib.RulesFrame\n"
            + "public import Lemmas.Flow.ReachFrame\n"
            + "public import Tactics.KernelRfl\n",
            ns=NS,
        )
    ]
    out.append("variable {P : Params} {L : Launch} {g : Nat} {w : BitVec 64} {m0 : Mem0}\n")
    F = "(f_exit (lookupD (f_car x m l mx sk)))"
    # The three sites that keep the facts of the first run: both barriers and the staging store.
    for pc, what in [
        (1154, "the epilogue's first barrier"),
        (1155, "the sum's staging store"),
        (1156, "the second barrier"),
    ]:
        out.append(f"/-- After {what} (pc {pc}): the facts are kept. -/")
        out.append(
            f"theorem reach_{pc} (L : Launch) (g : Nat) (x : BitVec 64) (m l mx sk : Value) :\n"
            f"    {R} {pc + 1}\n        {F}\n        {F} :=\n"
            "  reach_frameSet rulesFrame (S := []) (by kernel_rfl)\n"
            "    (fun _ _ => w0SegFree _) (by kernel_rfl) fun _ h => h\n"
        )
    out.append("/-- The first barrier of the epilogue (pc 1154). -/")
    out.append(
        ds_lemma(
            1154,
            "(.ebar0)",
            "@ds_nx P L g w _ (.ebar0) (.est) _ rfl (by decide)\n"
            "    Flow.code_1154 (fun _ _ _ hf => fires_barSyncN_next hf) rfl\n"
            f"    {SUCC} {NOST}\n    fun _ => reach_1154 L g {CA}",
        )
    )
    out.append("/-- The staging store of the sum (pc 1155). -/")
    out.append(
        ds_lemma(
            1155,
            "(.est)",
            "@ds_st P L g w _ (.est) (.ebar1) _ rfl (by decide)\n"
            f"    Flow.code_1155 rfl rfl rfl\n    {SUCC} {NOST}\n"
            f"    fun _ => reach_1155 L g {CA}",
        )
    )
    out.append("/-- The second barrier of the epilogue (pc 1156). -/")
    out.append(
        ds_lemma(
            1156,
            "(.ebar1)",
            "@ds_nx P L g w _ (.ebar1) (.eld) _ rfl (by decide)\n"
            "    Flow.code_1156 (fun _ _ _ hf => fires_barSyncN_next hf) rfl\n"
            f"    {SUCC} {NOST}\n    fun _ => reach_1156 L g {CA}",
        )
    )
    V = "(lookupD (f_car (scX L) b.m b.l b.mx b.sk))\n      b.pe"
    out.append("/-- After the LSE store (pc 1178): the facts of the final sum. -/")
    out.append(
        "theorem reach_1178 (L : Launch) (g : Nat) (V : Nat → Value) (pe : Value) :\n"
        f"    {R} 1179\n        (f_lse V pe) (f_ew V pe) :=\n"
        "  reach_frameSet rulesFrame (S :=\n      [1179, 1180, 1181, 1182, 1183]) (by kernel_rfl)\n"
        "    (fun _ _ => w0SegFree _) (by kernel_rfl) fun _ h => ((holds_append _ _ _).mp h).2\n"
    )
    out.append("/-- After the poll's event (pc 1184): the facts are kept. -/")
    out.append(
        "theorem reach_1184 (L : Launch) (g : Nat) (V : Nat → Value) (pe : Value) :\n"
        f"    {R} 1185\n        (f_ew V pe) (f_ew V pe) :=\n"
        "  reach_frameSet rulesFrame (S :=\n      [1185, 1186]) (by kernel_rfl)\n"
        "    (fun _ _ => w0SegFree _) (by kernel_rfl) fun _ h => h\n"
    )
    out.append("/-- The LSE store (pc 1178). -/")
    out.append(
        ds_lemma(
            1178,
            "(.lse)",
            "@ds_st P L g w _ (.lse) (.wsv) _ rfl (by decide)\n"
            f"    Flow.code_1178 rfl rfl rfl\n    {SUCC} {NOST}\n"
            f"    fun _ => reach_1178 L g {V}",
        )
    )
    out.append("/-- The poll of the O-ready barrier (pc 1184). -/")
    out.append(
        ds_lemma(
            1184,
            "(.wsv)",
            "@ds_wait P L g w _ (.wsv) (.wsv) _ _ _ _ _ _ rfl (by decide) Flow.code_1184 rfl\n"
            "    (fun c' h => cls_mem h (by decide)) (by intro h; cases h)\n"
            f"    (hne_of (by kernel_rfl)) fun _ => reach_1184 L g {V}",
        )
    )
    return HEAD_NO_TAIL(out) + TAIL


OLD = [1201, 1361, 1519, 1676]
OLDW = [1202, 1362, 1520, 1677]
BASE = [1331, 1491, 1649, 1806]
OFPX = [1339, 1499, 1657, 1814]
OBAR = [1342, 1502, 1659, 1817]
OEL = [1350, 1507, 1664, 1822]
OTMA = [1358, 1516, 1673, 1831]
NEXT = [1361, 1519, 1676, 1832]
EVENTS = set(OLD + OLDW + OFPX + OBAR + OEL + OTMA + [1832, 1835, 1840])
for _b in BASE:
    EVENTS |= set(range(_b, _b + 8))
VV = "(lookupD (f_car (scX L) b.m b.l b.mx b.sk))\n      b.pe"


def wrap_list(items, width=12):
    rows = [", ".join(str(i) for i in items[j : j + width]) for j in range(0, len(items), width)]
    return ",\n      ".join(rows)


def frame_set(lo, hi):
    return [p for p in range(lo + 1, hi) if p not in EVENTS]


def es_keys(c):
    t = (GEN / f"Epi{c}.lean").read_text()
    body = t.split(f"def es{c}_facts0")[1].split("]\n")[0]
    return [int(k) for k in re.findall(r"\((\d+), V", body)]


def reach_frame(pc, S, src="f_fac V pe", dst="f_fac V pe", conv="fun _ h => h", extra=""):
    ss = wrap_list(S)
    sset = f"(S :=\n      [{ss}])" if S else "(S := [])"
    return (
        f"theorem reach_{pc} (L : Launch) (g : Nat) (V : Nat → Value) (pe : Value){extra} :\n"
        f"    {R} {pc + 1}\n        ({src}) ({dst}) :=\n"
        f"  reach_frameSet rulesFrame {sset}\n"
        f"    (by kernel_rfl) (fun _ _ => w0SegFree _) (by kernel_rfl)\n    ({conv})\n"
    )


def chunk_file(c):
    SUCC_ = "(fun c' h => congrArg wcls (by simpa [succOk] using h))"
    STE = "(fun c' hel h => congrArg wcls (by simpa [succOk, hel] using h))"
    mods = ["Gen.DataSteps1", "GenRules", "Data.Fac", "Data.OutStep"]
    out = [
        HEAD.format(
            imports=imports(*mods)
            + "public import Kernels.FlashMlaSparseDecodeH64.Proof.Lib.RulesFrame\n"
            + "public import Lemmas.Flow.ReachFrame\n"
            + "public import Tactics.KernelRfl\n",
            ns=NS,
        )
    ]
    out.append("variable {P : Params} {L : Launch} {g : Nat} {w : BitVec 64} {m0 : Mem0}\n")
    o, ow, b0 = OLD[c], OLDW[c], BASE[c]
    out.append(f"/-- After chunk {c}'s load (pc {o}). -/")
    out.append(
        f"theorem reach_{o} (L : Launch) (g : Nat) (V : Nat → Value) (pe : Value)\n"
        f"    (vals : List Value) (hl : vals.length = (eRegs {c}).length) :\n"
        f"    {R} {o + 1}\n        (f_fac V pe ++ (eRegs {c}).zip vals) (f_ow {c} V pe vals) :=\n"
        "  reach_frameSet rulesFrame (S := []) (by kernel_rfl) (fun _ _ => w0SegFree _)\n"
        "    (by kernel_rfl) fun _ h => (holds_append _ _ _).mpr ⟨((holds_append _ _ _).mp h).1,\n"
        "      holds_zip_lookupD ((holds_append _ _ _).mp h).2 hl⟩\n"
    )
    keys = es_keys(c)
    out.append(f"/-- After chunk {c}'s load wait (pc {ow}): the scaled words. -/")
    out.append(
        f"theorem reach_{ow} (L : Launch) (g : Nat) (V : Nat → Value) (pe : Value)\n"
        f"    (o : List Value) :\n    {R} {ow + 1}\n        (f_ow {c} V pe o) (f_os {c} V pe o) :=\n"
        "  Reach.weaken_start (SegD.reach (SegD.frame (H := f_fac V pe) rulesFrame\n"
        f"      (Gen.es{c}_run L g (lookupD (f_ow {c} V pe o))) rfl (by kernel_rfl) (by kernel_rfl)\n"
        f"      fun _ _ => w0SegFree _) Flow.code_{b0} trivial rfl fun _ _ h => h)\n"
        f"    (fun _ h => (holds_append _ _ _).mpr ⟨holds_lookupD (live :=\n      [{wrap_list(keys)}])\n"
        "      h (by kernel_rfl), ((holds_append _ _ _).mp h).1⟩)\n"
    )
    for k in range(8):
        pc = b0 + k
        last = k == 7
        out.append(f"/-- After chunk {c}'s staging store {k} (pc {pc}). -/")
        out.append(
            reach_frame(
                pc,
                [],
                "f_os " + f"{c} V pe o",
                "f_fac V pe" if last else f"f_os {c} V pe o",
                "fun _ h => ((holds_append _ _ _).mp h).2" if last else "fun _ h => h",
                "\n    (o : List Value)",
            ).replace(f"(f_os {c} V pe o) (f_fac V pe)", f"(f_os {c} V pe o)\n        (f_fac V pe)")
        )
    out.append(f"/-- After chunk {c}'s proxy fence (pc {OFPX[c]}). -/")
    out.append(reach_frame(OFPX[c], frame_set(OFPX[c], OBAR[c])))
    up = max(OEL[c], NEXT[c])
    out.append(f"/-- After chunk {c}'s named barrier (pc {OBAR[c]}). -/")
    out.append(reach_frame(OBAR[c], frame_set(OBAR[c], up)))
    out.append(f"/-- After chunk {c}'s election (pc {OEL[c]}). -/")
    out.append(reach_frame(OEL[c], frame_set(OEL[c], NEXT[c])))
    out.append(f"/-- After chunk {c}'s TMA store (pc {OTMA[c]}). -/")
    out.append(reach_frame(OTMA[c], frame_set(OTMA[c], NEXT[c])))
    # data steps
    ds = []
    ds.append(f"/-- The chunk {c}'s load (pc {o}). -/")
    ds.append(
        ds_lemma(
            o,
            f"(.old {c})",
            f"@ds_tc P L g w _ (.old {c}) (.oldw {c}) _ _ rfl (by decide)\n"
            f"    Flow.code_{o} rfl {SUCC_} {NOST}\n    (by decide) (hoff_of (by kernel_rfl))\n"
            f"    fun _ vals hl => reach_{o} L g {VV} vals hl",
        )
    )
    ds.append(f"/-- The wait for chunk {c}'s load (pc {ow}). -/")
    ds.append(
        ds_lemma(
            ow,
            f"(.oldw {c})",
            f"@ds_nx P L g w _ (.oldw {c}) (.ost2 {c} 0) _ rfl (by decide)\n"
            f"    Flow.code_{ow} (fun _ _ _ hf => fires_tcWaitLd_next hf) rfl\n"
            f"    {SUCC_} {NOST}\n    fun _ => reach_{ow} L g {VV} b.o",
        )
    )
    for k in range(8):
        pc = b0 + k
        nxt = f"(.ost2 {c} {k + 1})" if k < 7 else f"(.ofpx {c})"
        ds.append(f"/-- Chunk {c}'s staging store {k} (pc {pc}). -/")
        ds.append(
            ds_lemma(
                pc,
                f"(.ost2 {c} {k})",
                f"@ds_stE P L g w _ (.ost2 {c} {k}) {nxt} _ 4 rfl (by decide)\n"
                f"    Flow.code_{pc} rfl rfl rfl (by simp [Control.D.acc])\n"
                f"    {STE} (fun _ => rfl) rfl\n    {STE}\n"
                f"    (fun _ _ _ _ => reach_{pc} L g {VV} b.o)",
            )
        )
    ds.append(f"/-- Chunk {c}'s proxy fence (pc {OFPX[c]}). -/")
    ds.append(
        ds_lemma(
            OFPX[c],
            f"(.ofpx {c})",
            f"@ds_nx P L g w _ (.ofpx {c}) (.obar {c}) _ rfl (by decide)\n"
            f"    Flow.code_{OFPX[c]} (fun _ _ _ hf => Option.some.inj (fires_fence_proxy hf).2) rfl\n"
            f"    {SUCC_} {NOST}\n    fun _ => reach_{OFPX[c]} L g {VV}",
        )
    )
    ds.append(f"/-- Chunk {c}'s named barrier (pc {OBAR[c]}). -/")
    ds.append(
        ds_lemma(
            OBAR[c],
            f"(.obar {c})",
            f"@ds_nx P L g w _ (.obar {c}) (.oel {c}) _ rfl (by decide)\n"
            f"    Flow.code_{OBAR[c]} (fun _ _ _ hf => fires_barSyncN_next hf) rfl\n"
            f"    (fun c' h => cls_obar _ rfl h) {NOST}\n    fun _ => reach_{OBAR[c]} L g {VV}",
        )
    )
    ds.append(f"/-- Chunk {c}'s election (pc {OEL[c]}). -/")
    ds.append(
        ds_lemma(
            OEL[c],
            f"(.oel {c})",
            f"@ds_el P L g w _ (.oel {c}) (.otma {c}) _ _ _ _ rfl (by decide)\n"
            f"    Flow.code_{OEL[c]} rfl (fun c' h => cls_oel _ rfl h) {NOST}\n"
            f"    (hne_of (by kernel_rfl)) (hne_of (by kernel_rfl))\n"
            f"    fun _ => reach_{OEL[c]} L g {VV}",
        )
    )
    ds.append(f"/-- Chunk {c}'s TMA store (pc {OTMA[c]}). -/")
    nxs = "(.old 1)"
    rr = f"reach_{OTMA[c]} L g {VV}"
    ds.append(
        ds_lemma(
            OTMA[c],
            f"(.otma {c})",
            f"@ds_nx P L g w _ (.otma {c}) {nxs} _ rfl (by decide)\n"
            f"    Flow.code_{OTMA[c]} (fun _ _ _ hf => fires_cpTensorStore_next hf) rfl\n"
            f"    (fun c' h => cls_otma _ rfl h) {NOST}\n    fun _ => {rr}",
        )
    )
    return "\n".join(out) + "\n" + "\n".join(ds) + TAIL


def HEAD_NO_TAIL(out):
    return "\n".join(out)


def main():
    outs = {GEN / "EpiFacts.lean": facts_file(), GEN / "EpiSites.lean": sites_file()}
    for c in range(4):
        outs[GEN / f"EpiOut{c}.lean"] = chunk_file(c)
    for path, text in outs.items():
        if "--check" in sys.argv:
            if not path.exists() or path.read_text() != text:
                sys.exit(f"w0epi_gen: {path.relative_to(ROOT)} is stale")
        else:
            path.write_text(text)


if __name__ == "__main__":
    main()
