MAC = """open Lean in
set_option hygiene false in
/-- The condition of the peer pack `pk<394 + 10 k>`: its four words are `halfB`. -/
local macro "w0k_pk " k:num : command => do
  let k := k.getNat
  let n := 394 + 10 * k
  let id (s : String) := mkIdent (.mkSimple s)
  let num (i : Nat) := Syntax.mkNumLit (toString i)
  let stage := if k = 0 then id "m_vm" else id s!"f_pst{k - 1}"
  let at_ := id s!"w0c_lo_at{k}"
  let lo (i : Nat) := num (4 * k + i)
  `(theorem $(id s!"w0k_pk{n}") {sc : ℝ} {w : W0Words} (hw : W0Ok sc w) (x : BitVec 64)
      (m l mx sk : Value) :
      $(id s!"pk{n}_cond") (lookupD ($stage x m l mx sk w.lo w.hi w.mw)) := by
    refine $(id s!"pk{n}_cond_of_reads") _ ?_ ?_ ?_ ?_
    · rw [$at_ hw.loLen $(lo 0) (by norm_num) (by norm_num)]
      exact (halfB_iff _).mpr (hw.lo $(lo 0) (by norm_num))
    · rw [$at_ hw.loLen $(lo 1) (by norm_num) (by norm_num)]
      exact (halfB_iff _).mpr (hw.lo $(lo 1) (by norm_num))
    · rw [$at_ hw.loLen $(lo 2) (by norm_num) (by norm_num)]
      exact (halfB_iff _).mpr (hw.lo $(lo 2) (by norm_num))
    · rw [$at_ hw.loLen $(lo 3) (by norm_num) (by norm_num)]
      exact (halfB_iff _).mpr (hw.lo $(lo 3) (by norm_num)))

"""

# ---- the conditions
A = (
    """-- SPDX-License-Identifier: Apache-2.0
-- Generated by Kernels/FlashMlaSparseDecodeH64/Gen/w0cond_blk_gen.py; do not edit.
-- domain: valid-rows
module

public import Kernels.FlashMlaSparseDecodeH64.Proof.Wg0.Gen.NumPld
public import Kernels.FlashMlaSparseDecodeH64.Proof.Wg0.Gen.NumLo
public import Kernels.FlashMlaSparseDecodeH64.Proof.Wg0.Gen.CondMask
public import Kernels.FlashMlaSparseDecodeH64.Proof.Wg0.Gen.CondPeer
public import Kernels.FlashMlaSparseDecodeH64.Proof.Wg0.Gen.CondSum

@[expose] public section

/-! # The conditions of the runs of a valid block: mask, peer packs, peer sums

At the stage a run starts from, the facts the run reads are those of a valid block (`W0Ok`): the
masks' source words are clean, the peer packs' words are `halfB` (`Assumptions.scoreHalf`), and the
peer sums' sources read as numbers. Generated by `w0cond_blk_gen.py`. -/

"""
    + OPEN
    + MAC
)
out = [A]
out.append("""/-- The condition of the mask run at the score loads' stage. -/
theorem w0k_mask {sc : ℝ} {w : W0Words} (hw : W0Ok sc w) (x : BitVec 64) (m l mx sk : Value)
    (lo : List Value) : mask_cond (lookupD (s_vm x m l mx sk lo w.hi w.mw)) := by
  obtain ⟨n, hn, hmwn⟩ := hw.mask
  refine mask_cond_of_reads _ n hn ?_ fun i hi => ?_
  · rw [w0c_vm_mw, hmwn]
  · rw [w0c_vm_hi x m l mx sk lo w.hi w.mw hw.hiLen i hi]
    exact (hw.hi i hi).1.1

""")
out.append("\n".join(f"w0k_pk {k}" for k in range(8)) + "\n\n")
out.append("""/-- The condition of `pk474` (none to meet). -/
theorem w0k_pk474 (V : Nat → Value) : pk474_cond V := pk474_cond_of_reads V

/-- The condition of `pk476`: the first two masked words have four bytes. -/
theorem w0k_pk476 {sc : ℝ} {w : W0Words} (hw : W0Ok sc w) (x : BitVec 64) (m l mx sk : Value)
    (lo : List Value) : pk476_cond (lookupD (f_pst7 x m l mx sk lo w.hi w.mw)) := by
  refine pk476_cond_of_reads _ ?_ ?_
  · rw [w0c_pk 1009 (by decide)]
    exact (w0b_hM hw x m l mx sk lo 0 (by norm_num)).1.1
  · rw [w0c_pk 1010 (by decide)]
    exact (w0b_hM hw x m l mx sk lo 1 (by norm_num)).1.1

""")
for k in range(8):
    c = 4 * k
    pk = pws(k + 1)
    got = "hj, pa, pb, h2, h3, h4, h5" if k < 7 else "hj, pa, pb, h2, h3"
    out.append(f"""/-- The condition of the peer sum `sum{k}`. -/
theorem w0k_sum{k} {{sc : ℝ}} {{w : W0Words}} (hw : W0Ok sc w) (x : BitVec 64)
    (m l mx sk : Value) (lo : List Value) :
    sum{k}_cond (lookupD (s_pld{k} x m l mx sk lo w.hi w.mw {pk})) := by
  obtain ⟨{got}⟩ := w0b_pld{k} hw x m l mx sk lo
""")
    if k < 7:
        out.append(
            f"  exact sum{k}_cond_of_reads _ (w0A w) (w0PeerF w) hj (w0A_lane w {c})\n"
            f"    (w0A_lane w {c + 1}) h2 h3 pa pb h4 h5\n\n"
        )
    else:
        out.append(
            f"  exact sum{k}_cond_of_reads _ (w0A w) (w0PeerF w) hj (w0A_lane w {c})\n"
            f"    (w0A_lane w {c + 1}) h2 h3 pa pb\n\n"
        )
out.append(CLOSE)
(D / "CondBlkA.lean").write_text("".join(out))
