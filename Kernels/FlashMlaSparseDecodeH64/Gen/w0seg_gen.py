"""Strict run windows of warpgroup 0's data-only windows.

For every tolerant `reach_<pc>` of `Proof/Wg0/Gen/{DataSites,EpiOut}*.lean` whose window is a chain of
value runs (`Gen.<run>_run`) between two events, writes `segS_<pc>`: the exact segment (`Seg`) from the
facts after the event to the facts before the next event, control facts `Hc`, `Hc'` carried across the
runs (the window's instructions write data registers only), under the runs' conditions
`Gen.<run>_cond (lookupD ..)` as hypotheses. Output: `Proof/Wg0/Gen/SegS<n>.lean`.
"""

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
GEN = ROOT / "Kernels/FlashMlaSparseDecodeH64/Proof/Wg0/Gen"
NS = "Kernels.FlashMlaSparseDecodeH64.Proof.Wg0"
# the windows of data registers only (every instruction reads and writes data registers)
DATA_ONLY = (
    [289]
    + [403 + 10 * k for k in range(7)]
    + [475]
    + [477 + 5 * k for k in range(7)]
    + [512]
    + [717, 818, 919, 1020, 1202, 1362, 1520, 1677]
    + [572]
)
# windows that write a control register: the successor's control facts frame without it
ERASE = {572: 1112}
SRC = {
    "DataSites0": "SegS0",
    "DataSites1": "SegS1",
    "DataSites2": "SegS2",
    "EpiOut0": "SegS3",
    "EpiOut1": "SegS4",
    "EpiOut2": "SegS5",
    "EpiOut3": "SegS6",
}


def balanced(text, pos):
    """The end of the balanced group starting at `pos` (an opening bracket)."""
    depth = 0
    for i in range(pos, len(text)):
        if text[i] in "(⟨[":
            depth += 1
        elif text[i] in ")⟩]":
            depth -= 1
            if depth == 0:
                return i + 1
    raise ValueError


def args2(text, pos):
    """Two parenthesised arguments after `pos`."""
    out = []
    for _ in range(2):
        while text[pos] in " \n":
            pos += 1
        e = balanced(text, pos)
        out.append((pos, e))
        pos = e
    return out


def conv_body(body):
    # drop the final event of each run chain: `SegD.reach X Flow.code_N trivial rfl hG` -> `X`
    body = re.sub(r"SegD\.reach \(", "(", body)
    body = re.sub(r"\s*Flow\.code_\d+ trivial rfl fun _ _ h => h\)", ")", body)
    body = body.replace("SegD.reach_then", "SegD.comp").replace(
        "Reach.weaken_start", "SegD.weaken_start"
    )
    return body


def conv(b):
    m = re.search(
        r"theorem reach_(\w+) (.*?):\s*\n\s*Reach kernel Assumptions\.all L g (\d+)\s*", b, re.S
    )
    name, binders, p = m.groups()
    (f0, f1), (g0, g1) = args2(b, m.end())
    F, G = b[f0:f1], b[g0:g1]
    m = re.compile(r":=\s*\n").search(b, g1)
    body = b[m.end() :]
    runs = re.findall(r"Gen\.(\w+)_run L g (\(lookupD \(.*?\)\))\)", body, re.S)
    runs = [(n, re.sub(r"\s+", " ", a)) for n, a in runs]
    end = re.findall(r"Flow\.code_(\d+)", b)[-1]
    # outermost `Reach.weaken_start A W`
    assert body.lstrip().startswith("Reach.weaken_start")
    start = body.index("Reach.weaken_start") + len("Reach.weaken_start")
    (a0, a1), (w0, w1) = args2(body, start)
    A, W = conv_body(body[a0:a1]), body[w0:w1]
    conds = [f"(c{i + 1} : Gen.{n}_cond {a})" for i, (n, a) in enumerate(runs)]
    cnd = "c1" if len(runs) == 1 else "⟨c1, c2⟩"
    live = f"Control.ctlLive {end}"
    if int(name) in ERASE:
        live = f"({live}).erase {ERASE[int(name)]}"
    head = (
        f"theorem segS_{name} {binders.rstrip()}\n    (Hc Hc' : List (Nat × Value))\n"
        f"    (hk : Hc'.map Prod.fst = {live})\n"
        f"    (hsub : ∀ R, Holds R Hc → Holds R Hc')\n    " + "\n    ".join(conds) + " :\n"
        f"    ∃ n, Seg kernel Assumptions.all L g n {p}\n      (Hc ++ {F[1:-1]}) {end}\n"
        f"      (Hc' ++ {G[1:-1]}) :=\n"
    )
    tail = (
        f"  windowS_close (SegD.frame (H := Hc') rulesFrame\n      {A}\n"
        f"      rfl (by kernel_rfl) (by rw [hk]; kernel_rfl) fun _ _ => w0SegFree _)\n"
        f"    {cnd}\n    (fun R h => {W} R (windowS_snd h)) hsub (fun _ h => h)\n"
    )
    return "/-- The window after the event at pc " + name + ". -/\n" + head + tail


def main():
    for src, out in SRC.items():
        text = (GEN / f"{src}.lean").read_text()
        text = re.sub(r"\nend\nend PTX[\w.]*\s*$", "\n", text)
        parts = []
        for b in re.split(r"\n(?=/-- |theorem |def )", text):
            m = re.search(r"theorem reach_(\d+) ", b)
            if m and int(m.group(1)) in DATA_ONLY:
                parts.append(conv(b))
        if not parts:
            continue
        head = (
            "-- SPDX-License-Identifier: Apache-2.0\n-- Generated by Kernels/FlashMlaSparseDecodeH64/Gen/"
            "w0seg_gen.py; do not edit.\n-- domain: valid-rows\nmodule\n\n"
            f"public import {NS}.Gen.{src}\npublic import {NS}.Data.SegLib\n"
            f"public import {NS}.GenRules\npublic import Tactics.KernelRfl\n\n"
            "@[expose] public section\n\n"
            "namespace PTX.Kernels.FlashMlaSparseDecodeH64.Proof.Wg0.Data\n"
            "open PTX PTX.Proof PTX.Flow PTX.Flow.Code PTX.Kernels.FlashMlaSparseDecodeH64\n\n"
            "noncomputable section\n\n"
        )
        (GEN / f"{out}.lean").write_text(
            head
            + "\n".join(parts)
            + "\nend\nend PTX.Kernels.FlashMlaSparseDecodeH64.Proof.Wg0.Data\n"
        )


if __name__ == "__main__":
    main()
