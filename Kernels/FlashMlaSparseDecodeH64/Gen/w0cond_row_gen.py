"""Generates `Proof/Wg0/Gen/CondSum.lean` and `Gen/CondRmax.lean`: the strict conditions
(`sum<k>_cond`, `rmax_cond`: no item's outcome is a fault) of the peer sums and the row maximum,
from the value equalities of `Data/NumSum.lean` and `Data/NumRow.lean`. Run from the root."""

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
K = ROOT / "Kernels/FlashMlaSparseDecodeH64/Proof/Wg0"
SUMREG = [
    3242,
    3247,
    3252,
    3256,
    3260,
    3264,
    3268,
    3272,
    3276,
    3280,
    3284,
    3288,
    3292,
    3296,
    3300,
    3304,
]


def head(imp, name):
    return f"""-- SPDX-License-Identifier: Apache-2.0
-- Generated by Kernels/FlashMlaSparseDecodeH64/Gen/w0cond_row_gen.py; do not edit.
-- domain: valid-rows
module

public import Kernels.FlashMlaSparseDecodeH64.Proof.Wg0.Data.{imp}
public import Kernels.FlashMlaSparseDecodeH64.Proof.Wg0.Data.StrictLib2

@[expose] public section

namespace PTX.Kernels.FlashMlaSparseDecodeH64.Proof.Wg0.Data
open PTX PTX.Flow PTX.Proof PTX.Assumption PTX.Kernels.FlashMlaSparseDecodeH64.Proof.Wg0.Gen
  PTX.Kernels.FlashMlaSparseDecodeH64.Proof.Wg0

noncomputable section

set_option linter.unusedSimpArgs false

"""


SEP = ",\n    "
END = "\nend\nend PTX.Kernels.FlashMlaSparseDecodeH64.Proof.Wg0.Data\n"
rowsrc = (K / "Gen/Row.lean").read_text()
numsum = (K / "Data/NumSum.lean").read_text()


def items_of(name):
    m = re.search(r"def %s : List XItem := \[\n(.*?)\n\]\n" % name, rowsrc, re.S)
    return [
        re.sub(r"\s+", " ", it.strip().rstrip(",")) for it in re.split(r",\n  (?=\.)", m.group(1))
    ]


# sums
out = head("NumSum", "")
for k in range(8):
    m = re.search(r"theorem w0s_sum%d (.*?) :\n    lookupD" % k, numsum, re.S)
    hyps = m.group(1)
    its = items_of(f"sum{k}_items0")

    def regs(it):
        return list(map(int, re.findall(r"\d+", it)))

    extra = ""
    term = [
        "cond_of_okVal st.1 (by intro h; cases h)",
        "And.intro h2.1.1 h3.1.1",
        "cond_of_okVal st.2 (by intro h; cases h)",
    ]
    if len(its) == 4:
        _, a, b = regs(its[3])
        extra = f"\n    {{e4 e5 : EReal}} (h4 : Rd (V {a}) e4) (h5 : Rd (V {b}) e5)"
        term.append("And.intro h4.1.1 h5.1.1")
    out += (
        f"/-- The condition of `sum{k}`. -/\ntheorem sum{k}_cond_of_reads {hyps}{extra} :\n"
        f"    xCond (lookupD (sum{k}_facts0 V)) sum{k}_items0 := by\n"
        f"  have st := w0s_sum{k} V A Y hj l0 l1 h2 h3 hp0 hp1\n"
        f"  simp only [sum{k}_items0, xCond]\n"
        f"  exact ⟨{SEP.join(term)}, trivial⟩\n\n"
    )
(K / "Gen/CondSum.lean").write_text(out.rstrip() + "\n" + END)

# rmax
numrow = (K / "Data/NumRow.lean").read_text()
i0 = numrow.index("theorem w0r_rmax")
hyps = (
    numrow[i0 + len("theorem w0r_rmax") : numrow.index("    Rd (lookupD", i0)]
    .rstrip()
    .rstrip(":")
    .rstrip()
)
body = numrow[
    numrow.index(":= by\n", numrow.index("    Rd (lookupD", i0)) + 6 : numrow.index("  have hfin")
]
its0, its1 = items_of("rmax_items0"), items_of("rmax_items1")
regs = {}
terms = []
cnt = 0
base = 0
for it in its0 + its1:
    ns = list(map(int, re.findall(r"\d+", re.sub(r"\.f32imm \d+", ".imm", it))))
    if it.startswith(".base (.unpack"):
        lo, hi, a = ns
        j = SUMREG.index(a)
        terms.append(f"upk_cond e{j} (erealValue_bytes _) (erealValue_bytes _)")
        regs[lo], regs[hi] = f"c{2 * j}", f"c{2 * j + 1}"
    elif "maxFI" in it and ".f32imm" in it:
        d, a = ns[0], ns[1]
        if "m0_" in "".join(regs.values()) and base == 0 and cnt == 16:
            base = 16
            cnt = 0
        cnt += 1
        terms.append(f"c_maxI {regs[a]}")
        regs[d] = f"m{base}_{cnt}"
    elif "maxFI" in it:
        d, a, b = ns[0], ns[1], ns[2]
        if a == 1075:
            terms.append(f"c_max (by decide) {regs[a]} {regs[b]}")
            regs[d] = "mm"
        else:
            cnt += 1
            terms.append(f"c_max (by decide) {regs[a]} {regs[b]}")
            regs[d] = f"m{base}_{cnt}"
    elif "mulI" in it:
        terms.append(f"c_scale (by decide) hsc {regs[1108]} h467")
    else:
        raise SystemExit(it)
n0 = len(its0)
out = head("NumRow", "")
ths = []
for k, (a, b) in enumerate([(0, n0), (n0, len(terms))]):
    out += (
        f"/-- The condition of piece {k} of the row maximum. -/\n"
        f"theorem rmax{k}_cond_of_reads {hyps} :\n"
        f"    xCond (lookupD (rmax_facts{k} V)) rmax_items{k} := by\n"
        + body
        + f"  simp only [rmax_items{k}, xCond]\n"
        f"  exact ⟨{SEP.join(terms[a:b] + ['trivial'])}⟩\n\n"
    )
names = " ".join(re.findall(r"\((\w+(?: \w+)*) :", hyps.replace("\n", " ")))
args = "V S sc hsc h467 hV hS"
out += (
    f"/-- The row maximum's run has no fault outcome. -/\ntheorem rmax_cond_of_reads {hyps} :\n"
    f"    rmax_cond V :=\n  ⟨rmax0_cond_of_reads {args}, rmax1_cond_of_reads {args}⟩\n"
)
(K / "Gen/CondRmax.lean").write_text(out + END)
