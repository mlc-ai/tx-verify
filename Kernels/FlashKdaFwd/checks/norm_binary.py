"""Extract the normalized instruction listings of the two compiled CUDA preparation kernels."""

import argparse
import hashlib
import json
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LINE = re.compile(r"\s*/\*([\da-f]+)\*/\s+(.*?)\s*;\s*/\* (0x[\da-f]+) \*/")


def extract(binary, name):
    listing = subprocess.check_output(
        ["cuobjdump", "--dump-sass", "--function", name, str(binary)], text=True
    )
    instructions = {}
    for line in listing.splitlines():
        if match := LINE.fullmatch(line):
            address, code, low_word = match.groups()
            instructions[int(address, 16)] = (" ".join(code.split()), int(low_word, 16))
    pc_list = [0x3C0, 0xA40, *range(0xAB0, 0xF00, 16)]
    for pc in (0xE80, 0xE90):
        if instructions[pc][1] >> 32 != 0x358637BD:
            raise ValueError(f"{binary} has a different addend at {pc:#x}")
    with binary.open("rb") as source:
        digest = hashlib.file_digest(source, "sha256").hexdigest()
    return digest, [instructions[pc][0] for pc in pc_list]


def render(sm100, sm103):
    manifest = json.loads((ROOT / "manifest.json").read_text())
    name = manifest["ptx"]["entries"][9]["entry_name"]
    first_digest, first = extract(sm100, name)
    second_digest, second = extract(sm103, name)
    if first != second:
        raise ValueError("the two target binaries have different instruction streams here")
    header = (
        "-- SPDX-License-Identifier: Apache-2.0\n"
        "-- Generated by checks/norm_binary.py from the CUDA disassembler.\n"
        "module\n\n@[expose] public section\nnamespace FlashKda.Binary\n\n"
    )
    # Register reuse flags affect operand caching, while register names identify data.
    tokens = [line.replace(",", "").replace(".reuse", "").split() for line in first]
    code = ",\n".join("   " + json.dumps(words) for words in tokens)
    return (
        header
        + f'def sm100Digest := "{first_digest}"\ndef sm103Digest := "{second_digest}"\n\n'
        + f"def instructions : List (List String) :=\n  [\n{code}]\n\nend FlashKda.Binary\n"
    )


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("sm100", type=Path)
    parser.add_argument("sm103", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    result = render(args.sm100, args.sm103)
    output = ROOT / "Data" / "NormMachine.lean"
    if args.check:
        if output.read_text() != result:
            raise SystemExit("the compiled instructions differ from the Lean input")
    else:
        output.write_text(result)
