"""Check the extrema of the exhaustive device sweep with exact integer arithmetic."""

import argparse
import json
import subprocess
from fractions import Fraction
from pathlib import Path

DENOMINATOR = 1 << 72
TRILLION = 10**12


def finite_field(word):
    assert 0x00800000 <= word < 0x7F800000
    mantissa = (1 << 23) + (word & 0x007FFFFF)
    return mantissa * Fraction(2) ** ((word >> 23) - 150)


def verify(record):
    assert record["visited"] == 254 * 2**23 and record["invalid"] == 0
    limits = []
    for name, sign in [("below", -1), ("above", 1)]:
        item = record[name]
        squared = finite_field(item["input"]) * finite_field(item["output"]) ** 2
        assert squared == 1 + Fraction(sign * item["delta"], DENOMINATOR)
        limits.append(squared)

    # Find the least whole part per trillion that suffices, without evaluating a square root.
    def covers(parts):
        e = Fraction(parts, TRILLION)
        return (1 - e) ** 2 <= limits[0] and limits[1] <= (1 + e) ** 2

    lo, hi = 0, 10**6
    assert covers(hi)
    while lo < hi:
        mid = (lo + hi) // 2
        if covers(mid):
            hi = mid
        else:
            lo = mid + 1
    assert Fraction(lo, TRILLION) ** 10 <= Fraction(1, 2**229)
    return {**record, "relative_error_parts_per_trillion": lo}


def lean_data(record):
    lines = [
        "-- SPDX-License-Identifier: Apache-2.0",
        "-- Generated by checks/root_sweep.py from the exhaustive GB300 sweep.",
        "module",
        "@[expose] public section",
        "namespace FlashKda.RootSweep",
        f"def visited := {record['visited']}",
        f"def invalid := {record['invalid']}",
        f"def parts := {record['relative_error_parts_per_trillion']}",
    ]
    for name in ["below", "above"]:
        e = record[name]
        lines.append(f"def {name} : Nat × Nat × Nat :=")
        lines.append(f"  (0x{e['input']:08x}, 0x{e['output']:08x}, {e['delta']})")
    return "\n".join([*lines, "end FlashKda.RootSweep", ""])


if __name__ == "__main__":
    cli = argparse.ArgumentParser(description=__doc__)
    group = cli.add_mutually_exclusive_group(required=True)
    group.add_argument("--binary", type=Path)
    group.add_argument("--record", type=Path)
    cli.add_argument("--lean-data", action="store_true")
    args = cli.parse_args()
    if args.binary:
        listing = subprocess.check_output(["cuobjdump", "--dump-sass", args.binary], text=True)
        assert listing.count("MUFU.RSQ ") == 1, "expected one reciprocal square root in the sweep"
        source = json.loads(subprocess.check_output([args.binary.resolve()], text=True))
    else:
        source = json.loads(args.record.read_text())
    result = verify(source)
    if args.record:
        assert result == source
    if args.lean_data:
        print(lean_data(result), end="")
    else:
        print(json.dumps(result, indent=2))
