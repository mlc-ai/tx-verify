def render_sites(tb):
    out = [HEAD]
    out.append("public import Kernels.FlashKdaFwd.Proof.Values.Loads")
    out.append("public import Kernels.FlashKdaFwd.Proof.Values.Sites")
    out.append("")
    out.append("@[expose] public section")
    out.append("")
    out.append("/-! # The matrix sites of a tile and their register tables (generated)")
    out.append("")
    out.append(
        "From `Gen/Tables/matrix_table.json`: the site of each matrix ordinal, the source of each"
    )
    out.append(
        "`ldmatrix`, `stmatrix` and scalar load, the address forms, the register table of each"
    )
    out.append(
        "matrix instruction and scalar load of the tile loop (`T<pc>`), and the program points of a"
    )
    out.append("lane by the number of matrix events it has made in its tile (`points`). -/")
    out.append("")
    out.append("namespace PTX.Kernels.FlashKdaFwd.Proof.Values.Gen")
    out.append("")
    out.append("/-- The site of the matrix event of each ordinal of a tile, in program order. -/")
