"""Generator of the value induction over the tile loop.

Inputs: the register table `Gen/Tables/matrix_table.json` (made and checked by
`Gen/matrix_table.py`) and the generated thread machine (`Proof/Thread`: `After/` says which run
of scalar instructions follows a site, `Run/` defines the runs, `Next.lean` the load functions).
Outputs, under `Proof/Values/Gen/`:

* `Sites.lean`: the site of each of the 182 matrix ordinals of a tile (`ordSites`); what each
  `ldmatrix`, `stmatrix` and scalar load reads or writes (`loadSrcs`, `storeSrcs`, `scalarSrcs`);
  the address forms (`loadForms`, `storeForms`, `scalarForms`); the table of the data registers
  live at each matrix instruction and scalar load, with their forms (`T<pc>`, `tables`); and the
  program points of a lane by the number of matrix events it has made in its tile (`points`).
* `Runs.lean`: for each of the 22 runs of scalar instructions of the tile loop, the table before
  it (`M<pc>`), the registers it reads and leaves (`I<pc>`, `O<pc>`) and its specification
  (`r<pc>_spec`: no instruction faults, and the registers it leaves hold their forms), found by
  executing the run on forms here and proved with the rules of `Proof/Values/Scalar.lean`.
* `Steps.lean`: for each ordinal `n`, the step across its matrix event (`mstep_n`), what holds at
  each program point of that count (`lpts_n`), and the operands of a multiply-accumulate
  instance (`mops_n`), each an application of a lemma of `Proof/Values/Induction.lean`; and the
  dispatchers `mstep`, `lpts`, `mops`, `store_next`.

    python3 Kernels/FlashKdaFwd/Gen/values.py                       # write the three files
    python3 Kernels/FlashKdaFwd/Gen/values.py --check               # verify they are fresh
    python3 Kernels/FlashKdaFwd/Gen/values.py --thread-src <dir>    # read another thread machine

The script fails (and writes nothing) if a run reads a register without a form, if an
instruction of a run meets operands whose forms no rule covers, or if the table disagrees with
the shapes it expects (the source registers of a store, the operands of an `mma.sync`).

The generated files are compiled like the hand-written ones of `Proof/Values/`. Measured:
`Sites.lean` 50 s (200 tables of 128 to 190 registers), `Runs.lean` 9 s, `Steps.lean` 60 s (550
theorems).
"""

