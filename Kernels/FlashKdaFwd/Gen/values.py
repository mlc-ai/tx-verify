def transitions(tb, th):
    """Every event of a lane inside a tile that has a successor point, in program order:
    a dictionary per event with the point before it, the point after it, the registers it writes
    with their forms, and the run that follows it (if any)."""
    out = []
    for n in range(182):
        pts = tb.points(n)
        for ip, pt in enumerate(pts):
            kind, j, pc = pt
            tr = {"n": n, "ip": ip, "pt": pt, "run": None, "dst": []}
            if ip + 1 < len(pts):
                tr["next"], tr["next_n"], tr["next_ip"] = pts[ip + 1], n, ip + 1
            elif n < 181:
                tr["next"], tr["next_n"], tr["next_ip"] = tb.points(n + 1)[0], n + 1, 0
            else:
                tr["next"] = None
            row = tb.rows[n]
            if kind == "ld":
                s = tb.scal[j - 159]
                tr["site"] = f"load_{j}"
                tr["dst"] = [(tb.rid(s["dst"][0]), tb.regs[s["dst"][0]]["desc"])]
                tr["run"] = th.run_of(tr["site"])
            elif kind == "wr":
                tr["site"] = f"matrixStoreWr_{j}"
                tr["run"] = th.run_of(tr["site"])
            elif kind == "rd":
                tr["site"] = f"matrixLoad_{j}"
            elif kind == "mx":
                tr["site"] = f"matrixLoadMx_{j}"
                tr["dst"] = [(tb.rid(r), tb.regs[r]["desc"]) for r in row["dst"]]
            elif kind == "mma":
                tr["site"] = f"warpMma_{j}"
                tr["dst"] = [(tb.rid(r), tb.regs[r]["desc"]) for r in row["D"]["regs"]]
                tr["run"] = th.run_of(tr["site"])
            elif kind == "mov":
                tr["site"] = f"matrixMove_{j}"
                tr["dst"] = [(tb.rid(r), tb.regs[r]["desc"]) for r in row["dst"]]
            else:
                tr["site"] = f"matrixStore_{j}"
            if kind in ("mx", "mov"):
                need(th.run_of(tr["site"]) is None, f"{tr['site']}: a run is not expected here")
            if tr["run"]:
                before = tb.descs_at(pc)
                before.update(dict(tr["dst"]))
                tr["before"] = before
                tr["spec"] = run_spec(th, tr["run"][0], tr["run"][1], before)
            out.append(tr)
    return out


