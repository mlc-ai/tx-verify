"""Generate the thread machine of the FlashKDA recurrence kernel from its flow table.

Reads the frozen PTX (`packed_fp32_sm100a.ptx`, through `analysis.load`) and the flow table
`Flow/flow.json` (through `emit.Sites`). Writes, under `Kernels/FlashKdaFwd/Proof/Thread/`:

* `Sites.lean`: the type `Site` (one constructor per kind of site, indexed by the site's
  ordinal as in `Flow/Sites`) and `Site.pc`;
* `Kinds.lean`: the static kind of every register (`kind`);
* `After/Tails.lean`: the functions `tail_<pc>` from the cut points inside segments: a local
  instruction that evaluation does not run (a parameter load, a `mapa`; `emit.Tail`), and a
  data run that control code precedes or that follows an event without a data recipe, such as
  the address of the next access after a store (`emit.RunTail`);
* `After/Part<k>.lean`: the transition function of each site (`emit.after_info`);
* `Next.lean`: `next`, which reads what the event returned and calls the transition function;
* `Steps/Tails.lean`: the outcome of the local code from each cut point (`local_tail_<pc>`);
* `Steps/Part<k>.lean`: one theorem `stepAt_<site>` per site, closed by the tactic of its class;
* `Never.lean`: where the machine stops following a thread (`next_giveUp`: only at the 21 loads
  of the offsets array, on a value that is not a 64-bit integer);
* `StepAt.lean`: the dispatch `stepAt` over the states (total once every site has a recipe);
* `Run/Part<k>.lean`: the data runs, as `Tools/out_gen.py` renders them from the run
  declarations `Gen/Out/runs_<k>.json`, which this script writes too: the runs of the data path
  first, then those with arithmetic on generic shared pointers (`pointers.py`). A run is a
  maximal stretch of local data instructions between two event sites, or between a site and
  the control code around it;
* `RunPtr.lean`: every pointer run on a concrete base pointer (its condition and its end
  pointers in closed form, from `PtrEval.lean`).

Hand-written beside them: `Base.lean`, `Lib.lean`, `DataLib.lean`, `EventLib.lean`, `Rules.lean`,
`PtrRules.lean`, `PtrEval.lean`, `Vocab.lean`, `Start.lean`, `Sound.lean`.

Nothing generated is trusted: Lean checks every transition against the decoded program.

    python3 Kernels/FlashKdaFwd/Gen/thread.py            # write the files
    python3 Kernels/FlashKdaFwd/Gen/thread.py --check    # write nothing; fail if a file is stale
"""

