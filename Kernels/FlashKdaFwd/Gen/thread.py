def vec_loads(sites):
    """The vector loads of the kernel (site names, in program order)."""
    return [
        s["name"]
        for s in sites.sites
        if len(sites.code[s["pc"]]["writes"]) == 4
        and sites.code[s["pc"]]["opcode"].startswith("ld.")
    ]


def extra_kinds(sites):
    """The site kinds beyond those of the flow table: `(kind, count, binders, arguments)`."""
    out = [(k2, sites.counts[k], ROW, " row") for k, k2 in SECOND.items()]
    n = len(vec_loads(sites))
    if n:
        out += [(k, n, "(" + " ".join(vs) + " : Value)", " " + " ".join(vs)) for k, vs in VEC]
    return out


