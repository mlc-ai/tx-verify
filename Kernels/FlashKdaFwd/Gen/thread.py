def lean(lines):
    """The file text: one list item may hold several lines; long lines are wrapped."""
    return "\n".join(wrap_lines("\n".join(lines).split("\n"))) + "\n"


def sites_file(sites):
    kinds = list(sites.counts.items())
    out = [
        HEAD + "public import Kernels.FlashKdaFwd.Flow.Sites\npublic import Lemmas.Flow.Matrix",
        "",
        "@[expose] public section",
        "",
        "/-! # The sites of the thread machine",
        "",
        "One constructor per kind of event site of the flow table (`Flow/Sites`), indexed by the",
        "site's ordinal among the sites of its kind, in program order. -/",
        "",
        f"namespace {NS}",
        "",
        "inductive Site where",
    ]
    out += [f"  | {k} (j : Fin {n})" for k, n in kinds]
    for k, k2 in SECOND.items():
        out.append(
            f"  /-- The second event of the `{k}` site `j`, with the 16 bytes of the first. -/"
        )
        out.append(f"  | {k2} (j : Fin {sites.counts[k]}) {ROW}")
    vec = vec_loads(sites)
    for k, vs in VEC if vec else []:
        out.append(
            f"  /-- Element {len(vs)} of the vector load `j`, with the values read before it. -/"
        )
        out.append(f"  | {k} (j : Fin {len(vec)}) ({' '.join(vs)} : PTX.Value)")
    out += [
        "",
        "/-- Sites are compared classically: a second event carries bytes, whose equality is not",
        "computable. -/",
        "noncomputable instance : DecidableEq Site := Classical.decEq _",
        "",
    ]
    out += ["/-- The program counter of a site, by the generated site constants. -/"]
    out += ["def Site.pc : Site → Nat"]
    for k, n in kinds:
        names = ", ".join(f"Flow.{k}_{i}" for i in range(n))
        out.append(f"  | .{k} j => [{names}].getD j.val 0")
    for k, k2 in SECOND.items():
        names = ", ".join(f"Flow.{k}_{i}" for i in range(sites.counts[k]))
        out.append(f"  | .{k2} j _ => [{names}].getD j.val 0")
    for k, vs in VEC if vec else []:
        names = ", ".join(f"Flow.{n}" for n in vec)
        out.append(f"  | .{k} j{' _' * len(vs)} => [{names}].getD j.val 0")
    seconds = " | ".join(f".{k2} _ row" for k2 in SECOND.values())
    out += [
        "",
        "/-- The sub-step of a site: 1 at the second event of an `ldmatrix` or `stmatrix`, `k` at",
        "element `k` of a vector load. -/",
        "def Site.sub : Site → Nat",
        "  | " + " | ".join(f".{k2} _ _" for k2 in SECOND.values()) + " => 1",
        *[f"  | .{k} _{' _' * len(vs)} => {len(vs)}" for k, vs in (VEC if vec else [])],
        "  | _ => 0",
        "",
        "/-- The accumulator of a site: at a second event, the bytes of the first; at a later",
        "element of a vector load, the values read before it. -/",
        "def Site.acc : Site → List PTX.Value",
        f"  | {seconds} => PTX.Flow.rowVals row",
        *[f"  | .{k} _ {' '.join(vs)} => [{', '.join(vs)}]" for k, vs in (VEC if vec else [])],
        "  | _ => []",
    ]
    out += ["", f"end {NS}"]
    return lean(out)


def kinds_file(sites):
    ids, widths = sites.ids, sites.widths
    opaque = set(sites.data)
    top = max(ids.values()) // 64 + 1
    words = [sum(1 << (ids[r] % 64) for r in opaque if ids[r] // 64 == k) for k in range(top)]
    runs = []
    for name, rid in sorted(ids.items(), key=lambda kv: kv[1]):
        ty = widths[name]
        k = ".pred" if ty == ".pred" else f".word {int(ty[2:])}"
        if 2251 <= rid <= 2261:
            k = "param"
        if name in sites.gparam:
            k = f".gparamPtr {sites.gparam[name]}"
        if runs and runs[-1][2] == k and runs[-1][1] == rid - 1:
            runs[-1][1] = rid
        else:
            runs.append([rid, rid, k])
    out = [
        HEAD + "public import Core.Data.Value",
        "",
        "@[expose] public section",
        "",
        "/-! # The static kind of every register",
        "",
        "The value a register holds has one form wherever the register is live: a predicate, an",
        "integer of the declared width, the address of a by-value parameter object",
        "(`mov.b64 %rd, <parameter>`) or its generic address (`cvta.param.u64`), or an opaque value",
        "(what a load or a warp matrix instruction returned, what the data path computed from it,",
        "and the cluster address a `mapa` wrote). The registers the 21 loads of the offsets array",
        "write are 64-bit integers. Register ids follow the declaration order of the PTX. -/",
        "",
        f"namespace {NS}",
        "",
        "inductive RegKind where",
        "  | pred",
        "  | word (bits : Nat)",
        "  | paramPtr (i : Nat)",
        "  /-- The generic address of the by-value parameter object `i` (`cvta.param.u64`). -/",
        "  | gparamPtr (i : Nat)",
        "  | opaque",
        "",
        f"/-- Bit `r % 64` of word `r / 64` is set when register `r` is opaque ({len(opaque)}",
        "registers). -/",
        "def opaqueWords : List Nat :=",
        "  [" + ", ".join(str(x) for x in words) + "]",
        "",
        "/-- Whether register `r` is opaque. -/",
        "def isOpaque (r : Nat) : Bool := Nat.testBit (opaqueWords.getD (r / 64) 0) (r % 64)",
        "",
        "/-- The kind of a register that is not opaque, by its declaration. -/",
        "def plainKind (r : Nat) : RegKind :=",
    ]
    bounds = []
    for n, (a, b, k) in enumerate(runs):
        term = f".paramPtr (r - {a})" if k == "param" else k
        out.append(f"  {'else ' if n else ''}bif Nat.blt r {b + 1} then {term}")
        bounds.append(b + 1)
    out += [
        "  else .pred",
        "",
        "theorem plainKind_ne (r : Nat) : plainKind r ≠ .opaque := by",
        "  unfold plainKind",
    ]
    for b in bounds:
        out += [f"  cases Nat.blt r {b}", "  rotate_left", "  · intro h; cases h"]
    out += [
        "  intro h; cases h",
        "",
        "/-- The kind of register `r`. -/",
        "def kind (r : Nat) : RegKind := bif isOpaque r then .opaque else plainKind r",
        "",
        f"end {NS}",
    ]
    return lean(out)


class Plan:
    """What is generated for each site: its transition function and its step theorem."""

    def __init__(self, sites):
        self.sites = sites
        self.after = {}  # name -> Lean text of the transition function(s)
        self.next = {}  # name -> Lean term of `next` at the site (over `d`, `e`)
        self.next_eq = {}  # name -> the same term over the state `⟨site, w, p, x⟩`
        self.step = {}  # name -> tactic text
        self.term = {}  # name -> the Lean term of the site
        self.vars = {}  # name -> extra binders of the site's theorems (a second event's row)
        self.args = {}  # name -> the same as arguments
        self.order = []  # generated names, in program order (a second event after its first)
        self.launch = set()  # names whose step theorem takes the launch facts `hL`
        self.outcome = set()  # names whose transition function has the type `Option (Option D)`
        self.pre = {}  # name -> a lemma stated before the site's step theorem
        self.offset = []  # the loads of the offsets array (names)
        self.skipped = {}
        for s in sites.sites:
            before = (len(self.order), set(self.after), set(self.launch), set(self.outcome))
            try:
                self.site(s)
            except translit.Unsupported as e:
                self.skipped[s["name"]] = str(e)
                for d in (self.after, self.next, self.next_eq, self.step, self.pre):
                    for n in set(d) - before[1] | {s["name"]}:
                        d.pop(n, None)
                del self.order[before[0] :]
                self.launch, self.outcome = before[2], before[3]

    def done(self, name, term, binders="", args=""):
        self.term[name], self.vars[name], self.args[name] = term, binders, args
        self.order.append(name)

    # Control code with cut points ----------------------------------------------------------

    def tree(self, name):
        """The transition function of a site, with its tree and what its proof needs."""
        text, node, outcome = emit.after_info(self.sites, name)
        self.after[name] = text
        if outcome:
            self.outcome.add(name)
        if emit.needs_launch(self.sites, node):
            self.launch.add(name)
        return node, outcome

    def succ(self, name, outcome, state, arg=""):
        """The transition of a site as a term over the state `state`."""
        t = f"after_{name} L g {state}{arg}"
        return t if outcome else f"some (some ({t}))"

    def local(self, name, node, outcome, indent=6):
        """The proof of the outcome of the code after the event of `name`, as a `by` block."""
        pad = " " * indent
        body = []
        for t in [f"unfold after_{name}", "dsimp only", *emit.prove(self.sites, node, outcome, 0)]:
            body.append(pad + t)
        return "(by\n" + "\n".join(body) + ")"

    def issue(self, name, kind, term):
        """A site whose event returns nothing the code reads."""
        node, outcome = self.tree(name)
        st = f"⟨{term}, w, p, x⟩"
        self.next[name] = self.succ(name, outcome, "d")
        self.next_eq[name] = self.succ(name, outcome, st)
        if emit.simple(node):
            self.step[name] = f"th_site [next_{name}, after_{name}]"
            return
        tac = {"mbarArrive": "ev_arrive", "store": "ev_store"}.get(kind, "ev_issue")
        self.step[name] = (
            f"{tac} ({self.succ(name, outcome, st)})\n    {self.local(name, node, outcome)}\n"
            f"    trans [next_{name}]"
        )

    def offset_load(self, name, term):
        """One of the 21 loads of the offsets array: the machine follows a 64-bit integer."""
        node, outcome = self.tree(name)
        if outcome:
            raise translit.Unsupported(f"{name}: the code after an offsets load can die")
        self.offset.append(name)
        self.next[name] = f"loadWord e (fun y => after_{name} L g d y)"
        self.step[name] = (
            f"th_load64 (fun y => after_{name} L g ⟨{term}, w, p, x⟩ y)\n"
            f"    (fun y => {self.local(name, node, outcome)})\n    [next_{name}]"
        )

    def wait(self, name, term):
        """A poll: the code after it starts with the branch on its outcome."""
        node, outcome = self.tree(name)
        ok = "after_%s L g {D} ok" % name
        wrap = "{T}" if outcome else "some (some ({T}))"
        self.next[name] = (
            "match e.kind with\n"
            f"    | .wait _ _ ok _ _ => {wrap.format(T=ok.format(D='d'))}\n"
            "    | _ => none"
        )
        if emit.simple(node):
            self.step[name] = f"th_site [next_{name}, after_{name}]"
            return
        if node[0] != "if" or node[1] != "ok" or node[-1].head or node[-1].lets:
            raise translit.Unsupported(
                f"{name}: the code after the poll does not start with its branch"
            )
        st = f"⟨{term}, w, p, x⟩"
        arms = []
        for lit, sub in (("Bool.false_eq_true, ", node[3]), ("", node[2])):
            lines = emit.prove_tree(self.sites, sub, outcome, 8)
            arms += [f"      · simp only [after_{name}, {lit}↓reduceIte]", *lines]
        self.step[name] = (
            f"ev_wait (fun ok => {wrap.format(T=ok.format(D=st))})\n"
            "    (fun ok => by\n      cases ok\n" + "\n".join(arms) + ")\n"
            f"    trans [next_{name}]"
        )

    def trap(self, name):
        """A `brkpt` (decoded as `trap`): undefined behaviour, no successor."""
        self.after[name] = ""
        self.next[name] = "none"
        self.step[name] = "th_trap"

    def site(self, s):
        sites, name = self.sites, s["name"]
        kind = name.rsplit("_", 1)[0]
        ins = sites.code[s["pc"]]
        term = sites.term(s["pc"])
        if kind in PLAIN:
            self.issue(name, kind, term)
        elif kind == "trap":
            self.trap(name)
        elif kind == "exit":
            # `ret` ends the thread: no successor state.
            self.after[name] = ""
            self.next[name] = "none"
            self.step[name] = f"th_site [next_{name}]"
        elif kind == "elect":
            self.elect(s, ins)
        elif kind == "shfl":
            self.shfl(s, ins)
        elif kind == "load" and self.data_run_follows(s, ins):
            self.data_site(name, term, "", s["pc"], "load")
            return
        elif kind == "load" and emit.offset_load(ins):
            self.offset_load(name, term)
        elif kind == "load" and len(ins["writes"]) == 4:
            self.vector_load(s, ins)
            return
        elif kind == "load":
            self.after[name] = emit.after(sites, name)
            self.next[name] = (
                "match e.kind with\n"
                "    | .rd _ bs =>\n"
                "      match rebuild 3 bs with\n"
                f"      | .ok v => some (some (after_{name} L g d v))\n"
                "      | .error _ => none\n"
                "    | _ => none"
            )
            self.step[name] = f"th_site [next_{name}, after_{name}]"
        elif kind == "mbarWait":
            self.wait(name, term)
        elif kind in ("warpMma", "matrixMove"):
            self.data_site(name, term, "", s["pc"], "matrix")
            return
        elif kind in SECOND:
            self.two_events(s, kind)
            return
        else:
            raise translit.Unsupported(f"no recipe yet for the kind {kind}")
        self.done(name, term)

    # The data path -------------------------------------------------------------------------

    def data_run_follows(self, s, ins):
        """Whether the load writes one opaque register and a data run follows it."""
        if len(ins["writes"]) != 1:
            return False
        try:
            return emit.straight(self.sites, s["pc"] + 1)[0] is not None
        except translit.Unsupported:
            return False

    def set_next(self, name, term, tpl):
        """The transition at a data site, from a template over the state and its fields."""
        self.next[name] = tpl.format(D="d", S="d.site", W="d.w", P="d.p", X="d.x")
        self.next_eq[name] = tpl.format(D=f"⟨{term}, w, p, x⟩", S=term, W="w", P="p", X="x")

    def two_events(self, s, kind):
        """`ldmatrix` and `stmatrix`: the first event keeps 16 bytes and stays at the
        instruction (the library's `step_ldmatrix_rd`, `step_stmatrix_mx`); the second is a
        data site of its own kind."""
        name, pc = s["name"], s["pc"]
        k = name.rsplit("_", 1)[1]
        k2 = SECOND[kind]
        term = f".{kind} {k}"
        head = f"refine Code.StepAt.of (fun _ => ⟨_, Flow.code_{pc}, rfl, trivial⟩) ?_"
        tail = [
            "  (fun _ _ _ => by simp)",
            "  (fun bs d' _ _ h => by",
            "    cases h",
            "    exact ⟨rfl, rfl, rfl, rfl, fun h => h⟩)",
        ]
        # the second event first: if it has no recipe, neither has the instruction
        second = f"{k2}_{k}"
        mode = "ldmx" if kind == "matrixLoad" else "stwr"
        after, nxt, step = self.data_text(second, f".{k2} {k} row", pc, mode)
        self.after[name] = ""
        if kind == "matrixLoad":
            self.set_next(
                name,
                term,
                "match e.kind with\n    | .rd _ bs => ldRow {D} bs (.%s %s)\n    | _ => none"
                % (k2, k),
            )
            self.step[name] = "\n  ".join(
                [
                    head,
                    f"exact Code.step_ldmatrix_rd (nv := fun bs => some (some ⟨.{k2} {k} bs, w, p, x⟩))",
                    f"  Flow.code_{pc} rfl rfl (laneOf_lt_rows rfl) rfl",
                    f"  (fun xa bs _ hall => by simp [codeFrom, next_{name}, ldRow, hall])",
                    f"  (fun xa bs _ hall => .inl (by simp [codeFrom, next_{name}, ldRow, hall]))",
                    *tail,
                ]
            )
        else:
            self.set_next(
                name,
                term,
                "match e.kind with\n    | .matrix _ _ recv => stRecv {D} recv (.%s %s)\n    | _ => none"
                % (k2, k),
            )
            self.step[name] = "\n  ".join(
                [
                    head,
                    f"exact Code.step_stmatrix_mx (nv := fun recv => some (some ⟨.{k2} {k} recv, w, p, x⟩))",
                    f"  Flow.code_{pc} rfl rfl (laneOf_lt_rows rfl) rfl",
                    f"  (fun own recv hl hall => by simp [codeFrom, next_{name}, stRecv, hl, hall])",
                    "  (fun own recv h => .inl (by",
                    f"    simp only [codeFrom, next_{name}, stRecv]",
                    "    exact ite_eq_right h))",
                    *tail,
                ]
            )
        self.done(name, term)
        self.after[second] = after
        self.set_next(second, f".{k2} {k} row", nxt)
        self.step[second] = step
        self.done(second, f".{k2} {k} row", ROW + " ")

    def vector_load(self, s, ins):
        """A four-element vector load: one state per element (the elements read so far are in
        the site, as the accumulator); the last element writes the four registers, and the data
        run after it is that of a data event."""
        sites, name, pc = self.sites, s["name"], s["pc"]
        j = vec_loads(sites).index(name)
        # the last element first: if it has no recipe, neither has the load
        last = f"loadEl3_{j}"
        after, nxt, step = self.data_text(last, f".loadEl3 {j} v0 v1 v2", pc, "ldv")
        self.after[name] = ""
        vs = []
        for k in range(3):
            n = name if k == 0 else f"loadEl{k}_{j}"
            term = sites.term(pc) if k == 0 else f".loadEl{k} {j} " + " ".join(vs)
            succ = f".loadEl{k + 1} {j} " + " ".join([*vs, "v"])
            self.after[n] = ""
            self.set_next(
                n,
                term,
                "match e.kind with\n    | .rd _ bs =>\n      match rebuild 3 bs with\n"
                "      | .ok v => some (some ⟨%s, {W}, {P}, {X}⟩)\n"
                "      | .error _ => none\n    | _ => none" % succ,
            )
            self.step[n] = f"ev_ldv_mid (fun v => ⟨{succ}, w, p, x⟩) trans [next_{n}]"
            binders = f"({' '.join(vs)} : Value) " if vs else ""
            self.done(n, term, binders, "".join(" " + v for v in vs))
            vs.append(f"v{k}")
        self.after[last] = after
        self.set_next(last, f".loadEl3 {j} v0 v1 v2", nxt)
        self.step[last] = step
        self.done(last, f".loadEl3 {j} v0 v1 v2", "(v0 v1 v2 : Value) ", " v0 v1 v2")

    def data_site(self, name, term, binders, pc, mode):
        after, nxt, step = self.data_text(name, term, pc, mode)
        self.after[name] = after
        self.set_next(name, term, nxt)
        self.step[name] = step
        self.done(name, term, binders)

    def data_text(self, name, term, pc, mode):
        """The transition function, the `next` template and the step proof of a data event
        (`mode`: a scalar `load`, a one-event `matrix` instruction, the matrix event of an
        `ldmatrix` (`ldmx`), the row write of an `stmatrix` (`stwr`), the last element of a
        vector load (`ldv`)). The proof has one part for the event and one for each thing that
        follows it before the next site: a data run, then control code; either can be absent."""
        sites = self.sites
        ins = sites.code[pc]
        written = [] if mode == "stwr" else ins["writes"]
        if any(r not in sites.data for r in written):
            raise translit.Unsupported(f"{mode} at {pc} writes a register that is not opaque")
        arg = {"load": "v", "matrix": "vs", "ldmx": "vs", "stwr": None, "ldv": "v0 v1 v2 v"}[mode]
        after, info = emit.data_after(sites, name, pc, written, arg)
        ids, run, control, q = info["ids"], info["run"], info["control"], info["next"]
        bind = "v" if mode == "ldv" else arg
        if mode == "ldv":
            val = "rebuild 3 bs"
            ev = ".rd _ bs"
        elif mode == "load":
            elem = int(ins["opcode"].rsplit(".b", 1)[1])
            dw = int(sites.widths[written[0]][2:])
            val = f"ldVal {'.same' if dw == elem else f'(.zero {dw})'} {elem} bs"
            ev = ".rd _ bs"
        else:
            val = f"matrixVals 32 {len(ids)} recv"
            ev = ".matrix _ _ recv"
        succ = "after_%s L g {D}" % name + (f" {arg}" if arg else "")
        x1 = "{X}" if info["event"] is None else "valueEx {X} " + info["event"]
        if run:
            succ = "across (Run.%s_cond (valueOf ⟨{S}, {W}, {P}, %s⟩))\n          (%s)" % (
                run[0],
                x1,
                succ,
            )
        else:
            succ = f"some (some ({succ}))"
        if mode == "stwr":
            nxt = "match e.kind with\n    | .wr _ _ =>\n        %s\n    | _ => none" % succ
        else:
            nxt = (
                "match e.kind with\n    | %s =>\n      match %s with\n      | .ok %s =>\n        %s\n"
                "      | .error _ => none\n    | _ => none" % (ev, val, bind, succ)
            )
        # the step
        st = f"⟨{term}, w, p, x⟩"
        aft = f"(after_{name} L g {st}" + (f" {arg})" if arg else ")")
        x1 = "x" if info["event"] is None else f"(valueEx x {info['event']})"
        a = pc + 1
        out = [f"refine Code.StepAt.of (fun _ => ⟨_, Flow.code_{pc}, rfl, trivial⟩) ?_"]
        both = "  (fun own recv vs hv _ u hu => ?_) (fun own recv f hf => ?_)"
        if mode == "load":
            out += [
                f"refine step_load_x (r := {ids[0]}) Flow.code_{pc} rfl rfl rfl rfl rfl",
                "  (fun xa bs v hv _ u hu => ?_) (fun xa bs f hf => ?_)",
            ]
            ds, vs, hdv, vex = f"[{ids[0]}]", "[v]", "rfl", "valueOf_ex"
        elif mode == "ldv":
            out += [
                f"refine step_ldv_last_x Flow.code_{pc} rfl rfl rfl (Nat.lt_irrefl 4) (by decide)",
                "  (fun xa bs v hv _ u hu => ?_) (fun xa bs f hf => ?_)",
            ]
            ds = "[" + ", ".join(map(str, ids)) + "]"
            vs, hdv, vex = "[v0, v1, v2, v]", "rfl", "valueOf_zip"
        elif mode == "matrix":
            out += [
                f"refine step_matrix_x (w := 32) Flow.code_{pc} (by simp) rfl (by decide)",
                both,
            ]
        elif mode == "ldmx":
            out += [
                f"refine step_ldmatrix_mx_x Flow.code_{pc} rfl rfl Nat.one_ne_zero (by decide)",
                both,
            ]
        else:
            out.append(
                f"refine step_stmatrix_wr_x Flow.code_{pc} rfl rfl Nat.one_ne_zero"
                " (fun xa bs _ u hu => ?_)"
            )
        if mode in ("matrix", "ldmx"):
            ds = "[" + ", ".join(map(str, ids)) + "]"
            vs, hdv, vex = "vs", "(matrixVals_length hv).1.symm", "valueOf_zip"
        body = []
        if mode == "stwr":
            body.append(
                f"have h1 : At u {a} (factsAt {a} {st}) :="
                " hu.mono (holds_sub hu.2.2.2.2 (by kernel_rfl))"
            )
            hn = f"(by simp [codeFrom, next_{name}])"
        else:
            body += [
                f"have hv' : {val} = .ok {bind} := hv",
                f"have h1 : At u {a} (factsAt {a} ⟨{term}, w, p, {x1}⟩) :=",
                f"  hu.mono (holds_after (ds := {ds}) (vs := {vs}) {hdv} hu.2.2.2.2 (by kernel_rfl)",
                f"    fun r _ => congrFun ({vex} (by kernel_rfl)) r)",
            ]
            hn = f"(by simp [codeFrom, next_{name}, hv'])"
        b, xr = a, x1
        if run:
            rname, last, ra, rb = run
            body += [
                f"have hrun := SegD.run_land (liveS := Flow.live {ra}) (liveT := Flow.live {rb})",
                f"  Rules.rulesFrame (Run.{rname}_run L g (valueOf ⟨{term}, w, p, {x1}⟩)) rfl",
                "  (by kernel_rfl) (Rules.segFree_range _ _) rfl (by kernel_rfl) (by kernel_rfl)",
                "  (by kernel_rfl) (by kernel_rfl)",
                "rw [← valueOf_ex (by kernel_rfl)] at hrun",
            ]
            b = rb
            xr = f"(valueEx {x1} (Run.{rname}_facts{last} (valueOf ⟨{term}, w, p, {x1}⟩)))"
        if control:
            body += [
                f"have hctl : Seg kernel Assumptions.all L g {len(control)} {b}",
                f"    (factsAt {b} ⟨{term}, w, p, {xr}⟩) {q}",
                f"    (facts {aft}) := by",
                "  th_seg",
            ]
        cc = "(C := codeFrom L g d0)"
        if run:
            seg = "(hrun.comp_seg hctl)" if control else "hrun"
            body.append(f"exact cont_across {cc} (d' := {aft})")
            body.append(f"  h1 {seg} rfl rfl trivial {hn}")
        elif control:
            body.append(f"exact cont_seg {cc} (d' := {aft})")
            body.append(f"  h1 hctl rfl rfl trivial {hn}")
        else:
            body.append(f"exact cont_at {cc} (d' := {aft})")
            body.append(f"  h1 rfl rfl trivial {hn}")
        if mode == "stwr":
            out += body
        else:
            out += ["· " + body[0]] + ["  " + line for line in body[1:]]
            out += [f"· have hf' : {val} = .error f := hf", f"  simp [codeFrom, next_{name}, hf']"]
        return after, nxt, "\n  ".join(out)

    def elect(self, s, ins):
        """An election: the file after the election's guarded move and copy of the leader
        (`scope_<site>`, the cut of the step's proof), then the rest."""
        sites, name, pc = self.sites, s["name"], s["pc"]
        rx, px = ins["writes"]
        code = sites.code
        scope = [pc + 1, pc + 2]
        if not (code[pc + 1]["guard"] and code[pc + 2]["opcode"].startswith("mov")):
            raise translit.Unsupported(f"election at {pc}: unexpected scope")
        terms = translit.PathTerms(code, sites.ids, sites.data)
        terms.bits[rx], terms.preds[px] = "(BitVec.ofNat 64 ld)", "b"
        terms.assigned += [rx, px]
        terms.run(scope)
        every = set(terms.assigned)
        words, preds = terms.updates(every)
        lets = []
        for n, ty, t, c in terms.lets:
            lets += [f"  -- {c}"[:99], f"  let {n} : {ty} := {t}"]
        w = "setW [" + ", ".join(f"({i}, {t})" for i, t in words) + "] d.w"
        p = "setP [" + ", ".join(f"({i}, {t})" for i, t in preds) + "] d.p"
        scope_def = "\n".join(
            [
                f"/-- The file after `{name}` ({pc}: `{emit.brief(ins)}`) elected lane `ld` and the two",
                "moves",
                "of its scope; `b` says whether this lane is the elected one. The site is unchanged:",
                "the state describes the program counter three after the election. -/",
                f"def scope_{name} (d : D) (ld : Nat) (b : Bool) : D :=",
                *lets,
                f"  ⟨d.site, {w}, {p}, d.x⟩",
            ]
        )
        rest = translit.PathTerms(code, sites.ids, sites.data)
        node = translit.tree(code, sites.ids, sites.data, pc + 3, rest)
        for leaf in emit.leaves(node):
            if leaf[0] == "tail":
                sites.tail(leaf[1])
        if emit.is_outcome(sites, node):
            raise translit.Unsupported(f"election at {pc}: the code after it can die")
        after_def = "\n".join(
            [
                f"/-- After the scope of `{name}`, from the file `scope_{name}` gives. -/",
                f"def after_{name} (L : Launch) (g : Nat) (d : D) : D :=",
                *emit.render(sites, node, 2),
            ]
        )
        self.after[name] = scope_def + "\n\n" + after_def
        self.next[name] = (
            "match e.kind with\n"
            "    | .elect _ _ ld =>\n"
            f"      some (some (if laneOf L g = ld then after_{name} L g (scope_{name} d ld true)\n"
            f"        else after_{name} L g (scope_{name} d ld false)))\n"
            "    | _ => none"
        )
        site = sites.term(pc)
        if not emit.simple(node):
            # the rest has a cut point: its outcome is a lemma of its own, from the file after
            # the scope; the election's successors are one function of the elected lane
            self.launch.add(name)
            st = f"⟨{site}, w, p, x⟩"
            self.next[name] = (
                "match e.kind with\n"
                "    | .elect _ _ ld =>\n"
                f"      some (some (after_{name} L g (scope_{name} d ld (laneOf L g == ld))))\n"
                "    | _ => none"
            )
            self.pre[name] = "\n".join(
                [
                    f"theorem local_after_{name} (hL : Launched L) (s : Site) (w : Nat → BitVec 64)",
                    "    (p : Nat → Bool) (x : Nat → Value) :",
                    f"    Local (codeFrom L g d0) {pc + 3} (factsAt {pc + 3} ⟨s, w, p, x⟩)",
                    f"      (some (some (after_{name} L g ⟨s, w, p, x⟩))) := by",
                    f"  unfold after_{name}",
                    "  dsimp only",
                    *emit.prove(sites, node, False, 2),
                ]
            )
            self.step[name] = "\n".join(
                [
                    f"ev_elect (fun ld b => some (some (after_{name} L g (scope_{name} {st} ld b))))",
                    "    (fun ld b => by",
                    f"      refine Local.cut (q' := {pc + 3})",
                    f"        (H := factsAt {pc + 3} (scope_{name} {st} ld b)) ?_ ?_",
                    f"      · cases b <;> (simp only [scope_{name}]; lseg)",
                    f"      · simp only [scope_{name}]",
                    f"        exact local_after_{name} hL _ _ _ _)",
                    f"    trans [next_{name}]",
                ]
            )
            return
        self.step[name] = (
            f"th_elect ((Site{site.split()[0]} {site.split()[1]}).pc + 3)\n"
            f"    (fun ld b => factsAt ((Site{site.split()[0]} {site.split()[1]}).pc + 3)\n"
            f"      (scope_{name} ⟨{site}, w, p, x⟩ ld b))\n"
            f"    [next_{name}, after_{name}, scope_{name}]"
        )

    def shfl(self, s, ins):
        """A shuffle with a validity predicate: the received value is never read, or it is read
        once, as an integer, by the `setp` right after the shuffle."""
        sites, name, pc = self.sites, s["name"], s["pc"]
        dst = ins["writes"][0]
        code = sites.code
        readers = [i["pc"] for i in code if dst in i["reads"]]
        self.after[name] = emit.after(sites, name)
        if not readers:
            self.next[name] = (
                "match e.kind with\n"
                f"    | .shfl _ _ _ _ _ ok => some (some (after_{name} L g d 0 ok))\n"
                "    | _ => none"
            )
            self.step[name] = f"th_site [next_{name}, after_{name}]"
        elif readers == [pc + 1] and code[pc + 1]["opcode"].startswith("setp"):
            self.next[name] = (
                "match e.kind with\n"
                "    | .shfl _ _ _ _ v ok =>\n"
                "      match wordOf v with\n"
                f"      | some n => some (some (after_{name} L g d (BitVec.ofNat 64 n) ok))\n"
                "      | none => none\n"
                "    | _ => none"
            )
            self.step[name] = f"th_shfl_word [next_{name}, after_{name}]"
        else:
            raise translit.Unsupported(f"shuffle at {pc}: value read at {readers}")


def chunks(names, size=CHUNK):
    return [names[i : i + size] for i in range(0, len(names), size)]


def run_files(sites, found=None, first=0):
    """The data runs of the kernel: their declarations for `Tools/out_gen.py`, the generated
    run files, and `sites.runs`. Without `found`: the runs right after an event
    (`emit.straight`), those without pointer arithmetic first, six to a file (the files of the
    data path, which the arithmetic on shared pointers leaves as they were), then the others.
    With `found`: these runs (the runs of the tails), in files numbered from `first`."""
    code = sites.code
    live = analysis.flow_gen.liveness(code)
    rules = NS + ".Rules"

    def items(table):
        return {
            key: {
                "kind": kind,
                "op": f"{rules}.{op}",
                "f": f"{rules}.{f}",
                "rule": f"{rules}.{rule} {{pc}}",
            }
            for key, (kind, op, f, rule) in table.items()
        }

    def has_ptr(run):
        return any(w in sites.ptr for pc in range(*run) for w in code[pc]["writes"])

    if found is None:
        found = []
        for s in sites.sites:
            try:
                run = emit.straight(sites, s["pc"] + 1)[0]
            except translit.Unsupported:
                continue
            if run is not None:
                found.append(run)
        groups = [(g, False) for g in chunks([r for r in found if not has_ptr(r)], RUN_CHUNK)]
        groups += [(g, True) for g in chunks([r for r in found if has_ptr(r)], PTR_RUN_CHUNK)]
    else:
        groups = [(g, True) for g in chunks(found, PTR_RUN_CHUNK)]
    fn_data, fn_ptr = items(DATA_FN), items(pointers.FN)
    lean_files, decls = {}, {}
    for k, (group, ptr) in enumerate(groups, start=first):
        runs = []
        for a, b in group:
            written = []
            for pc in range(a, b):
                written += [r for r in code[pc]["writes"] if r not in written]
            runs.append(
                {
                    "name": f"r{a}",
                    "start": a,
                    "end": b,
                    "cut": 16,
                    "outputs": [r for r in written if r in live[b]],
                    "segfree": f"{rules}.segFree {{pc}}",
                    "rules": {kind: f"{rules}.{t}" for kind, t in DATA_RULES.items()},
                    "fn": {**fn_data, **fn_ptr} if ptr else fn_data,
                }
            )
        decl = {
            "ptx": analysis.PTX.relative_to(ROOT).as_posix(),
            "namespace": NS + ".Run",
            "output": f"Kernels/FlashKdaFwd/Proof/Thread/Run/Part{k:03d}.lean",
            "imports": [
                "Kernels.FlashKdaFwd.Spec",
                "Kernels.FlashKdaFwd.Flow.Code",
                MOD + (".PtrRules" if ptr else ".Rules"),
            ],
            "kernel": "PTX.Kernels.FlashKdaFwd.kernel",
            "code": "PTX.Kernels.FlashKdaFwd.Flow",
            "assumptions": "PTX.Kernels.FlashKdaFwd.Assumptions.all",
            "runs": runs,
        }
        text = out_gen.render(decl)
        for r in runs:
            last = max(int(m) for m in re.findall(rf"def {r['name']}_facts(\d+) ", text))
            sites.runs[(r["start"], r["end"])] = (r["name"], last)
        lean_files[f"Run/Part{k:03d}.lean"] = text
        decls[f"runs_{k:03d}.json"] = json.dumps(decl, indent=2) + "\n"
    return lean_files, decls


def run_ptr_file(sites, parts):
    """`RunPtr.lean`: every pointer run on a concrete base pointer (`PtrEval.lean`): its
    condition holds and its end facts are pointers in closed form, under the range conditions
    of its moves. Returns the text and the runs without such a lemma."""
    code, ids = sites.code, sites.ids
    live = analysis.flow_gen.liveness(code)
    ptr = "ptr 64 true (.shared o c)"
    out = [
        HEAD
        + "".join(f"public import {MOD}.Run.Part{k:03d}\n" for k in parts)
        + f"public import {MOD}.PtrEval",
        "",
        "@[expose] public section",
        "",
        "/-! # The pointer runs on a concrete base pointer",
        "",
        "For every data run that moves a generic shared pointer (`add.s64` by a word, then by a",
        "constant, then the swizzle): where its base register holds a generic shared pointer of",
        "offset `off` and each move stays in the window (`Rules.MoveOkW`, `Rules.MoveOk`), the",
        "run's condition holds and its end facts are the pointers of the same window with the",
        "moved offset (`Rules.movedBy`, `Rules.movedOff`) and the swizzled offset (`Rules.swz`).",
        "The layers above get the address of every carry load and of every final store from",
        "these, one rewriting per site. -/",
        "",
        f"namespace {NS}",
        "open PTX PTX.Proof PTX.Flow",
        "",
    ]
    missing = []
    for (a, b), (name, last) in sorted(sites.runs.items()):
        ins = [code[pc] for pc in range(a, b)]
        if not any(w in sites.ptr for i in ins for w in i["writes"]):
            continue
        shape = "".join(pointers.classify(i, sites.ptr, sites.data) for i in ins)
        written = [w for i in ins for w in i["writes"]]
        outs = sorted(ids[r] for r in written if r in live[b])
        value, hyps, have, cond = {}, [], [], []
        off = "off"
        base = ids[ins[0]["operands"][1]]
        hyps.append(f"(hV : V {base} = .{ptr} off)")
        if shape.startswith("R"):
            word = ids[ins[0]["operands"][2]]
            hyps += [f"(hW : V {word} = .bits n delta)", "(hd : Rules.MoveOkW off delta)"]
            off = "(Rules.movedBy off delta)"
            value[ids[ins[0]["writes"][0]]] = (f".{ptr} {off}", "okVal_of_ok a", a)
            have.append("have a := Rules.r_eval hV hW hd")
            cond.append("⟨_, a⟩")
        rest = shape[1:] if shape.startswith("R") else shape
        if rest == "KSAX":
            k0 = a + (1 if shape.startswith("R") else 0)
            k = int(code[k0]["operands"][2])
            hyps.append(f"(hk : Rules.MoveOk {off} {k})")
            hb = "(okVal_of_ok (dflt := .bits 32 0) a)" if shape.startswith("R") else "hV"
            have.append(f"have h := Rules.ksax_eval (k := {k}) {hb} hk")
            cond += ["h.1.1", "h.1.2.1", "h.1.2.2.1", "h.1.2.2.2"]
            value[ids[code[k0]["writes"][0]]] = (f".{ptr} (Rules.movedOff {off} {k})", "h.2.1", k0)
            value[ids[code[k0 + 3]["writes"][0]]] = (
                f".{ptr} (Rules.swz (Rules.movedOff {off} {k}))",
                "h.2.2",
                k0 + 3,
            )
        elif rest:
            missing.append((name, shape))
            continue
        if last != 1 or any(r not in value for r in outs):
            missing.append((name, shape))
            continue
        binders = "{V : Nat → Value} {o c : Nat} {off : BitVec 64}"
        if shape.startswith("R"):
            binders += " {delta : BitVec 64} {n : Nat}"
        eqs = []
        for r in outs:
            term, proof, pc = value[r]
            have.append(f"have e{r} : Run.{name}_v{pc} V = _ := {proof}")
            eqs.append(f"e{r}")
        facts = ", ".join(f"({r}, {value[r][0]})" for r in outs)
        out += [
            f"theorem {name}_ptr {binders}",
            "    " + " ".join(hyps) + " :",
            f"    Run.{name}_cond V ∧ Run.{name}_facts1 V = [{facts}] := by",
            *("  " + line for line in have),
            "  exact ⟨⟨" + ", ".join(cond + ["trivial"]) + "⟩,",
            f"    by rw [Run.{name}_facts1, " + ", ".join(eqs) + "]⟩",
            "",
        ]
    out += [f"end {NS}"]
    return lean(out), missing


def run_tail_lemma(sites, t):
    """The outcome of a data run that is a function of its own (`emit.RunTail`): the run landed
    on the live lists (`SegD.run_land`), then the site (`Local.across`) or the rest
    (`Local.run`)."""
    a, b = t.pc, t.end
    v = "(valueOf ⟨s, w, p, x⟩)"
    _, facts, run = t.names(sites, v)
    out = []
    if t.cvta:
        ins = sites.code[a]
        d, s = sites.ids[ins["writes"][0]], sites.ids[ins["reads"][0]]
        out += [
            f"/-- {a}: `{emit.brief(ins)}` as a piece (`Rules.cvta_piece`). -/",
            f"theorem cvta_{a}_run (L : Launch) (g : Nat) (V : Nat → Value) :",
            f"    SegD kernel Assumptions.all L g 1 {a} [({s}, V {s})] {a + 1}",
            f"      [({d}, Rules.cvtaVal L g V {s})] (Rules.cvtaCond L g V {s}) :=",
            f"  Rules.cvta_piece (pc := {a}) Flow.code_{a} L g V",
            "",
        ]
    if t.site:
        close = [
            "  exact Local.across (C := codeFrom L g d0)",
            f"    (d' := ⟨{sites.term(b)}, w, p, valueEx x {facts}⟩)",
            "    hrun rfl rfl trivial",
        ]
    else:
        close = [f"  exact Local.run hrun fun _ => local_tail_{b} hL _ _ _ _"]
    out += [
        f"/-- The outcome of the data run from instruction {a} and of the code after it. -/",
        f"theorem local_tail_{a} (hL : Launched L) (s : Site) (w : Nat → BitVec 64)",
        "    (p : Nat → Bool) (x : Nat → Value) :",
        f"    Local (codeFrom L g d0) {a} (factsAt {a} ⟨s, w, p, x⟩)",
        f"      (tail_{a} L g ⟨s, w, p, x⟩) := by",
        f"  have hrun := SegD.run_land (liveS := Flow.live {a}) (liveT := Flow.live {b})",
        f"    Rules.rulesFrame ({run}) rfl (by kernel_rfl)",
        "    (Rules.segFree_range _ _) rfl (by kernel_rfl) (by kernel_rfl) (by kernel_rfl)",
        "    (by kernel_rfl)",
        "  rw [← valueOf_ex (by kernel_rfl)] at hrun",
        *close,
        "",
    ]
    return out


def split(lo, hi, leaf, pad):
    """A proof by binary splitting on `k` over `lo ≤ k < hi` (`leaf k` gives a leaf's tactics)."""
    if hi - lo == 1:
        return [
            f"{pad}have hke : k = {lo} := by omega",
            f"{pad}subst hke",
            *[pad + t for t in leaf(lo)],
        ]
    mid = (lo + hi) // 2
    return [
        f"{pad}rcases Nat.lt_or_ge k {mid} with h{mid} | h{mid}",
        *split(lo, mid, leaf, pad + "· ")[:1],
        *["  " + t for t in split(lo, mid, leaf, pad)[1:]],
        *split(mid, hi, leaf, pad + "· ")[:1],
        *["  " + t for t in split(mid, hi, leaf, pad)[1:]],
    ]


def render(sites):
    run_lean, decls = run_files(sites)
    plan = Plan(sites)
    # The runs of the tails the plan reached (a run that control code precedes).
    tail_runs = sorted(
        (t.pc, t.end)
        for t in sites.tails.values()
        if isinstance(t, emit.RunTail) and not t.cvta and (t.pc, t.end) not in sites.runs
    )
    more_lean, more_decls = run_files(sites, tail_runs, len(run_lean))
    run_lean.update(more_lean)
    decls.update(more_decls)
    ptr_parts = [
        int(name[8:11]) for name, text in run_lean.items() if f"import {MOD}.PtrRules" in text
    ]
    done = plan.order
    files = {"Sites.lean": sites_file(sites), "Kinds.lean": kinds_file(sites), **run_lean}
    files["RunPtr.lean"], plan.no_ptr_lemma = run_ptr_file(sites, sorted(ptr_parts))
    parts = chunks(done)
    opens = [
        f"namespace {NS}",
        "open PTX PTX.Proof PTX.Flow PTX.Flow.Arith32",
        "",
        "noncomputable section",
        "",
        "-- A generated transition names the launch, the thread and its lets whether it reads them or not.",
        "set_option linter.unusedVariables false",
        "",
    ]
    run_imports = "".join(f"public import {MOD}.Run.Part{k:03d}\n" for k in range(len(run_lean)))
    # The functions from the cut points inside segments, callees first.
    tails = emit.tail_order(sites)
    out = [HEAD + f"public import {MOD}.Base\n" + run_imports.rstrip("\n")]
    out += ["", "@[expose] public section", "", *opens]
    for pc in tails:
        out += [sites.tails[pc].text(sites), ""]
    out += ["end", "", f"end {NS}"]
    files["After/Tails.lean"] = lean(out)
    for k, names in enumerate(parts):
        out = [HEAD + f"public import {MOD}.After.Tails"]
        out += ["", "@[expose] public section", "", *opens]
        for n in names:
            if plan.after[n]:
                out += [plan.after[n], ""]
        out += ["end", "", f"end {NS}"]
        files[f"After/Part{k:03d}.lean"] = lean(out)
    # `next`: one function per kind, dispatching on the ordinal.
    out = [HEAD + "".join(f"public import {MOD}.After.Part{k:03d}\n" for k in range(len(parts)))]
    out += ["", "@[expose] public section", "", *opens]
    # The equation of a site whose transition is outcome-valued unfolds the function's body.
    out += ["set_option maxRecDepth 100000", ""]
    by_kind = {}
    for n in done:
        by_kind.setdefault(n.rsplit("_", 1)[0], []).append(n)
    kinds = [(kind, count, "", "") for kind, count in sites.counts.items()]
    kinds += extra_kinds(sites)
    covered = {}
    for kind, count, row, ra in kinds:
        out.append(f"/-- The successor after the event of the `{kind}` site `j`. -/")
        out.append(
            f"def next_{kind} (L : Launch) (g : Nat) (j : Fin {count}) {row + ' ' if row else ''}"
            "(d : D) (e : Event) : Option (Option D) :="
        )
        names = {int(n.rsplit("_", 1)[1]): n for n in by_kind.get(kind, [])}
        covered[kind] = sorted(names)

        def search(lo, hi, pad):
            """A binary search on `j.val` over the ordinals `lo ≤ k < hi`."""
            if not any(lo <= k < hi for k in names):
                return [f"{pad}none"]
            if hi - lo == 1:
                return [pad + line for line in plan.next[names[lo]].split("\n")]
            mid = (lo + hi) // 2
            return [
                f"{pad}bif Nat.blt j.val {mid} then",
                *search(lo, mid, pad + "  "),
                f"{pad}else",
                *search(mid, hi, pad + "  "),
            ]

        out += [*search(0, count, "  "), ""]
    out.append("/-- The successor after event `e`. -/")
    out.append("def next (L : Launch) (g : Nat) (d : D) (e : Event) : Option (Option D) :=")
    out.append("  match d.site with")
    for kind, _, row, ra in kinds:
        out.append(f"  | .{kind} j{ra} => next_{kind} L g j{ra} d e")
    out.append("")
    out += [
        "variable {L : Launch} {g : Nat} (w : Nat → BitVec 64) (p : Nat → Bool) (x : Nat → Value)",
        "  (e : Event)",
        "",
    ]
    for n in done:
        site = plan.term[n]
        body = plan.next_eq.get(n) or plan.next[n].replace(" d)", f" ⟨{site}, w, p, x⟩)").replace(
            " d ", f" ⟨{site}, w, p, x⟩ "
        )
        if n in plan.outcome:
            # An outcome-valued function may start with a branch: the unifier would compare it
            # with the dispatch's own `if`s argument by argument. Sealed, only `next` unfolds.
            out.append(f"attribute [local irreducible] after_{n} in")
        out.append(
            f"theorem next_{n} {plan.vars[n]}: next L g ⟨{site}, w, p, x⟩ e =\n    ({body}) := rfl"
        )
        out.append("")
    out += ["end", "", f"end {NS}"]
    files["Next.lean"] = lean(out)
    files["Code.lean"] = lean(
        [
            HEAD + f"public import {MOD}.Next",
            "",
            "@[expose] public section",
            "",
            *opens,
            "/-- The thread machine, from the state `d0` (the generated entry is added with the",
            "last sites). At the second event of an `ldmatrix` or `stmatrix` the thread is at",
            "sub-step 1 with the bytes of the first event in its accumulator. -/",
            "@[reducible] def codeFrom (L : Launch) (g : Nat) (d0 : D) :",
            "    Flow.Code kernel Assumptions.all L g where",
            "  D := D",
            "  init := d0",
            "  pc := (·.site.pc)",
            "  facts := facts",
            "  sub := (·.site.sub)",
            "  acc := (·.site.acc)",
            "  inv := fun _ => True",
            "  next := next L g",
            "",
            "end",
            "",
            f"end {NS}",
        ]
    )
    entry = translit.PathTerms(sites.code, sites.ids, sites.data)
    entry.param_loads = True
    node = translit.tree(sites.code, sites.ids, sites.data, 0, entry)
    files["Entry.lean"] = lean(
        [
            HEAD + f"public import {MOD}.Code",
            "",
            "@[expose] public section",
            "",
            *opens,
            "/-- The file at a thread's first site, as the code before it computes it, written over",
            "a file `d` whose content does not matter (every register live at a first site is",
            "assigned on the way). -/",
            "def entry (L : Launch) (g : Nat) (d : D) : D :=",
            *emit.render(sites, node, 2),
            "",
            "/-- The state at a thread's first site. -/",
            "def init (L : Launch) (g : Nat) : D :=",
            "  entry L g ⟨.shfl 0, fun _ => 0, fun _ => false, fun _ => .pred false⟩",
            "",
            "/-- The thread machine. -/",
            "@[reducible] def code (L : Launch) (g : Nat) : Flow.Code kernel Assumptions.all L g :=",
            "  codeFrom L g (init L g)",
            "",
            "end",
            "",
            f"end {NS}",
        ]
    )
    step_opens = [
        "set_option linter.unusedTactic false",
        "set_option linter.unreachableTactic false",
        "-- The sites at the end of a loop body have long segments with several branches.",
        "set_option maxHeartbeats 1600000",
        "set_option maxRecDepth 100000",
        "",
        "variable {L : Launch} {g : Nat} {d0 : D} (w : Nat → BitVec 64) (p : Nat → Bool)",
        "  (x : Nat → Value)",
        "",
    ]
    out = [
        HEAD + f"public import {MOD}.Code\nimport Kernels.FlashKdaFwd.Flow.Code\n"
        "import Tactics.KernelRfl",
        "",
        "@[expose] public section",
        "",
        *opens,
        *step_opens[:-3],
        "variable {L : Launch} {g : Nat} {d0 : D}",
        "",
    ]
    for pc in tails:
        t = sites.tails[pc]
        o = f"tail_{pc} L g ⟨s, w, p, x⟩"
        if isinstance(t, emit.RunTail):
            out += run_tail_lemma(sites, t)
            continue
        out += [
            f"/-- The outcome of the local code from instruction {pc}. -/",
            f"theorem local_tail_{pc} (hL : Launched L) (s : Site) (w : Nat → BitVec 64)",
            "    (p : Nat → Bool) (x : Nat → Value) :",
            f"    Local (codeFrom L g d0) {pc} (factsAt {pc} ⟨s, w, p, x⟩)",
            f"      ({o if t.outcome else f'some (some ({o}))'}) := by",
            f"  unfold tail_{pc}",
            "  dsimp only",
            *emit.prove(sites, t.node, t.outcome, 2),
            "",
        ]
    out += ["end", "", f"end {NS}"]
    files["Steps/Tails.lean"] = lean(out)
    for k, names in enumerate(parts):
        out = [
            HEAD + f"public import {MOD}.Steps.Tails\nimport Kernels.FlashKdaFwd.Flow.Code\n"
            "import Tactics.KernelRfl",
            "",
        ]
        out += ["@[expose] public section", "", *opens, *step_opens]
        for n in names:
            if n in plan.pre:
                out += [plan.pre[n], ""]
            hl = "(hL : Launched L) " if n in plan.launch else ""
            out.append(
                f"theorem stepAt_{n} {hl}{plan.vars[n]}: (codeFrom L g d0).StepAt"
                f" ⟨{plan.term[n]}, w, p, x⟩ := by\n  {plan.step[n]}"
            )
            out.append("")
        out += ["end", "", f"end {NS}"]
        files[f"Steps/Part{k:03d}.lean"] = lean(out)
    # Where the machine stops following a thread.
    out = [HEAD + f"public import {MOD}.Code", "", "@[expose] public section", "", *opens]
    out += [
        "/-- A transition at one site is never `some none`: it is a state, the end of the thread,",
        "or one of the conditional successors, which are never `some none`. -/",
        'macro "ne_leaf" : tactic => `(tactic| repeat\' (first',
        "  | exact across_ne _ _",
        "  | exact ldRow_ne _ _ _",
        "  | exact stRecv_ne _ _ _",
        "  | (intro h; cases h)",
        "  | split))",
        "",
        "variable (L : Launch) (g : Nat) (w : Nat → BitVec 64) (p : Nat → Bool) (x : Nat → Value)",
        "",
    ]

    def ne_tree(node, pad):
        """The proof that an outcome-valued tree is never `some none`."""
        lines = [f"{pad}refine mapaThen_ne fun peer => ?_" for h in node[-1].head if h[0] == "mapa"]
        if node[0] == "site":
            return lines + [f"{pad}intro h; cases h"]
        if node[0] == "tail":
            if sites.tails[node[1]].outcome:
                return lines + [f"{pad}exact tail_{node[1]}_ne L g _"]
            return lines + [f"{pad}intro h; cases h"]
        lines.append(f"{pad}split")
        for sub in (node[2], node[3]):
            inner = ne_tree(sub, pad + "  ")
            lines += [f"{pad}· " + inner[0].lstrip(), *inner[1:]]
        return lines

    def has_lets(node):
        return bool(node[-1].lets) or (node[0] == "if" and (has_lets(node[2]) or has_lets(node[3])))

    outcome_nodes = []
    for pc in tails:
        tl = sites.tails[pc]
        if isinstance(tl, emit.RunTail):
            outcome_nodes.append((f"tail_{pc}", tl))
        elif tl.outcome:
            outcome_nodes.append((f"tail_{pc}", tl.node))
    outcome_nodes += [
        (f"after_{n}", emit.after_info(sites, n)[1]) for n in done if n in plan.outcome
    ]
    for fn, node in outcome_nodes:
        if isinstance(node, emit.RunTail):
            if node.site:
                close = "exact across_ne _ _"
            elif sites.tails[node.end].outcome:
                close = f"exact under_ne (tail_{node.end}_ne L g _)"
            else:
                close = "exact under_ne (by intro h; cases h)"
            out += [
                f"theorem {fn}_ne (d : D) : {fn} L g d ≠ some none := by",
                f"  unfold {fn}",
                f"  {close}",
                "",
            ]
            continue
        out += [
            f"theorem {fn}_ne (d : D) : {fn} L g d ≠ some none := by",
            f"  unfold {fn}",
            *(["  dsimp only"] if has_lets(node) else []),
            *ne_tree(node, "  "),
            "",
        ]
    offset = sorted(int(n.rsplit("_", 1)[1]) for n in plan.offset)
    for kind, count, row, ra in kinds:
        cov = covered[kind]
        if kind == "load":
            continue

        def leaf(k, kind=kind, cov=cov, ra=ra, count=count):
            if k not in cov:
                return ["intro h; cases h"]
            name = f"{kind}_{k}"
            return [
                f"rw [show next L g ⟨.{kind} ⟨{k}, hk⟩{ra}, w, p, x⟩ e = _ from",
                f"  next_{name} w p x e{ra}]",
                f"exact after_{name}_ne L g _" if name in plan.outcome else "ne_leaf",
            ]

        out += [
            f"theorem next_{kind}_ne (j : Fin {count}) {row + ' ' if row else ''}(e : Event) :",
            f"    next L g ⟨.{kind} j{ra}, w, p, x⟩ e ≠ some none := by",
            "  obtain ⟨k, hk⟩ := j",
            *split(0, count, leaf, "  "),
            "",
        ]
    nload = sites.counts["load"]
    cov = covered["load"]
    what = "∃ a bs v, e.kind = .rd a bs ∧ rebuild 3 bs = .ok v ∧ ∀ y, v ≠ .bits 64 y"

    def leaf_give(k):
        eq = f"next L g ⟨.load ⟨{k}, hk⟩, w, p, x⟩ e = _ from next_load_{k} w p x e"
        if k in offset:
            return [f"rw [show {eq}] at h", "exact ⟨rfl, loadWord_giveUp h⟩"]
        if k in cov:
            return [f"rw [show {eq}] at h", "exact absurd h (by ne_leaf)"]
        return ["exact absurd h (by intro h; cases h)"]

    def leaf_bits(k):
        if k in offset:
            return [f"exact ⟨_, (next_load_{k} w p x _).trans (loadWord_bits hv)⟩"]
        return ["exact absurd hj (by decide)"]

    def leaf_pc(k):
        return ["rfl"] if k in offset else ["exact absurd hj (by decide)"]

    out += [
        "/-- The ordinals of the loads of the read-only offsets array (the 21 `ld.global.b64`), the",
        "sites where the machine follows a 64-bit integer only. -/",
        "def offsetLoads : List Nat := [" + ", ".join(map(str, offset)) + "]",
        "",
        "/-- These sites are the instructions the assumption `inputReadOnly` names. -/",
        f"theorem offsetLoads_pc (j : Fin {nload}) (hj : offsetLoads.contains j.val = true) :",
        "    Assumptions.inputReadSites.contains (Site.load j).pc = true := by",
        "  obtain ⟨k, hk⟩ := j",
        "  replace hj : offsetLoads.contains k = true := hj",
        *split(0, nload, leaf_pc, "  "),
        "",
        "/-- At a load the machine stops following only if the load is one of the offsets array",
        "and the bytes read rebuild to a value that is not a 64-bit integer. -/",
        f"theorem next_load_giveUp (j : Fin {nload}) (e : Event)",
        "    (h : next L g ⟨.load j, w, p, x⟩ e = some none) :",
        f"    offsetLoads.contains j.val = true ∧ {what} := by",
        "  obtain ⟨k, hk⟩ := j",
        *split(0, nload, leaf_give, "  "),
        "",
        "/-- **At a load of the offsets array, a read whose bytes rebuild to a 64-bit integer is",
        "followed.** The successor is `after_load_<k> L g d y` for the integer `y` (the site's",
        "equation `next_load_<k>` and `loadWord_bits`), the file after the code that follows the",
        "load with `y` in the destination register. -/",
        f"theorem next_load_bits (j : Fin {nload}) (hj : offsetLoads.contains j.val = true)",
        "    (pc : Nat) (a : Acc) (bs : List (Option Byte)) (y : BitVec 64)",
        "    (hv : rebuild 3 bs = .ok (.bits 64 y)) :",
        "    ∃ d', next L g ⟨.load j, w, p, x⟩ ⟨pc, .rd a bs⟩ = some (some d') := by",
        "  obtain ⟨k, hk⟩ := j",
        "  replace hj : offsetLoads.contains k = true := hj",
        *split(0, nload, leaf_bits, "  "),
        "",
        "/-- **The machine stops following a thread (`some none`) in one case only**: at one of the",
        "21 loads of the offsets array, on a read whose bytes rebuild to a value that is not a",
        "64-bit integer. Everywhere else it follows the thread or says that it stops. This is the",
        "hypothesis `Frame.tracked_of` asks about: the layer above shows that such a read returns",
        "the launch's integer bytes (the assumption `inputReadOnly` and the precondition). -/",
        "theorem next_giveUp (d : D) (e : Event) (h : next L g d e = some none) :",
        "    ∃ j, d.site = .load j ∧ offsetLoads.contains j.val = true ∧",
        f"      {what} := by",
        "  obtain ⟨s, w, p, x⟩ := d",
        "  cases s with",
        "  | load j => exact ⟨j, rfl, next_load_giveUp L g w p x j e h⟩",
    ]
    for kind, _, row, ra in kinds:
        if kind != "load":
            out.append(f"  | {kind} j{ra} => exact absurd h (next_{kind}_ne L g w p x j{ra} e)")
    out += ["", "end", "", f"end {NS}"]
    files["Never.lean"] = lean(out)
    # The dispatch over the generated states.
    out = [HEAD + "".join(f"public import {MOD}.Steps.Part{k:03d}\n" for k in range(len(parts)))]
    out += ["", "@[expose] public section", "", *opens, *step_opens[-3:]]
    # With every site covered the dispatch is total; otherwise it is stated on the covered
    # ordinals (`cov_<kind>`, `Site.covered`).
    complete = not plan.skipped
    for kind, count, row, ra in kinds:
        cov = covered[kind]
        if complete:
            assert cov == list(range(count)), kind

            def leaf(k, kind=kind, ra=ra):
                hl = " hL" if f"{kind}_{k}" in plan.launch else ""
                return [f"exact stepAt_{kind}_{k} w p x{hl}{ra}"]

            out += [
                f"theorem stepAt_{kind} (hL : Launched L) (j : Fin {count})"
                f"{' ' + row if row else ''} :",
                f"    (codeFrom L g d0).StepAt ⟨.{kind} j{ra}, w, p, x⟩ := by",
                "  obtain ⟨k, hk⟩ := j",
                *split(0, count, leaf, "  "),
                "",
            ]
            continue
        out += [
            f"/-- The ordinals of the `{kind}` sites whose step is generated"
            f" ({len(cov)} of {count}). -/",
            f"def cov_{kind} : List Nat := [" + ", ".join(map(str, cov)) + "]",
            "",
        ]
        if not cov:
            continue

        def leaf(k, kind=kind, cov=cov, ra=ra):
            if k in cov:
                hl = " hL" if f"{kind}_{k}" in plan.launch else ""
                return [f"exact stepAt_{kind}_{k} w p x{hl}{ra}"]
            return ["exact absurd hj (by decide)"]

        out += [
            f"theorem stepAt_{kind} (hL : Launched L) (j : Fin {count}) {row + ' ' if row else ''}"
            f"(hj : cov_{kind}.contains j.val = true) :",
            f"    (codeFrom L g d0).StepAt ⟨.{kind} j{ra}, w, p, x⟩ := by",
            "  obtain ⟨k, hk⟩ := j",
            f"  replace hj : cov_{kind}.contains k = true := hj",
            *split(0, count, leaf, "  "),
            "",
        ]
    if complete:
        out += [
            "/-- **The step obligation of every state**, under the launch facts (`Launched`, which",
            "`Start.lean` proves from the specification's precondition). -/",
            "theorem stepAt (hL : Launched L) (d : D) : (codeFrom L g d0).StepAt d := by",
            "  obtain ⟨s, w, p, x⟩ := d",
            "  cases s with",
        ]
        for kind, _, row, ra in kinds:
            out.append(f"  | {kind} j{ra} => exact stepAt_{kind} w p x hL j{ra}")
        out += ["", "end", "", f"end {NS}"]
        files["StepAt.lean"] = lean(out)
        return files, plan, decls
    out += [
        "/-- Whether the step of a site is generated (every site, once every kind has its",
        "recipe). -/",
        "def Site.covered : Site → Bool",
    ]
    for kind, _, row, ra in kinds:
        out.append(f"  | .{kind} j{' _' * len(ra.split())} => cov_{kind}.contains j.val")
    out += [
        "",
        "/-- **The step obligation of every generated state**, under the launch facts",
        "(`Launched`, which `Start.lean` proves from the specification's precondition). -/",
        "theorem stepAt (hL : Launched L) (d : D) (hd : d.site.covered = true) :",
        "    (codeFrom L g d0).StepAt d := by",
        "  obtain ⟨s, w, p, x⟩ := d",
        "  cases s with",
    ]
    for kind, _, row, ra in kinds:
        if covered[kind]:
            out.append(f"  | {kind} j{ra} => exact stepAt_{kind} w p x hL j{ra} hd")
        else:
            out.append(f"  | {kind} j{ra} => exact absurd hd (by simp [Site.covered, cov_{kind}])")
    out += ["", "end", "", f"end {NS}"]
    files["StepAt.lean"] = lean(out)
    return files, plan, decls


def main():
    cli = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    cli.add_argument("--check", action="store_true", help="write nothing; fail if a file is stale")
    args = cli.parse_args()
    sites = emit.Sites()
    files, plan, decls = render(sites)
    targets = {OUT / name: text for name, text in files.items()}
    targets.update({DECLS / name: text for name, text in decls.items()})
    # The numbered files of an earlier run: a part that is no longer made is removed.
    previous = [p for f in ("After", "Steps", "Run") for p in (OUT / f).glob("Part*.lean")]
    previous += DECLS.glob("runs_*.json")
    outputs.write_or_check(targets, args.check, previous)
