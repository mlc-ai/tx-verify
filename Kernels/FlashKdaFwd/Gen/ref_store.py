"""Generate `Proof/Ref/Store/Family.lean`, the step lemmas of the regular sites of the store phase.

Two families of sites of the store phase differ only in constants: the sixteen tensor stores of
a full tile (`st_ts_0` .. `st_ts_15`) and the first seven of the eight global stores of a chunk
(`st_gst_0` .. `st_gst_6`). The file has their step lemmas, the two dispatch lemmas `step_ts`
and `step_gst` that connect them (and the hand-written `st_gst_7`) to the machine's transition
function, and `next_ts`, `next_gst` (the machine has a successor state at these sites for every
event).

The Lean text comes from the templates below and reads no file. The site numbers are those of
the generated thread machine: tensor store `i` of the phase is the site `tensorCopy (TS0 + i)`,
global store `j` is `store (GS0 + j)`.

    python3 Kernels/FlashKdaFwd/Gen/ref_store.py            # write Family.lean
    python3 Kernels/FlashKdaFwd/Gen/ref_store.py --check    # write nothing; fail if it is stale
                                                            # or the simulator disagrees

After the comparison of `Family.lean`, `--check` reads the frozen PTX (through `analysis.load`)
and replays threads 160, 161 and 191 of a block on the control-flow simulator (`simulate.py`;
lengths 0 to 112, sequence index 0 and 1, polls succeeding at once and failing once or twice).
It compares, at every event between the `bar.sync 0` at 1402 and the one at 3113, with the
closed forms of `Proof/Ref/Store`: the event and its operands (`Shapes.lean: Ev`), the registers
`%r1806` (tile), `%r1809` (row) and `%r1811` (8 times the chunk) that
`Progress.lean: tileOf, leftOf` read, the ledger in the protocol's terms
(`Exports.lean: counts_at`) and the counted events left (`Progress.lean: leftAt`). The simulator
fires one event for the vector load `ld.shared.v4.b32`; the thread machine fires four (one per
element), which the comparison accounts for (a load counts 4).
"""

import argparse
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import analysis  # noqa: E402
import outputs  # noqa: E402
import simulate  # noqa: E402

OUT = HERE.parent / "Proof" / "Ref" / "Store" / "Family.lean"
TS0, GS0 = 226, 10
HEAD = """-- SPDX-License-Identifier: Apache-2.0
-- Generated by Kernels/FlashKdaFwd/Gen/ref_store.py; do not edit.
module

public import Kernels.FlashKdaFwd.Proof.Ref.Store.Steps

@[expose] public section

/-! # Store phase: the step lemmas of the two families of sites

The sixteen tensor stores of a full tile (`st_ts_<i>`: store `i` computes the shared source
address of store `i + 1`, the last one leads to the group commit) and the first seven global
stores of a chunk (`st_gst_<j>`: nothing is computed between them). The irregular sites are in
`Steps.lean`. Every lemma names the successor position (`Step.ts`, `Step.commit`, `Step.gst`).
`step_ts`, `step_gst`: the same for a successor of the machine (`Thread.next`); `next_ts`,
`next_gst`: at these sites the machine has a successor state for every event. -/

namespace PTX.Kernels.FlashKdaFwd.Proof.Ref.Store
open PTX PTX.Proof PTX.Flow PTX.Flow.Arith32
open PTX.Kernels.FlashKdaFwd PTX.Kernels.FlashKdaFwd.Proof.Thread
open PTX.Kernels.FlashKdaFwd.Proof.Ref PTX.Kernels.FlashKdaFwd.Recurrence

noncomputable section
set_option linter.unusedSimpArgs false
set_option linter.unusedTactic false
set_option linter.unreachableTactic false
set_option linter.unusedVariables false
set_option maxRecDepth 100000
set_option maxHeartbeats 4000000

variable {P : Params} {L : Launch} {mem0 : Mem0} {g : Nat}
  {w : Nat → BitVec 64} {p : Nat → Bool} {x : Nat → Value}
"""
TS = """
theorem st_ts_{i} (hpre : Pre P L mem0) (t : Nat)
    (h : RefAt P g (.ts t {i}) ⟨.tensorCopy {n}, w, p, x⟩) :
    Succ P g (.ts t {i}) dTs (after_tensorCopy_{n} L g ⟨.tensorCopy {n}, w, p, x⟩) := by
  obtain ⟨-, hk, hp⟩ := h
  have hp' := hp
  simp only [AtPos, Tile, Mult, tsSrc, finVal, getLit] at hp'
  have hs := shared_lt hpre
  refine ⟨.ts t {j}, ⟨rfl, ?_, ?_⟩, (by led_of t), Step.ts t {i} {j} rfl⟩
  · keep_of hk [after_tensorCopy_{n}]
  · pos_facts [after_tensorCopy_{n}] [hp']
"""
TS_LAST = """
theorem st_ts_15 (hpre : Pre P L mem0) (t : Nat)
    (h : RefAt P g (.ts t 15) ⟨.tensorCopy {n}, w, p, x⟩) :
    Succ P g (.ts t 15) dTs (after_tensorCopy_{n} L g ⟨.tensorCopy {n}, w, p, x⟩) :=
  ⟨.commit t, ⟨rfl, Keep.of_w h.keep rfl rfl rfl rfl rfl rfl, h.pos.1, h.pos.2.1⟩,
    (by led_of t), Step.commit t⟩
"""
GS = """
theorem st_gst_{j} (t row c : Nat) (h : RefAt P g (.gst t row c {j}) ⟨.store {n}, w, p, x⟩) :
    Succ P g (.gst t row c {j}) dGst (after_store_{n} L g ⟨.store {n}, w, p, x⟩) :=
  ⟨.gst t row c {k}, ⟨rfl, (row_same h.keep h.pos).1, (row_same h.keep h.pos).2⟩,
    (by led_of t), Step.gst t row c {j} {k} rfl⟩
"""
DISPATCH_TS_HEAD = """
/-- **A tensor store of a full tile**, for every `i`: the successor of the machine. -/
theorem step_ts (hpre : Pre P L mem0) (t : Nat) (i : Fin 16)
    (hr : RefAt P g (.ts t i) ⟨(Pos.ts t i).site, w, p, x⟩) {e : Event} {s' : D}
    (hn : Thread.next L g ⟨(Pos.ts t i).site, w, p, x⟩ e = some (some s')) :
    Succ P g (.ts t i) dTs s' := by
  fin_cases i
"""
DISPATCH_TS = """  · obtain rfl := Option.some.inj (Option.some.inj
      ((next_tensorCopy_{n} (L := L) (g := g) _ _ _ _).symm.trans hn))
    exact st_ts_{i} hpre t hr
"""
DISPATCH_GS_HEAD = """
/-- **A global store of a chunk**, for every `j`: the successor of the machine. -/
theorem step_gst (hpre : Pre P L mem0) (hg : g < L.threads) (t row c : Nat) (j : Fin 8)
    (hr : RefAt P g (.gst t row c j) ⟨(Pos.gst t row c j).site, w, p, x⟩) {e : Event} {s' : D}
    (hn : Thread.next L g ⟨(Pos.gst t row c j).site, w, p, x⟩ e = some (some s')) :
    Succ P g (.gst t row c j) dGst s' := by
  fin_cases j
"""
DISPATCH_GS = """  · obtain rfl := Option.some.inj (Option.some.inj
      ((next_store_{n} (L := L) (g := g) _ _ _ _).symm.trans hn))
    exact {call}
"""
NEXT_TS_HEAD = """
/-- **The machine has a successor state at a tensor store**, whatever the event. -/
theorem next_ts (t : Nat) (i : Fin 16) (e : Event) :
    ∃ d', Thread.next L g ⟨(Pos.ts t i).site, w, p, x⟩ e = some (some d') := by
  fin_cases i
"""
NEXT_TS = """  · exact ⟨_, next_tensorCopy_{n} (L := L) (g := g) _ _ _ _⟩
"""
NEXT_GS_HEAD = """
/-- **The machine has a successor state at a global store**, whatever the event. -/
theorem next_gst (t row c : Nat) (j : Fin 8) (e : Event) :
    ∃ d', Thread.next L g ⟨(Pos.gst t row c j).site, w, p, x⟩ e = some (some d') := by
  fin_cases j
"""
NEXT_GS = """  · exact ⟨_, next_store_{n} (L := L) (g := g) _ _ _ _⟩
"""
TAIL = """
end

end PTX.Kernels.FlashKdaFwd.Proof.Ref.Store
"""


def family():
    """The text of `Family.lean`."""
    out = [HEAD]
    for i in range(15):
        out.append(TS.format(i=i, j=i + 1, n=TS0 + i))
    out.append(TS_LAST.format(n=TS0 + 15))
    for j in range(7):
        out.append(GS.format(j=j, k=j + 1, n=GS0 + j))
    out.append(DISPATCH_TS_HEAD)
    for i in range(16):
        out.append(DISPATCH_TS.format(i=i, n=TS0 + i))
    out.append(DISPATCH_GS_HEAD)
    for j in range(8):
        call = f"st_gst_{j} t row c hr" if j < 7 else "st_gst_7 hpre hg t row c hr"
        out.append(DISPATCH_GS.format(n=GS0 + j, call=call))
    out.append(NEXT_TS_HEAD)
    for i in range(16):
        out.append(NEXT_TS.format(n=TS0 + i))
    out.append(NEXT_GS_HEAD)
    for j in range(8):
        out.append(NEXT_GS.format(n=GS0 + j))
    out.append(TAIL)
    return "".join(out)


def check():
    """Compare the closed forms of the store phase with the simulator; returns the number of
    runs with a mismatch."""
    code, _, _ = analysis.load()
    shared, output = simulate.SHARED, simulate.OUTPUT

    class Traced(simulate.Thread):
        """A thread that records the known registers before each of its events."""

        def event(self, pc, ins, names):
            snap = {k.split("#")[-1]: v for k, v in self.env.items() if v is not None}
            rec = super().event(pc, ins, names)
            rec["env"] = snap
            return rec

    def uses(tile, o):
        return (tile + 1 - o) // 2

    bad = runs = 0
    for length in [0, 1, 2, 5, 15, 16, 17, 31, 32, 33, 48, 49, 64, 100, 112]:
        for seq, lengths in [(0, [length, 7]), (1, [3, length])]:
            for tid in [160, 161, 191]:
                for fail in [0, 1, 2]:
                    runs += 1
                    first, head, heads = sum(lengths[:seq]), 1, 2
                    th = Traced(code, tid, seq, head, lengths, heads, fail)
                    th.run()
                    pcs = [e["pc"] for e in th.events]
                    i0, i7 = pcs.index(1402), pcs.index(3113)
                    before, phase = th.events[:i0], th.events[i0:i7]
                    full, rest = divmod(length, 16)
                    part = 0 if rest == 0 else 3 + 192 * rest
                    lead = tid == 160 and length >= 1
                    left = 1 + 20 * full + part if lead else 1
                    errors = []

                    def expect(cond, what, errors=errors):
                        if not cond:
                            errors.append(what)

                    expect(sum(1 for e in before if e["op"].startswith("bar.sync")) == 5, "5 bars")
                    expect(phase[0]["pc"] == 1402, "entry")
                    left -= 1
                    polls, arrs = [0, 0], [0, 0]
                    pos = 1
                    tiles_ = (length + 15) // 16 if lead else 0
                    for t in range(tiles_):
                        o = t % 2
                        while True:  # the poll, repeated while it fails
                            e = phase[pos]
                            pos += 1
                            env = e["env"]
                            expect(
                                e["pc"] == 2987
                                and e["mbar"] == shared + 98352 + 8 * o
                                and e["parity"] == t // 2 % 2,
                                f"poll {t}",
                            )
                            expect(env.get("%r1806") == t, f"%r1806 at poll {t}")
                            expect(
                                polls == [uses(t, 0), uses(t, 1)]
                                and arrs == [uses(t, 0), uses(t, 1)],
                                f"counts at poll {t}",
                            )
                            expect(left == 20 * (full - t) + part, f"left at poll {t}")
                            if e["ok"]:
                                break
                        polls[o] += 1
                        left -= 1
                        if 16 * t + 16 <= length:
                            for i in range(16):
                                e = phase[pos]
                                pos += 1
                                v = list(e["operands"].values())
                                expect(
                                    e["pc"] == 3052 + 2 * i
                                    and v[1:]
                                    == [
                                        8 * i,
                                        16 * t + first,
                                        head,
                                        shared + 4096 * o + 86912 + 256 * i,
                                    ],
                                    f"store {t} {i}",
                                )
                                expect(e["env"].get("%r1806") == t, f"%r1806 at store {t} {i}")
                                expect(left == 20 * (full - t) + part - 1 - i, f"left {t} {i}")
                                left -= 1
                            expect(phase[pos]["pc"] == 3083, f"commit {t}")
                            pos += 1
                            left -= 1
                        else:
                            for row in range(length - 16 * t):
                                for c in range(16):
                                    e = phase[pos]
                                    pos += 1
                                    env = e["env"]
                                    expect(
                                        e["pc"] == 3020
                                        and e["addr"]
                                        == shared + 4096 * o + 16 * row + 86912 + 256 * c,
                                        f"load {t} {row} {c}",
                                    )
                                    expect(
                                        env.get("%r1806") == t
                                        and env.get("%r1809") == row
                                        and env.get("%r1811") == 8 * c,
                                        f"regs {t} {row} {c}",
                                    )
                                    expect(left == 2 + 192 * (rest - row) - 12 * c, "left at load")
                                    left -= 4
                                    for j in range(8):
                                        e = phase[pos]
                                        pos += 1
                                        expect(
                                            e["pc"] == 3025 + j
                                            and e["addr"]
                                            == output
                                            + 256 * ((first + 16 * t + row) * heads + head)
                                            + 2 * (8 * c + j),
                                            f"gst {t} {row} {c} {j}",
                                        )
                                        left -= 1
                        expect(phase[pos]["pc"] == 3093, f"group wait {t}")
                        at_wait = 20 * (full - t) + part - 18 if t < full else 2
                        expect(left == at_wait, "left at the group wait")
                        pos += 1
                        left -= 1
                        e = phase[pos]
                        pos += 1
                        expect(
                            e["pc"] == 3101 and e["mbar"] == shared + 98368 + 8 * o, f"arrive {t}"
                        )
                        expect(e["env"].get("%r1806") == t, f"%r1806 at arrive {t}")
                        arrs[o] += 1
                        left -= 1
                    expect(pos == len(phase), "events after the last tile")
                    expect(left == 0, f"left at the exit: {left}")
                    if errors:
                        bad += 1
                        print("MISMATCH", length, seq, tid, fail, errors[:3])
    print(f"{runs} runs, {bad} with a mismatch")
    return bad


def main():
    cli = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    cli.add_argument(
        "--check",
        action="store_true",
        help="write nothing; fail if the file is stale or the simulator disagrees",
    )
    args = cli.parse_args()
    outputs.write_or_check({OUT: family()}, args.check)
    if args.check and check():
        sys.exit(1)


if __name__ == "__main__":
    main()
