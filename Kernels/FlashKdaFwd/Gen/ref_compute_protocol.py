"""Generate `Proof/Ref/Compute/ExportsProtocolAccess.lean`.

The Compute phase of the reference layer (the tile loop of a compute thread, instructions 2106
to 2944) has one closed-form lemma per position with a memory access (`Access.lean: acc_<n>`,
80 positions of a tile) and one transition equation per site of the thread machine
(`Thread/Next.lean: next_<site>`). The exports of the phase for the protocol contracts need the
same facts as ONE statement over all positions. This script writes the two case analyses:

* `acc_at`: the event at a position with a memory access is the read, or the write, of the
  footprint `accOf P L g t n` that the phase's table `addrTab` gives (80 cases, one per
  `acc_<n>`);
* `st_row`: the state after the matrix event of an `stmatrix` (18 positions) is at the
  second-event site of the instruction and carries the 16 bytes the lane received, all known.

Reads `Gen/Tables/ref_compute.json` (written by `ref_compute.py`): the positions of a tile
with the kind and ordinal of their site and the address register, constant and size of their
access.

    python3 Kernels/FlashKdaFwd/Gen/ref_compute_protocol.py            # write the file
    python3 Kernels/FlashKdaFwd/Gen/ref_compute_protocol.py --check    # write nothing; fail if
                                                                       # the file is stale
"""

import argparse
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import outputs  # noqa: E402

TABLE = HERE / "Tables" / "ref_compute.json"
OUT = HERE.parent / "Proof" / "Ref" / "Compute" / "ExportsProtocolAccess.lean"

HEADER = """-- SPDX-License-Identifier: Apache-2.0
-- Generated by Kernels/FlashKdaFwd/Gen/ref_compute_protocol.py; do not edit.
module

public import Kernels.FlashKdaFwd.Proof.Ref.Compute.Reach

@[expose] public section

/-! # The memory accesses of the Compute phase as one statement over the positions

`Access.lean` has one lemma per position of a tile with a memory access (`acc_<n>`: the row read
of an `ldmatrix`, the row write of an `stmatrix`, a scalar load; 80 positions). The exports of
the phase need them as one statement about "the event at position `n`". This file is that case
analysis and nothing else:

* `addrOf n`: the entry of the phase's table `addrTab` for position `n`: the register that holds
  the address of the access, the constant the instruction adds and the size in bytes (size 0:
  the position has no memory access);
* `accOf P L g t n`: the footprint of the access at position `n` of tile `t` of thread `g`: the
  bytes of the thread's own block (`g / L.block`) from the closed form of the register plus the
  constant;
* `isWr k`: the kind of site `k` (`SK`, `Forms.lean`) is the row write of an `stmatrix`;
* `acc_at`: at a position with an access, the event is a read of `accOf P L g t n` (and the
  position is no row write) or the write of `accOf P L g t n` with the bytes `row.reduceOption`
  of the row the site carries (and the position is a row write). It is never undefined
  behaviour;
* `st_row`: when the successor of the matrix event of an `stmatrix` is a state, that state is at
  the instruction's second site (`matrixStoreWr j row`) and the row it carries is 16 known
  bytes. This is why the write event of an `stmatrix` carries 16 bytes.

A *position* is the index (0 to 267) of an event in the straight line of the 268 events of one
tile (`Inv.lean`). Everything here is in the namespace `Compute.Proto`, the namespace of the
phase's exports for the protocol contracts (`ExportsProtocol.lean`). -/

namespace PTX.Kernels.FlashKdaFwd.Proof.Ref.Compute.Proto
open PTX PTX.Proof PTX.Flow PTX.Flow.Arith32
open PTX.Kernels.FlashKdaFwd PTX.Kernels.FlashKdaFwd.Proof.Thread
open PTX.Kernels.FlashKdaFwd.Proof.Ref PTX.Kernels.FlashKdaFwd.Recurrence

noncomputable section

variable {P : Params} {L : Launch} {mem0 : Mem0} {g t : Nat}
  {w : Nat → BitVec 64} {p : Nat → Bool} {x : Nat → Value}
  {tt : TState} {ins : Instr} {e : Event} {o : Option TState}

/-- The address register, the added constant and the size in bytes of the memory access of
position `n` (size 0: no memory access at the position). -/
def addrOf (n : Nat) : Nat × Nat × Nat := addrTab.getD n (0, 0, 0)

/-- The footprint of the memory access at position `n` of tile `t` of thread `g`: in the shared
memory of the thread's own block, at the closed form of the address register plus the
instruction's constant. -/
def accOf (P : Params) (L : Launch) (g t n : Nat) : Acc :=
  { loc := ⟨.shared, g / L.block, regVal P g t (addrOf n).1 + (addrOf n).2.1⟩,
    size := (addrOf n).2.2 }

/-- The kind of site is the row write of an `stmatrix` (the second event of the instruction). -/
def isWr : SK → Bool
  | .stWr _ => true
  | _ => false
"""


def wrap(items, indent="  ", width=98):
    """A Lean list literal of `items`, wrapped; continuation lines are indented one more."""
    lines, cur = [], indent + "["
    for i, it in enumerate(items):
        piece = it + (", " if i + 1 < len(items) else "]")
        if len(cur) + len(piece.rstrip()) > width:
            lines.append(cur.rstrip())
            cur = indent + " "
        cur += piece
    lines.append(cur.rstrip())
    return "\n".join(lines)


def alts(n, first, indent="    ", width=98):
    """An `rcases` pattern with `n` alternatives `rfl`, after the text `first`."""
    lines, cur = [], first
    for i in range(n):
        piece = "rfl" + (" | " if i + 1 < n else "")
        if len(cur) + len(piece.rstrip()) > width:
            lines.append(cur.rstrip())
            cur = indent
        cur += piece
    lines.append(cur.rstrip())
    return "\n".join(lines)


def main():
    cli = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    cli.add_argument("--check", action="store_true", help="write nothing; fail if stale")
    args = cli.parse_args()
    tab = json.loads(TABLE.read_text())
    pos = tab["positions"]
    acc = [q for q in pos if q["address"] is not None]
    st = [q for q in pos if q["site"] == "matrixStore"]
    for q in st:  # the row write is the next position, at the same instruction
        nxt = pos[q["n"] + 1]
        assert nxt["site"] == "matrixStoreWr" and nxt["ordinal"] == q["ordinal"], q
    out = [HEADER]

    out.append("/-- The positions of a tile with a memory access. -/")
    out.append("def accPos : List Nat :=\n" + wrap([str(q["n"]) for q in acc]) + "\n")
    out.append(
        "theorem acc_pos : ∀ n < 268, (addrOf n).2.2 ≠ 0 → n ∈ accPos := by decide +kernel\n"
    )
    out.append("""/-- **The event at a position with a memory access**: a read of the position's footprint, or
(at the row write of an `stmatrix`) the write of the bytes of the site's row to it. -/
theorem acc_at (hpre : Pre P L mem0) {n : Nat} {site : Site} (h : Tile P L g t n w p x)
    (hs : (skOf n).At site) (hat : (code L g).AtD ⟨site, w, p, x⟩ tt)
    (hc : kernel.code[site.pc]? = some ins)
    (hf : Fires site.pc (eventTmpl Assumptions.all L g tt ins.op) e o)
    (ha : (addrOf n).2.2 ≠ 0) :
    (∃ bs, e.kind = .rd (accOf P L g t n) bs ∧ isWr (skOf n) = false) ∨
      ∃ j row, site = .matrixStoreWr j row ∧
        e.kind = .wr (accOf P L g t n) row.reduceOption ∧ isWr (skOf n) = true := by
  have hmem := acc_pos n h.pos ha
  simp only [accPos, List.mem_cons, List.not_mem_nil, or_false] at hmem""")
    out.append(alts(len(acc), "  rcases hmem with "))
    for q in acc:
        n, site, j = q["n"], q["site"], q["ordinal"]
        if site == "matrixStoreWr":
            out.append(f"  · obtain ⟨row, rfl⟩ : ∃ row, site = .matrixStoreWr {j} row := hs")
            out.append(f"    obtain rfl := acc_{n} hpre h hat hc hf")
            out.append("    exact .inr ⟨_, row, rfl, rfl, rfl⟩")
        else:
            out.append(f"  · obtain rfl : site = .{site} {j} := hs")
            out.append(f"    obtain ⟨bs, rfl⟩ := acc_{n} hpre h hat hc hf")
            out.append("    exact .inl ⟨bs, rfl, rfl⟩")
    out.append("")

    out.append("/-- The positions of the matrix event of an `stmatrix` (its first event). -/")
    out.append("def stPos : List Nat :=\n" + wrap([str(q["n"]) for q in st]) + "\n")
    out.append(
        "theorem st_pos : ∀ n < 268, isWr (skOf (n + 1)) = true → n ∈ stPos := by decide +kernel\n"
    )
    out.append("""/-- The state behind the matrix event of an `stmatrix`, when it is a state: at the second
site of the instruction, with the 16 bytes received, all known. -/
theorem stRecv_row {d d' : D} {recv : List (Option Byte)} {s : List (Option Byte) → Site}
    (h : stRecv d recv s = some (some d')) :
    d'.site = s recv ∧ recv.length = 16 ∧ recv.all Option.isSome = true := by
  unfold stRecv at h
  split at h
  · rename_i hc
    obtain rfl := Option.some.inj (Option.some.inj h)
    exact ⟨rfl, hc.1, hc.2⟩
  · cases h

/-- **The row of an `stmatrix` write**: the successor of the matrix event of an `stmatrix`
(position `n`, the row write being position `n + 1`) is at the row-write site of the
instruction and carries 16 known bytes. -/
theorem st_row {n : Nat} {site : Site} {s' : D} (hn : n < 268)
    (hw : isWr (skOf (n + 1)) = true) (hs : (skOf n).At site)
    (hnext : Thread.next L g ⟨site, w, p, x⟩ e = some (some s')) :
    ∃ j row, s'.site = .matrixStoreWr j row ∧ row.length = 16 ∧
      row.all Option.isSome = true := by
  have hmem := st_pos n hn hw
  simp only [stPos, List.mem_cons, List.not_mem_nil, or_false] at hmem""")
    out.append(alts(len(st), "  rcases hmem with "))
    for q in st:
        j = q["ordinal"]
        out.append(f"  · obtain rfl : site = .matrixStore {j} := hs")
        out.append(f"    rw [next_matrixStore_{j}] at hnext")
        out.append("    obtain ⟨op, own, recv, -, hf⟩ := stNext_some hnext")
        out.append("    obtain ⟨h1, h2, h3⟩ := stRecv_row hf")
        out.append("    exact ⟨_, recv, h1, h2, h3⟩")
    out.append("")
    out.append("end\n")
    out.append("end PTX.Kernels.FlashKdaFwd.Proof.Ref.Compute.Proto\n")
    text = "\n".join(out)
    outputs.write_or_check({OUT: text}, args.check)


if __name__ == "__main__":
    main()
