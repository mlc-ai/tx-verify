def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument(
        "--check",
        action="store_true",
        help="write nothing; fail if a file is stale or the simulator disagrees",
    )
    args = ap.parse_args()
    table = build()
    files = {
        TABLE: json.dumps(table, indent=1) + "\n",
        OUT / "Tables.lean": tables_lean(table),
        OUT / "Sites.lean": sites_lean(table),
    }
    outputs.write_or_check(files, args.check)
    if args.check:
        check(table)


if __name__ == "__main__":
    main()
