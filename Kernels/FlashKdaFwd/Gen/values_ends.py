"""Generator of the per-site statements of the value layer at the ends of the tile loop.

The four stretches of `Proof/Values/Ends/` (the conversion loop, the carry loads, the final
stores, the store path of a partial tile) have families of regular sites: ten load / store pairs
of the conversion loop, 128 carry loads, 128 final stores. This script reads the register table
`Gen/Tables/matrix_table.json` (written by `matrix_table.py`; key `carries`: for each carry
register its FP32 entry and the positions of its load and its store outside the tile loop) and
the frozen PTX (through `analysis.load`), and writes

* `Gen/Tables/values_ends.json`: the sites of the three families, each with its instruction
  position, the ordinal of its site among the sites of its kind, its registers and the name of
  the data run that follows it;
* `Proof/Values/Ends/Gen/Tables.lean`: the carry registers in the order of their loads
  (`carryTable`: register id, key block, value block, half, accumulator register, and the
  constant the instruction adds to the lane's base pointer) and the registers of the ten
  conversion pairs (`convTable`);
* `Proof/Values/Ends/Gen/Steps.lean`: for each site, the machine's successor across its event
  (`conv_<j>`, `carry_<j>`, `final_<j>`: what the event must be for the thread to be followed,
  the successor's site and its data slots), and one dispatcher per family.

    python3 Kernels/FlashKdaFwd/Gen/values_ends.py            # write the three files
    python3 Kernels/FlashKdaFwd/Gen/values_ends.py --check    # write nothing; fail if one is stale

Checks made here (the script stops otherwise): the loads of the carries are the instructions
765, 770, …, 1400 and their stores 3132, 3137, …, 3767, in the same register order; the constant
of each is `32768 + 4 * (2048 m + 1024 (r / 2) + 128 bi + 64 q + 8 (r % 2))`; each conversion
pair is `ld.b32 x, [p]`, `cvt.rn.bf16.f32 y, x`, …, `st.shared.b16 [a], y`.
"""

import argparse
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
KERNEL = HERE.parent
sys.path.insert(0, str(HERE))
import analysis  # noqa: E402
import outputs  # noqa: E402

TABLE = HERE / "Tables" / "matrix_table.json"
JSON_OUT = HERE / "Tables" / "values_ends.json"
OUT = KERNEL / "Proof" / "Values" / "Ends" / "Gen"
WIDTH = 100
NS = "PTX.Kernels.FlashKdaFwd.Proof.Values.Ends"

HEAD = """-- SPDX-License-Identifier: Apache-2.0
-- Generated by Kernels/FlashKdaFwd/Gen/values_ends.py; do not edit.
module
"""

CONV_LOADS = [426, 443, 473, 490, 513, 530, 553, 570, 593, 610]
CARRY_LOAD0, FINAL_STORE0, STEP = 765, 3132, 5
PAIR_STORES = list(range(3025, 3033))


class Fail(Exception):
    pass


def need(cond, msg):
    if not cond:
        raise Fail(msg)


def wrap_list(items, indent="  "):
    """`[a, b, …]` broken into lines of at most WIDTH characters."""
    lines, cur = [], indent + "["
    for n, it in enumerate(items):
        piece = it + ("," if n + 1 < len(items) else "]")
        if len(cur) + 1 + len(piece) > WIDTH and cur.strip() != "[":
            lines.append(cur)
            cur = indent + " " + piece
        else:
            cur = cur + ("" if cur.endswith("[") else " ") + piece
    if not items:
        cur += "]"
    lines.append(cur)
    return "\n".join(lines)


def site_ordinals(code):
    """The ordinal of every event site among the sites of its kind: `(kind, ordinal)` by pc."""
    seen, out = {}, {}
    for ins in code:
        if not ins["event"]:
            continue
        op = ins["opcode"]
        kind = "load" if op.startswith("ld.") else "store" if op.startswith("st.") else None
        if kind is None:
            continue
        out[ins["pc"]] = (kind, seen.get(kind, 0))
        seen[kind] = seen.get(kind, 0) + 1
    return out


def build():
    code, ids, _ = analysis.load()
    table = json.loads(TABLE.read_text())
    sites = site_ordinals(code)

    def site(pc, kind):
        need(pc in sites and sites[pc][0] == kind, f"pc {pc} is no {kind} site")
        return sites[pc][1]

    # -- the carries, in the order of their loads ------------------------------------------
    carries = sorted(table["carries"].items(), key=lambda kv: kv[1]["load_pc"])
    need(len(carries) == 128, "128 carries expected")
    rows = []
    for j, (name, c) in enumerate(carries):
        lpc, spc = CARRY_LOAD0 + STEP * j, FINAL_STORE0 + STEP * j
        need(c["load_pc"] == lpc and c["store_pc"] == spc, f"{name}: load / store positions")
        ld, st = code[lpc], code[spc]
        need(ld["opcode"] == "ld.b32" and ld["writes"] == [name], f"{lpc}: not the load of {name}")
        need(st["opcode"] == "st.b32" and name in st["reads"], f"{spc}: not the store of {name}")
        m, bi, q, r = c["key_block"], c["value_block"], c["half"], c["c_register"]
        const = 32768 + 4 * (2048 * m + 1024 * (r // 2) + 128 * bi + 64 * q + 8 * (r % 2))
        need(const == 32768 + c["buffer_offset"], f"{name}: buffer offset")
        for pc0 in (lpc, spc):  # the constant of the pointer run before the instruction
            add = code[pc0 - 4]
            need(add["opcode"] == "add.s64" and add["operands"][2] == str(const),
                 f"{pc0}: the pointer of {name} is not base + {const}")  # fmt: skip
        need(ids[name] == c["id"], f"{name}: register id")
        rows.append({
            "j": j, "register": name, "id": c["id"], "key_block": m, "value_block": bi,
            "half": q, "c_register": r, "const": const,
            "load_pc": lpc, "load_site": site(lpc, "load"),
            "store_pc": spc, "store_site": site(spc, "store"),
        })  # fmt: skip
    need([r["load_site"] for r in rows] == list(range(31, 159)), "carry load sites 31..158")
    need([r["store_site"] for r in rows] == list(range(18, 146)), "final store sites 18..145")

    # -- the conversion pairs --------------------------------------------------------------
    conv = []
    for j, lpc in enumerate(CONV_LOADS):
        ld, cv = code[lpc], code[lpc + 1]
        need(ld["opcode"] == "ld.b32" and cv["opcode"] == "cvt.rn.bf16.f32", f"{lpc}: pair")
        need(cv["reads"] == ld["writes"], f"{lpc}: the conversion reads the load")
        spc = lpc + 4
        st = code[spc]
        need(st["opcode"] == "st.shared.b16" and cv["writes"][0] in st["reads"], f"{spc}: store")
        need(all(not code[p]["event"] for p in range(lpc + 1, spc)), f"{lpc}: events between")
        conv.append({
            "j": j, "load_pc": lpc, "load_site": site(lpc, "load"), "store_pc": spc,
            "store_site": site(spc, "store"), "loaded": ids[ld["writes"][0]],
            "narrowed": ids[cv["writes"][0]], "run": f"r{lpc + 1}",
        })  # fmt: skip
    need([c["load_site"] for c in conv] == list(range(21, 31)), "conversion load sites 21..30")
    need([c["store_site"] for c in conv] == list(range(10)), "conversion store sites 0..9")

    # -- the element stores of a partial tile ----------------------------------------------
    vec = code[3020]
    need(vec["opcode"] == "ld.shared.v4.b32", "3020: the vector load")
    unpacked = {}
    for pc in range(3021, 3025):
        ins = code[pc]
        need(ins["opcode"] == "mov.b32" and len(ins["writes"]) == 2, f"{pc}: unpack")
        el = vec["writes"].index(ins["reads"][0])
        unpacked[ins["writes"][0]] = (el, 0)
        unpacked[ins["writes"][1]] = (el, 1)
    elems = []
    for i, pc in enumerate(PAIR_STORES):
        st = code[pc]
        need(st["opcode"] == "st.global.b16", f"{pc}: element store")
        src = [r for r in st["reads"] if r in unpacked]
        need(len(src) == 1 and unpacked[src[0]] == (i // 2, i % 2), f"{pc}: element {i}")
        need(st["operands"][0] == f"[%rd1168+{2 * i - 8}]" or (i == 4 and st["operands"][0] == "[%rd1168]"),
             f"{pc}: address {st['operands'][0]}")  # fmt: skip
        elems.append({"i": i, "pc": pc, "site": site(pc, "store"), "source": ids[src[0]]})
    need([e["site"] for e in elems] == list(range(10, 18)), "element store sites 10..17")
    return {
        "source": "Kernels/FlashKdaFwd/Gen/values_ends.py",
        "carries": rows, "conversion": conv, "elements": elems,
        "vector_load": {"pc": 3020, "site": site(3020, "load"), "dsts": [ids[r] for r in vec["writes"]]},
    }  # fmt: skip


# ---------------------------------------------------------------------------------------------
# Lean output.


def tables_lean(data):
    rows = [
        f"({r['id']}, {r['key_block']}, {r['value_block']}, {r['half']}, {r['c_register']}, "
        f"{r['const']})"
        for r in data["carries"]
    ]
    conv = [f"({c['loaded']}, {c['narrowed']})" for c in data["conversion"]]
    elems = [str(e["source"]) for e in data["elements"]]
    return f"""{HEAD}
@[expose] public section

/-! # The registers of the regular sites at the ends of the tile loop

Generated from the register table `Gen/Tables/matrix_table.json` (key `carries`) and the decoded
program. -/

namespace {NS}.Gen

/-- **The carry registers, in the order of their loads** (instructions 765, 770, …, 1400: the
sites `load 31` to `load 158`) and of their stores (3132, 3137, …, 3767: the sites `store 18` to
`store 145`), which is the same. Each entry: the register id; the key block `m`, the value block
`bi`, the half `q` and the accumulator register `r` of the FP32 entry it carries (key feature
`16 m + cRow l r`, value channel `halfBase w bi q + cCol l r` for lane `l` of warp `w`); and
the constant its load and its store add to the lane's base pointer. -/
def carryTable : List (Nat × Nat × Nat × Nat × Nat × Nat) :=
{wrap_list(rows)}

/-- **The registers of the ten load / store pairs of the conversion loop** (the sites
`load 21` to `load 30` and `store 0` to `store 9`): the register the `ld.b32` writes and the
16-bit register `cvt.rn.bf16.f32` writes, which the `st.shared.b16` stores. -/
def convTable : List (Nat × Nat) :=
{wrap_list(conv)}

/-- **The source registers of the eight element stores of a partial tile** (the sites
`store 10` to `store 17`): store `i` writes half `i % 2` of element `i / 2` of the vector
load. -/
def elemTable : List Nat :=
{wrap_list(elems)}

end {NS}.Gen
"""


def steps_lean(data):
    out = [
        HEAD,
        f"""
public import Kernels.FlashKdaFwd.Proof.Values.Ends.Lib
public import Kernels.FlashKdaFwd.Proof.Thread.Sound
public import Tactics.KernelRfl

@[expose] public section

/-! # The machine's successor at the regular sites at the ends of the tile loop

Generated: one statement per site, each proved from the site's transition equation
(`Thread.next_<site>`) and transition function, and one dispatcher per family.

* `conv_<j>` (the ten loads of the conversion loop): a read of bytes that load as the binary32
  payload `r` is followed: the successor is at the `j`-th `st.shared.b16` and the register
  that the store writes holds the bfloat16 payload `r` (the run after the load is
  `cvt.rn.bf16.f32`, which keeps the real number of a payload).
* `convWr_<j>`, `finalWr_<j>`: the bytes of a write event at the `j`-th conversion store,
  resp. final store, are those of the stored form of the source register's slot.
* `carry_<j>` (the 128 carry loads): a followed successor of the `j`-th load is at the next
  site, the event was a read whose bytes load as a value `v`, the slot of the `j`-th carry
  holds `v`, and every other data slot is unchanged (slots below 2246: the pointer registers,
  which the run after the load rewrites, are above).
* `final_<j>` (the first 127 final stores): a followed successor is at the next store and the
  data slots are unchanged.
-/

namespace {NS}.Gen
open PTX PTX.Proof PTX.Flow PTX.Frame
open PTX.Kernels.FlashKdaFwd.Proof.Thread
open PTX.Kernels.FlashKdaFwd.Proof.Values

noncomputable section

variable {{L : Launch}} {{mem0 : Mem0}} {{X : Execution}} {{g : ℕ}}
""",
    ]
    # -- conversion -----------------------------------------------------------------------
    out.append("\n/-! ## The conversion loop -/\n")
    for c in data["conversion"]:
        j, ls, ss, reg = c["j"], c["load_site"], c["store_site"], c["narrowed"]
        out.append(f"""
theorem conv_{j} {{w : ℕ → BitVec 64}} {{p : ℕ → Bool}} {{x : ℕ → Value}} {{pc : ℕ}} {{a : Acc}}
    {{bs : List (Option Byte)}} {{r : ℝ}} (hbs : ldVal .same 32 bs = .ok (.float .f32 r)) :
    ∃ d', Thread.next L g ⟨.load {ls}, w, p, x⟩ ⟨pc, .rd a bs⟩ = some (some d') ∧
      d'.site = .store {ss} ∧ d'.x {reg} = .float .bf16 r := by
  have hn : Rules.narrowE [.float .f32 r] = .ok (.float .bf16 r) :=
    Rules.narrowE_fin valFloat_float
  refine ⟨after_load_{ls} L g ⟨.load {ls}, w, p, x⟩ (.float .f32 r), ?_, rfl, ?_⟩
  · rw [next_load_{ls}]
    simp only [hbs]
    exact across_pos ⟨⟨_, hn⟩, trivial⟩
  · show okVal (.bits 32 0) (Rules.narrowE [.float .f32 r]) = _
    exact okVal_of_ok hn

theorem convWr_{j} (F : Followed L mem0 X) {{k pc : ℕ}} {{a : Acc}} {{bs : List Byte}} {{d : D}}
    (he : X.get (g, k) = some ⟨pc, .wr a bs⟩) (hσ : stateAt (code L) X g k = some (some d))
    (hs : d.site = .store {ss}) : ∃ v', storeValue 16 (d.x {reg}) = .ok v' ∧ bs = v'.toBytes :=
  store_bytes_direct F he hσ (by rw [hs]; exact Flow.code_{c["store_pc"]}) rfl
    (fun _ => memTmpl_direct_weakStore rfl rfl rfl rfl rfl) (by rw [hs]; rfl)
    (by rw [hs]; kernel_rfl) rfl
""")
    out.append(
        """
/-- **A conversion load**, at any of the ten sites: a read of bytes that load as a binary32
payload is followed, the successor is at the site's store, and the register the store writes
holds the bfloat16 payload of the same number. -/
theorem conv_load (j : Fin 10) {d : D} (hs : d.site = .load ⟨21 + j.val, by omega⟩) {pc : ℕ}
    {a : Acc} {bs : List (Option Byte)} {r : ℝ} (hbs : ldVal .same 32 bs = .ok (.float .f32 r)) :
    ∃ d', Thread.next L g d ⟨pc, .rd a bs⟩ = some (some d') ∧
      d'.site = .store ⟨j.val, by omega⟩ ∧
      d'.x (convTable.getD j.val (0, 0)).2 = .float .bf16 r := by
  obtain ⟨s, w, p, x⟩ := d
  cases hs
  fin_cases j
"""
        + "".join(f"  · exact conv_{c['j']} hbs\n" for c in data["conversion"])
    )
    out.append(
        """
/-- **The bytes of a conversion store**: those of the stored form of the slot of the register
the site stores. -/
theorem conv_wr (F : Followed L mem0 X) (j : Fin 10) {k pc : ℕ} {a : Acc} {bs : List Byte}
    {d : D} (he : X.get (g, k) = some ⟨pc, .wr a bs⟩)
    (hσ : stateAt (code L) X g k = some (some d)) (hs : d.site = .store ⟨j.val, by omega⟩) :
    ∃ v', storeValue 16 (d.x (convTable.getD j.val (0, 0)).2) = .ok v' ∧ bs = v'.toBytes := by
  fin_cases j
"""
        + "".join(f"  · exact convWr_{c['j']} F he hσ hs\n" for c in data["conversion"])
    )
    # -- carry loads ----------------------------------------------------------------------
    out.append("\n/-! ## The carry loads -/\n")
    rows = data["carries"]
    for r in rows:
        j, ls, reg = r["j"], r["load_site"], r["id"]
        last = j == 127
        succ = ".fenceProxy 1" if last else f".load {ls + 1}"
        if last:
            body = f"""  rw [next_load_{ls}] at hn
  split at hn
  · rename_i a bs hk
    split at hn
    · rename_i v hv
      cases hn
      refine ⟨a, bs, v, hk, by rw [ldVal, hv]; rfl, rfl, fun r _ => valueEx_one _ _ _ _⟩
    · cases hn
  · cases hn"""
        else:
            body = f"""  rw [next_load_{ls}] at hn
  split at hn
  · rename_i a bs hk
    split at hn
    · rename_i v hv
      obtain ⟨-, rfl⟩ := across_eq_some hn
      exact ⟨a, bs, v, hk, hv, rfl, fun r hr => valueEx_two (by omega) _ _ _ _⟩
    · cases hn
  · cases hn"""
        out.append(f"""
theorem carry_{j} {{d d' : D}} {{e : Event}} (hs : d.site = .load {ls})
    (hn : Thread.next L g d e = some (some d')) :
    ∃ a bs v, e.kind = .rd a bs ∧ ldVal .same 32 bs = .ok v ∧ d'.site = {succ} ∧
      ∀ r < 2246, d'.x r = if r = {reg} then v else d.x r := by
  obtain ⟨s, w, p, x⟩ := d
  cases hs
{body}
""")
    out.append(
        """
/-- **A carry load**, at any of the 128 sites: a followed successor is at the next site, the
event was a read whose bytes load as a value, the carry's slot holds that value and the other
data slots are unchanged. -/
theorem carry_step {j : ℕ} (hj : j < 128) {d d' : D} {e : Event} (hs : d.site = carrySite j)
    (hn : Thread.next L g d e = some (some d')) :
    ∃ a bs v, e.kind = .rd a bs ∧ ldVal .same 32 bs = .ok v ∧ d'.site = carrySite (j + 1) ∧
      ∀ r < 2246, d'.x r = if r = carryReg j then v else d.x r := by
  interval_cases j
"""
        + "".join(f"  · exact carry_{r['j']} hs hn\n" for r in rows)
    )
    # -- final stores ---------------------------------------------------------------------
    out.append("\n/-! ## The final stores -/\n")
    for r in rows:
        j, ss, reg, spc = r["j"], r["store_site"], r["id"], r["store_pc"]
        if j < 127:
            out.append(f"""
theorem final_{j} {{d d' : D}} {{e : Event}} (hs : d.site = .store {ss})
    (hn : Thread.next L g d e = some (some d')) :
    d'.site = .store {ss + 1} ∧ ∀ r < 2246, d'.x r = d.x r := by
  obtain ⟨s, w, p, x⟩ := d
  cases hs
  rw [next_store_{ss}] at hn
  obtain ⟨-, rfl⟩ := across_eq_some hn
  exact ⟨rfl, fun r hr => valueEx_ne (by omega) _ _⟩
""")
        out.append(f"""
theorem finalWr_{j} (F : Followed L mem0 X) {{k pc : ℕ}} {{a : Acc}} {{bs : List Byte}} {{d : D}}
    (he : X.get (g, k) = some ⟨pc, .wr a bs⟩) (hσ : stateAt (code L) X g k = some (some d))
    (hs : d.site = .store {ss}) : ∃ v', storeValue 32 (d.x {reg}) = .ok v' ∧ bs = v'.toBytes :=
  store_bytes_generic F he hσ (by rw [hs]; exact Flow.code_{spc}) rfl (fun _ => rfl) rfl rfl rfl
    (by rw [hs]; rfl) (by rw [hs]; kernel_rfl) rfl
""")
    out.append(
        """
/-- **A final store**, at any of the first 127 sites: a followed successor is at the next
store, with the data slots unchanged. -/
theorem final_step {j : ℕ} (hj : j < 127) {d d' : D} {e : Event}
    (hs : d.site = finalSite ⟨j, by omega⟩) (hn : Thread.next L g d e = some (some d')) :
    d'.site = finalSite ⟨j + 1, by omega⟩ ∧ ∀ r < 2246, d'.x r = d.x r := by
  interval_cases j
"""
        + "".join(f"  · exact final_{r['j']} hs hn\n" for r in rows[:127])
    )
    out.append(
        """
/-- **The bytes of a final store**: those of the stored form of the slot of the site's
carry. -/
theorem final_wr (F : Followed L mem0 X) {j : ℕ} (hj : j < 128) {k pc : ℕ} {a : Acc}
    {bs : List Byte} {d : D} (he : X.get (g, k) = some ⟨pc, .wr a bs⟩)
    (hσ : stateAt (code L) X g k = some (some d)) (hs : d.site = finalSite ⟨j, hj⟩) :
    ∃ v', storeValue 32 (d.x (carryReg j)) = .ok v' ∧ bs = v'.toBytes := by
  interval_cases j
"""
        + "".join(f"  · exact finalWr_{r['j']} F he hσ hs\n" for r in rows)
    )
    out.append(f"""
end

end {NS}.Gen
""")
    return "".join(out)


def render(data):
    return {
        JSON_OUT: json.dumps(data, indent=1) + "\n",
        OUT / "Tables.lean": tables_lean(data),
        OUT / "Steps.lean": steps_lean(data),
    }


def main():
    cli = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    cli.add_argument("--check", action="store_true", help="write nothing; fail if one is stale")
    args = cli.parse_args()
    try:
        files = render(build())
    except Fail as f:
        print(f"values_ends.py: {f}")
        return 1
    outputs.write_or_check(files, args.check)
    return 0


if __name__ == "__main__":
    sys.exit(main())
