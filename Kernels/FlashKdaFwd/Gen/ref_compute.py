"""Tables and generated Lean files of the Compute phase of the reference layer.

The Compute phase (instructions 2106 to 2944) is the tile loop of the 128 compute threads of a
thread block. One iteration (one tile) is a straight line of 268 events: two polls, 182 warp
matrix instructions (an `ldmatrix` or an `stmatrix` is two events: a row read and a matrix event,
or a matrix event and a row write), 18 scalar loads, the named barrier, a proxy fence and two
arrivals. The reference invariant of the phase (`Proof/Ref/Compute/Inv.lean`) names a state of
the loop by the tile `t` and the position `n < 268` in the tile; what differs between the
positions is tabulated here.

This script reads the generated thread machine (`Proof/Thread/After/Part*.lean`, written by
`thread.py`: the transition function of every site), the frozen PTX (through `analysis.load`)
and the register table of the value layer (`Gen/Tables/matrix_table.json`, written by
`matrix_table.py`: the address form of every memory access). It

* builds the list of the 268 positions of a tile (site, instruction index, the transition
  function that leaves the position) and the list of the control registers that the tile's code
  assigns, in program order, each with its closed form over the launch, the thread index and
  the tile (`REGS`; the closed forms are written by hand, see `closed_forms`);
* writes the tables to `Gen/Tables/ref_compute.json` and the generated Lean files of
  `Proof/Ref/Compute/` (`Tables.lean`, `Steps.lean`, `Trace.lean`, `Access.lean`);
* with `--check` writes nothing. It fails if one of these five files is stale. Then it runs
  the control-flow simulator (`simulate.py`) for several launches and thread indices and
  compares, at every visit of every position, each register assigned so far with its closed
  form, and every event operand (polled mbarrier and parity, barrier id and count, the address
  of every memory access) with the form the invariant states; the addresses are also compared
  with the forms of `matrix_table.json`. This takes about a minute;
* with `--show` also prints the positions and the registers.

Nothing here is trusted: Lean checks the generated files against the generated thread machine.

    python3 Kernels/FlashKdaFwd/Gen/ref_compute.py            # write the tables and the Lean files
    python3 Kernels/FlashKdaFwd/Gen/ref_compute.py --check    # write nothing; fail if a file is
                                                              # stale or the simulator disagrees

Words. *Position*: the index `n` (0 to 267) of an event of one tile. *Register id*: the number
of a register in the thread machine (`%rN` is `306 + N`). *Count* of a position: how many of
the registers of `REGS` have been assigned when the thread is at the position. `S` is the base
address of the block's shared memory, `t` the tile, `tid` the thread's index in its block,
`gate` the position of the tile's first gate logit in the 32-element buffer (`Forms.lean`).
"""

