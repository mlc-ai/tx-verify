def lean_access(pos, addr, forms):
    reg = regions(pos, addr, forms)
    lists = {"acc": [], "in": [], "out": []}
    for n in sorted(addr):
        r, c, _ = addr[n]
        if pos[n][0] != "load" and r not in lists[reg[n]]:
            lists[reg[n]].append(r)
    what = {"acc": "`state_acc`", "in": "the input stage", "out": "the output stage"}
    lem = {"acc": "acc_addr", "in": "in_addr", "out": "out_addr"}
    out = []
    for n in sorted(addr):
        kind, j, pc = pos[n]
        r, c, sz = addr[n]
        if kind == "matrixLoad":
            out.append(ROW_RD.format(n=n, j=j, pc=pc, r=r, what=what[reg[n]], lem=lem[reg[n]]))
        elif kind == "matrixStoreWr":
            out.append(ROW_WR.format(n=n, j=j, pc=pc, r=r, what=what[reg[n]], lem=lem[reg[n]]))
        else:
            if r == 1948:
                side = f"gate_addr hpre h.compute (t := t) (c := {c}) (by decide)"
                w = "a gate logit"
            else:
                side = (
                    f"decay_addr hpre h.compute (t := t) (c := {c}) (by decide)\n"
                    "    (by decide) (by decide)"
                )
                w = "a decay factor"
            close = CLOSE16.format(c=c) if sz == 2 else CLOSE32
            out.append(
                SCALAR.format(n=n, j=j, pc=pc, r=r, c=c, sz=sz, lem=side, what=w, close=close)
            )
    head = (
        ACCESS_HEAD.replace("ACCREGS", wrap([str(r) for r in lists["acc"]], 3).strip())
        .replace("INREGS", wrap([str(r) for r in lists["in"]], 3).strip())
        .replace("OUTREGS", ", ".join(map(str, lists["out"])))
    )
    return (
        HEADER
        + head
        + "\n"
        + "\n".join(out)
        + "\nend\n\nend PTX.Kernels.FlashKdaFwd.Proof.Ref.Compute\n"
    )


def main():
    cli = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    cli.add_argument(
        "--check",
        action="store_true",
        help="write nothing; fail if a file is stale or the simulator disagrees",
    )
    cli.add_argument("--show", action="store_true", help="print the positions and registers")
    args = cli.parse_args()
    code, _, _ = analysis.load()
    pos = positions(code)
    trans = transitions()
    regs = closed_forms(trans, pos)
    cnt = counts(regs)
    mat = matrix_before(pos)
    addr = address_registers(code, pos)
    forms = table_forms(pos)
    assert set(addr) == set(forms)
    assert len({r[0] for r in regs}) == len(regs)
    if args.show:
        for n, (kind, j, pc) in enumerate(pos):
            new = [r[0] for r in regs if r[3] == n]
            print(n, kind, j, pc, cnt[n], mat[n], addr.get(n, ""), new or "")
    table = json.dumps({
        "positions": [{"n": n, "site": k, "ordinal": j, "pc": pc, "count": cnt[n],
                       "matrix_before": mat[n],
                       "address": list(addr[n]) if n in addr else None}
                      for n, (k, j, pc) in enumerate(pos)],
        "registers": [{"id": r[0], "closed_form": r[1], "from_position": r[3]}
                      for r in regs],
    }, indent=1) + "\n"  # fmt: skip
    files = {
        TABLE: table,
        OUT / "Tables.lean": lean_tables(pos, regs, cnt, mat, addr),
        OUT / "Steps.lean": lean_steps(pos, trans),
        OUT / "Trace.lean": lean_trace(pos, trans),
        OUT / "Access.lean": lean_access(pos, addr, forms),
    }
    outputs.write_or_check(files, args.check)
    if args.check:
        check(code, pos, regs, cnt, addr, forms)


if __name__ == "__main__":
    main()
