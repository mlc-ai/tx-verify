def site_term(kind, j):
    return f".{kind} {j} row" if kind in ("matrixLoadMx", "matrixStoreWr") else f".{kind} {j}"


def good_lemma(n, kind, j, trans):
    """The step of position `n` of a tile (2 to 263), from the form of the successor."""
    site = site_term(kind, j)
    row = "{row : List (Option Byte)} " if "row" in site else ""
    fn = leaving(kind, j)
    hpre = ""
    tl = ""
    if fn is not None:
        needs = bool(trans[fn]["stored"]) and fn not in (
            "after_matrixLoadMx_3",
            "after_matrixStoreWr_17",
        )
        hpre = "(hpre : Pre P L mem0) " if needs else ""
        tl = f"(tl_{kind}_{j} hpre h)" if needs else f"(tl_{kind}_{j} h)"
    head = (
        f"theorem good_{n} {hpre}{row}(h : Tile P L g t {n} w p x)\n    "
        + HYP.format(site=site, n=n)
        + f"  rw [next_{kind}_{j}] at hn\n"
    )
    same = "(h.same (by decide) (by decide) rfl)"
    if kind == "matrixLoad":
        body = (
            "  obtain ⟨a, bs, hk, hf⟩ := rdNext_some hn\n  obtain rfl := ldRow_some hf\n"
            f"  exact next_body ⟨_, rfl⟩ {same}\n    {LED} (ledEv_rd hk)\n"
        )
    elif kind == "matrixStore":
        body = (
            "  obtain ⟨op, own, recv, hk, hf⟩ := stNext_some hn\n"
            "  obtain rfl := stRecv_some hf\n"
            f"  exact next_body ⟨_, rfl⟩ {same}\n    {LED} (ledEv_matrix hk)\n"
        )
    elif kind in ("matrixLoadMx", "warpMma", "matrixMove"):
        k = 1 if kind == "matrixMove" else 4
        body = (
            f"  obtain ⟨op, own, recv, vs, hk, hf⟩ := mxNext_some (n := {k}) hn\n"
            + CLOSE
            + f"  exact next_body rfl {tl} {LED} (ledEv_matrix hk)\n"
        )
    elif kind == "matrixStoreWr":
        body = (
            "  obtain ⟨a, bs, hk, hf⟩ := wrNext_some hn\n"
            + CLOSE
            + f"  exact next_body rfl {tl} {LED} (ledEv_wr hk)\n"
        )
    else:
        assert kind == "load"
        body = (
            "  obtain ⟨a, bs, hk, hf⟩ := rdNext_some hn\n  split at hf\n  · "
            + CLOSE.strip()
            + f"\n    exact next_body rfl {tl} {LED} (ledEv_rd hk)\n"
            "  · cases hf\n"
        )
    return head + body


def leaf(n, kind, j, trans, ind):
    """The case `n` of the case analysis."""
    pad = " " * ind
    site = site_term(kind, j)
    fn = leaving(kind, j)
    if "row" in site:
        at = f"{pad}obtain ⟨row, rfl⟩ : ∃ row, site = {site} := h.site\n"
    else:
        at = f"{pad}obtain rfl : site = {site} := h.site\n"
    if n in (0, 1, 264):
        call = f"good_{n} hpre h.facts hat hc hf hn"
    elif n == 265:
        call = "good_265 hpre h.facts hc hf hn"
    elif n in (266, 267):
        call = f"good_{n} hpre hg h.facts hat hc hf hn"
    else:
        needs = (
            fn is not None
            and bool(trans[fn]["stored"])
            and fn not in ("after_matrixLoadMx_3", "after_matrixStoreWr_17")
        )
        call = f"good_{n} hpre h.facts hn" if needs else f"good_{n} h.facts hn"
    return f"{pad}obtain rfl : n = {n} := by omega\n{at}{pad}exact {call}\n"


def search(lo, hi, pos, trans, ind):
    """A binary search for the position `n` with `lo ≤ n < hi`."""
    if hi - lo == 1:
        kind, j, _ = pos[lo]
        return leaf(lo, kind, j, trans, ind)
    mid = (lo + hi) // 2
    pad = " " * ind
    return (
        f"{pad}rcases Nat.lt_or_ge n {mid} with hm | hm\n"
        f"{pad}·\n"
        + search(lo, mid, pos, trans, ind + 2)
        + f"{pad}·\n"
        + search(mid, hi, pos, trans, ind + 2)
    )


