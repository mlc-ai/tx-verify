POLL_E, POLL_F, BAR, FENCE, ARR_F, ARR_E = 2144, 2186, 2913, 2914, 2920, 2928
SITE_OF_OP = {"ldmatrix": "matrixLoad", "stmatrix": "matrixStore", "mma": "warpMma",
              "movmatrix": "matrixMove", "ld": "load"}  # fmt: skip


def rid(name):
    """The register id of `%rN` in the thread machine."""
    m = re.fullmatch(r"%r(\d+)", name)
    return 306 + int(m.group(1))


# -- the positions of a tile ----------------------------------------------------------------


def site_ordinals(code):
    """The ordinal of every event site among the sites of its kind, by instruction index."""
    seen, out = {}, {}
    for ins in code:
        if not ins["event"]:
            continue
        op = ins["opcode"]
        base = op.split(".")[0]
        if op.startswith("mbarrier.try_wait"):
            kind = "mbarWait"
        elif op.startswith("mbarrier.arrive"):
            kind = "mbarArrive"
        elif base == "bar":
            kind = "bar"
        elif op.startswith("fence.proxy"):
            kind = "fenceProxy"
        elif base in ("ld", "ldu") and "matrix" not in base:
            kind = "load"
        elif base in SITE_OF_OP:
            kind = SITE_OF_OP[base]
        else:
            kind = base
        out[ins["pc"]] = (kind, seen.get(kind, 0))
        seen[kind] = seen.get(kind, 0) + 1
    return out


def positions(code):
    """The 268 positions of a tile: `(kind, ordinal, pc)` with the kinds of `Thread.Site`
    (`matrixLoadMx` and `matrixStoreWr` are the second events)."""
    ords = site_ordinals(code)
    pos = [("mbarWait", 7, POLL_E), ("mbarWait", 8, POLL_F)]
    for pc in range(POLL_F + 1, BAR):
        if pc not in ords:
            continue
        kind, j = ords[pc]
        if kind == "matrixLoad":
            pos += [("matrixLoad", j, pc), ("matrixLoadMx", j, pc)]
        elif kind == "matrixStore":
            pos += [("matrixStore", j, pc), ("matrixStoreWr", j, pc)]
        else:
            pos.append((kind, j, pc))
    pos += [("bar", 6, BAR), ("fenceProxy", 2, FENCE), ("mbarArrive", 4, ARR_F),
            ("mbarArrive", 5, ARR_E)]  # fmt: skip
    assert len(pos) == 268, len(pos)
    assert ords[POLL_E] == ("mbarWait", 7) and ords[POLL_F] == ("mbarWait", 8)
    assert ords[BAR] == ("bar", 6) and ords[FENCE] == ("fenceProxy", 2)
    assert ords[ARR_F] == ("mbarArrive", 4) and ords[ARR_E] == ("mbarArrive", 5)
    return pos


IS_MATRIX = ("matrixLoadMx", "warpMma", "matrixMove", "matrixStore")


def matrix_before(pos):
    """The matrix events of the tile made before each position."""
    out, m = [], 0
    for kind, _, _ in pos:
        out.append(m)
        m += kind in IS_MATRIX
    assert m == 182
    return out


# -- the transition functions of the thread machine -------------------------------------------


def transitions():
    """`after_<site>`: parameters, the `let`s of control registers and the registers stored."""
    src = "".join(f.read_text() for f in sorted(AFTER.glob("Part*.lean")))
    out = {}
    pat = (r"^def (after_\w+) \(L : Launch\) \(g : Nat\) \(d : D\)(.*?) ?: "
           r"(D|Option \(Option D\)) :=\n(.*?)(?=\n/--|\nend\b)")  # fmt: skip
    for m in re.finditer(pat, src, re.S | re.M):
        body = m.group(4)
        lets = re.findall(r"let (r\d+|p\d+) : (?:BitVec 64|Bool) := (.*)", body)
        sw = re.search(r"setW \[(.*?)\] d\.w", body, re.S)
        stored = [int(x) for x in re.findall(r"\(\s*(\d+),", sw.group(1))] if sw else []
        sites = re.findall(r"⟨\.(\w+) (\d+),", body)
        params = re.findall(r"\((\w+) : ([^)]*)\)", m.group(2))
        out[m.group(1)] = {"params": params, "lets": lets, "stored": stored,
                           "sites": [(k, int(j)) for k, j in sites],
                           "run": "Run." in body, "setP": "setP" in body}  # fmt: skip
    return out


def leaving(kind, j):
    """The transition function that leaves a position (none for a first event)."""
    if kind in ("matrixLoad", "matrixStore"):
        return None
    return f"after_{kind}_{j}"


# -- the registers of a tile and their closed forms -------------------------------------------

# Launch numbers of the simulator.
S0 = simulate.SHARED


class Env:
    """The numbers a closed form is evaluated on."""

    def __init__(self, tid, t, tiles, gate):
        self.tid, self.t, self.T, self.gate = tid, t, tiles, gate
        self.S = S0
        self.lane, self.warp = tid % 32, tid // 32
        self.acc = 512 * self.warp + 16 * (tid % 8) + 128 * (tid // 16 % 2) + 2048 * (tid // 8 % 2)
        self.pair = 8 * (tid % 8) + 64 * (tid // 16 % 2) + 1024 * (tid // 8 % 2)
        self.kr = 16 * (tid % 8) + 256 * (tid // 8 % 2) + 128 * (tid // 16 % 2)
        self.gt = 4 * (tid // 4 % 8)
        self.g2 = 2 * (gate + tid // 4 % 8)


IN = "P.sharedBase + 18048 * (t % 3)"  # the input stage of the tile, minus 32768
ROW = IN + " + laneOff g"  # ... plus the row of the lane
ACC = "P.sharedBase + accOff g"  # the lane's first row of the bf16 state copy
KR = IN + " + krOff g"


def closed_forms(trans, pos):
    """`REGS`: `(id, lean term, python function of Env, position from which it holds)`, in the
    order of assignment. The first seven are carried around the loop."""
    regs = [
        (2106, "4294967296 - (tilesOf P g - t)", lambda e: (1 << 32) - (e.T - e.t)),
        (2107, "t / 3 % 2", lambda e: e.t // 3 % 2),
        (2108, "t % 3", lambda e: e.t % 3),
        (2109, "(t / 2 + 1) % 2", lambda e: (e.t // 2 + 1) % 2),
        (2110, "t % 2", lambda e: e.t % 2),
        (1947, "gateOff P g", lambda e: e.g2),
        (486, "if lane g = 0 then 1 else 0", lambda e: int(e.lane == 0)),
        (1151, "P.sharedBase + 8 * (t % 2) + 98368", lambda e: e.S + 8 * (e.t % 2) + 98368),
        (1152, "10000000", lambda e: 10000000),
    ]
    regs = [r + (0,) for r in regs]
    hand = {
        1923: ("tid g", lambda e: e.tid),
        1924: ("tid g / 32", lambda e: e.warp),
        1932: ("tid g / 8 % 2", lambda e: e.tid // 8 % 2),
        1935: ("pairOff g", lambda e: e.pair),
        1938: ("P.sharedBase", lambda e: e.S),
        1160: (ACC, lambda e: e.S + e.acc),
        1939: ("8 * (t % 3)", lambda e: 8 * (e.t % 3)),
        1940: ("P.sharedBase + 8 * (t % 3)", lambda e: e.S + 8 * (e.t % 3)),
        1156: ("P.sharedBase + 8 * (t % 3) + 98304", lambda e: e.S + 8 * (e.t % 3) + 98304),
        1157: ("10000000", lambda e: 10000000),
        1941: (IN, lambda e: e.S + 18048 * (e.t % 3)),
        1943: ("laneOff g", lambda e: 16 * e.lane),
        1944: (ROW, lambda e: e.S + 18048 * (e.t % 3) + 16 * e.lane),
        1168: ("0", lambda e: 0),
        1945: ("warpOff g", lambda e: 1024 * e.warp),
        1946: (ROW + " + warpOff g",
               lambda e: e.S + 18048 * (e.t % 3) + 16 * e.lane + 1024 * e.warp),
        1948: (IN + " + gateOff P g", lambda e: e.S + 18048 * (e.t % 3) + e.g2),
        2005: ("8 * (t % 2)", lambda e: 8 * (e.t % 2)),
        2009: ("P.sharedBase + 4096 * (t % 2) + (warpOff g + laneOff g)",
               lambda e: e.S + 4096 * (e.t % 2) + 1024 * e.warp + 16 * e.lane),
        2012: (KR, lambda e: e.S + 18048 * (e.t % 3) + e.kr),
        2014: (IN + " + gtOff g", lambda e: e.S + 18048 * (e.t % 3) + e.gt),
        1921: ("8", lambda e: 8),
        1922: ("128", lambda e: 128),
        2031: ("P.sharedBase + 8 * (t % 2) + 98352", lambda e: e.S + 8 * (e.t % 2) + 98352),
        2034: ("P.sharedBase + 8 * (t % 3) + 98328", lambda e: e.S + 8 * (e.t % 3) + 98328),
        2035: ("0", lambda e: 0),
    }  # fmt: skip
    known = {r[0]: r for r in regs}

    def add(n, fn):
        """The registers stored by the transition `fn`, which leads to position `n`."""
        tr = trans[fn]
        lets = dict(tr["lets"])
        for r in tr["stored"]:
            if r in hand:
                entry = (r, hand[r][0], hand[r][1], n)
            else:
                m = re.fullmatch(r"\(addi (?:\(d\.w (\d+)\)|r(\d+)) (\d+)\)", lets[f"r{r}"])
                assert m, (fn, r, lets[f"r{r}"])
                base, c = int(m.group(1) or m.group(2)), int(m.group(3))
                _, lean, py, _ = known[base]
                entry = (r, f"{lean} + {c}", (lambda e, py=py, c=c: py(e) + c), n)
            assert r not in known, (fn, r)
            known[r] = entry
            regs.append(entry)

    for n, (kind, j, _) in enumerate(pos[:-1]):
        fn = leaving(kind, j)
        if fn is not None:
            add(n + 1, fn)
    return regs


def counts(regs):
    """The count of each position: the registers of `REGS` assigned up to it."""
    return [sum(1 for r in regs if r[3] <= n) for n in range(268)]


# -- the events of a tile -------------------------------------------------------------------


def address_registers(code, pos):
    """For each position with a memory access: the register of the address, the constant added
    to it, and the size of the access."""
    out = {}
    for n, (kind, j, pc) in enumerate(pos):
        ins = code[pc]
        if kind in ("matrixLoad", "matrixStoreWr"):
            which = ins["operands"][1 if kind == "matrixLoad" else 0]
            m = re.fullmatch(r"\[(%r\d+)\]", which)
            out[n] = (rid(m.group(1)), 0, 16)
        elif kind == "load":
            m = re.fullmatch(r"\[(%r\d+)\+(\d+)\]", ins["operands"][1])
            size = {"ld.shared.b16": 2, "ld.shared.b32": 4}[ins["opcode"]]
            out[n] = (rid(m.group(1)), int(m.group(2)), size)
    return out


def table_forms(pos):
    """The address form of `matrix_table.json` for each position with a memory access:
    `(constant, stage weight, output stage weight, gate weight, bit weights)`."""
    data = json.loads(MATRIX.read_text())
    by_pc = {m["pc"]: m["address"] for m in data["matrix"] if "address" in m}
    by_pc.update({s["pc"]: s["address"] for s in data["scalar"] if s["opcode"].startswith("ld.")})
    out = {}
    for n, (kind, _, pc) in enumerate(pos):
        if kind in ("matrixLoad", "matrixStoreWr", "load"):
            a = by_pc[pc]
            out[n] = (a["const"], a["stage"], a["out_stage"], a["gate_offset"], a["tid_bits"])
    return out


def form_value(form, env):
    c, st, ost, gw, bits = form
    return (env.S + c + st * (env.t % 3) + ost * (env.t % 2) + gw * env.gate
            + sum(w * (env.tid >> i & 1) for i, w in enumerate(bits)))  # fmt: skip


# -- the check against the simulator -------------------------------------------------------


class Watch(simulate.Thread):
    """A simulated thread that records the integer registers before every event."""

    def run_all(self, limit=5_000_000):
        pc, steps, out = 0, 0, []
        while True:
            steps += 1
            assert steps <= limit
            ins = self.code[pc]
            op = ins["opcode"]
            names = {n.split("#")[-1]: n for n in ins["reads"] + ins["writes"]}
            take = True
            if ins["guard"] is not None:
                take = bool(self.env[ins["guard"]["register"]]) != ins["guard"]["negated"]
            if op.split(".")[0] == "bra":
                pc = ins["target"] if take else pc + 1
                continue
            if not take:
                pc += 1
                continue
            if op == "ret":
                return out
            assert op not in ("brkpt", "trap"), pc
            if ins["event"]:
                snap = {k: v for k, v in self.env.items() if v is not None}
                out.append((pc, snap, self.event(pc, ins, names)))
            else:
                self.local(ins, names)
            pc += 1


def check(code, pos, regs, cnt, addr, forms):
    launches = [([0], 1), ([1], 1), ([16], 1), ([17], 2), ([37, 5], 2), ([5, 64, 3], 3),
                ([112], 1), ([3, 100], 2)]  # fmt: skip
    tids = [0, 1, 2, 3, 4, 5, 7, 8, 13, 16, 24, 31, 32, 33, 47, 63, 64, 77, 96, 100, 127]
    pc_first = {}
    for n, (_, _, pc) in enumerate(pos):
        pc_first.setdefault(pc, n)
    visits = 0
    for lengths, heads in launches:
        total = sum(lengths)
        for seq in range(len(lengths)):
            for head in range(heads):
                for fail in (0, 2):
                    for tid in tids:
                        th = Watch(code, tid, seq, head, lengths, heads, fail_polls=fail)
                        trace = [x for x in th.run_all() if POLL_E <= x[0] <= ARR_E]
                        T = simulate.tiles(lengths[seq])
                        gate = (total * head + sum(lengths[:seq])) % 8
                        # successful events only: a failed poll repeats its position
                        t, n = 0, 0
                        polls = {POLL_E: 0, POLL_F: 0}
                        for pc, snap, ev in trace:
                            env = Env(tid, t, T, gate)
                            kind, j, ppc = pos[n]
                            assert ppc == pc, (lengths, tid, t, n, pc, ppc)
                            for r, lean, py, _ in regs[: cnt[n]]:
                                assert snap.get(f"%r{r - 306}") == py(env), (
                                    lengths,
                                    tid,
                                    t,
                                    n,
                                    r,
                                    lean,
                                    snap.get(f"%r{r - 306}"),
                                    py(env),
                                )
                            if n in addr:
                                r, c, _ = addr[n]
                                assert ev["addr"] == form_value(forms[n], env), (tid, t, n)
                                assert ev["addr"] == snap[f"%r{r - 306}"] + c
                            if pc == POLL_E:
                                assert ev["mbar"] == S0 + 98368 + 8 * (t % 2)
                                assert ev["parity"] == (t // 2 + 1) % 2
                            if pc == POLL_F:
                                assert ev["mbar"] == S0 + 98304 + 8 * (t % 3)
                                assert ev["parity"] == t // 3 % 2
                            if pc == BAR:
                                assert (ev["id"], ev["count"]) == (8, 128)
                            if pc == ARR_F:
                                assert ev["mbar"] == S0 + 98352 + 8 * (t % 2)
                            if pc == ARR_E:
                                assert snap["%r1728"] == S0 + 98328 + 8 * (t % 3)
                            visits += 1
                            if pc in polls and not ev["ok"]:
                                continue
                            # the simulator makes one event of an `ldmatrix` / `stmatrix`
                            n += 2 if kind in ("matrixLoad", "matrixStore") else 1
                            if n == 268:
                                t, n = t + 1, 0
                        assert (t, n) == (T, 0), (lengths, tid, t, n, T)
    print(f"check: {visits} visits of positions agree with the closed forms")


# -- output ------------------------------------------------------------------------------------


def wrap(items, indent, width=100):
    """A comma-separated list, wrapped."""
    lines, cur = [], " " * indent
    for k, it in enumerate(items):
        piece = it + ("," if k + 1 < len(items) else "")
        if len(cur) + len(piece) + 1 > width and cur.strip():
            lines.append(cur.rstrip())
            cur = " " * indent
        cur += piece + " "
    lines.append(cur.rstrip())
    return "\n".join(lines)


