"""Write the phase map of the kernel: every event site by phase, with the roles that reach it,
its successors in the site graph and the loops.

A reading aid for the reference layer (`Proof/Ref/<Phase>`), not a proof input. It is computed
from the frozen flow (`Flow/flow.json`) and from the role analysis of `analysis.py` (which folds
the thread index of a role, so a branch that a role never takes is not followed). The map is
written to the file given on the command line; no file of the repository is made from it, so
there is nothing to check.

    python3 Kernels/FlashKdaFwd/Gen/phase_map.py <output.md>
"""

import collections
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import analysis  # noqa: E402

# First instruction of each phase (instruction indices of the patched program, from zero).
PHASES = [
    ("Startup", 0, "roles, launch scalars, the scan of the packed offsets, mbarrier setup"),
    ("StateLoad", 301, "the load warp's tensor loads of the FP32 state, the state mbarrier"),
    ("Conversion", 388, "FP32 state to the bfloat16 copy `state_acc` (compute warps)"),
    ("CarryLoad", 622, "each compute lane loads its FP32 carry registers; proxy fence 1401"),
    ("Producer", 1403, "the load warp's tile loop: 70 tensor loads per tile"),
    ("Compute", 2106, "the compute warps' tile loop: 182 matrix instructions per tile"),
    ("Store", 2945, "the store warp's tile loop: tensor stores, partial-tile stores"),
    ("Epilogue", 3113, "final state: stores to the buffer, tensor stores, exit"),
]
END = 3836


def phase_of(pc):
    name = PHASES[0][0]
    for phase, first, _ in PHASES:
        if pc >= first:
            name = phase
    return name


def entries(flow, by_name):
    """The entry sites of each phase by role: the sites a role reaches from a site of another
    phase, with the control registers live there, grouped by the phase that defines them."""
    code, ids, _, result = analysis.analyze()
    defs = collections.defaultdict(set)
    for pc, ins in enumerate(code):
        for w in ins["writes"]:
            defs[w].add(phase_of(pc))
    by_pc = {s["pc"]: s for s in flow["sites"]}
    text = [
        "## Entries of the phases, by role",
        "",
        "An entry is a site that a role reaches directly from a site of another phase (or the",
        "role's first site). Listed: the control registers that are live at the entry (the",
        "register file the phase starts from), grouped by the phase whose code writes them; a",
        "register written in several phases is listed under each. `data` is the number of live",
        "data registers (opaque values). The registers written in an EARLIER phase are what that",
        "phase's exit must describe in closed form.",
        "",
    ]
    for role, data in result["roles"].items():
        sites = {row["pc"]: row for row in data["sites"]}
        preds = collections.defaultdict(set)
        for s in flow["sites"]:
            if s["pc"] not in sites:
                continue
            for path in s["next"]:
                if path["to"] and by_name[path["to"]]["pc"] in sites:
                    preds[by_name[path["to"]]["pc"]].add(s["pc"])
        text += [f"### Role {role} ({len(sites)} sites reached)", ""]
        for pc in sorted(sites):
            phase = phase_of(pc)
            cross = sorted(p for p in preds[pc] if phase_of(p) != phase)
            if not cross and pc != min(sites):
                continue
            row = sites[pc]
            groups = collections.defaultdict(list)
            for r in row["live_control"]:
                for ph in sorted(defs.get(r, {"special"})):
                    groups[ph].append(r)
            origin = ", ".join(by_pc[p]["name"] for p in cross) or "the thread's start"
            text.append(
                f"* **{phase}** entry `{by_pc[pc]['name']}` (pc {pc}), from {origin}; "
                f"data {len(row['live_data'])}:"
            )
            for ph, _, _ in PHASES:
                if ph in groups:
                    text.append(f"  * written in {ph}: " + " ".join(f"`{r}`" for r in groups[ph]))
        text.append("")
    return text


def main():
    out = Path(sys.argv[1])
    flow = json.loads((analysis.KERNEL / "Flow" / "flow.json").read_text())
    sites = flow["sites"]
    by_name = {s["name"]: s for s in sites}
    code, _, _ = analysis.load()
    reach = {role: set(analysis.reachable(code, role)) for role in analysis.ROLES}
    letters = {"compute": "C", "load": "L", "store": "S"}

    def roles(pc):
        return "".join(letters[r] for r in analysis.ROLES if pc in reach[r]) or "-"

    lines = [
        "# Phase map of the FlashKDA forward kernel (generated by `Gen/phase_map.py`)",
        "",
        "Instruction indices are those of the patched program (`packed_fp32_sm100a.ptx`, from",
        "zero). Roles: C = a compute thread (index 0 to 127 in its block), L = a thread of the",
        "load warp (128 to 159), S = a thread of the store warp (160 to 191); a role is listed",
        "at a site when the role analysis reaches the site's instruction (`-`: no role does).",
        "`->` lists the successors in the site graph as `site(+n)`: `n` local instructions",
        "between the two events; `^` marks a back edge (the successor is not later in the",
        "code); `?` marks a path with a branch condition; `END` is a path that leaves the",
        "code without another event.",
        "",
    ]
    summary = [
        "| phase | first | last | sites | by kind | back edges |",
        "|---|---|---|---|---|---|",
    ]
    body = []
    for index, (phase, first, about) in enumerate(PHASES):
        last = (PHASES[index + 1][1] if index + 1 < len(PHASES) else END) - 1
        mine = [s for s in sites if first <= s["pc"] <= last]
        kinds = collections.Counter(s["name"].rsplit("_", 1)[0] for s in mine)
        back = []
        body += [f"## {phase} ({first} to {last}): {about}", ""]
        body.append("| site | pc | roles | instruction | successors |")
        body.append("|---|---|---|---|---|")
        for s in mine:
            succ = []
            for path in s["next"]:
                to = path["to"]
                if to is None:
                    succ.append("END")
                    continue
                target = by_name.get(to)
                mark = ""
                if target is not None and target["pc"] <= s["pc"]:
                    mark += "^"
                    back.append(f"{s['name']} → {to}")
                if path["conditions"]:
                    mark += "?"
                where = ""
                if target is not None and phase_of(target["pc"]) != phase:
                    where = f" [{phase_of(target['pc'])}]"
                succ.append(f"{to}(+{path['length']}){mark}{where}")
            text = " ".join([s["opcode"]] + s["operands"])
            if len(text) > 60:
                text = text[:57] + "..."
            text = text.replace("|", "/")
            body.append(
                f"| {s['name']} | {s['pc']} | {roles(s['pc'])} | `{text}` | {', '.join(succ)} |"
            )
        body.append("")
        kind_text = ", ".join(f"{k} {n}" for k, n in sorted(kinds.items()))
        summary.append(
            f"| {phase} | {first} | {last} | {len(mine)} | {kind_text} | "
            f"{'; '.join(back) if back else 'none'} |"
        )
    body += entries(flow, by_name)
    out.write_text("\n".join(lines + summary + [""] + body) + "\n", encoding="utf-8")
    print(f"{len(sites)} sites in {len(PHASES)} phases -> {out}")


if __name__ == "__main__":
    main()
